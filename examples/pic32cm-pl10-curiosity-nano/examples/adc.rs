//! `pic32c-hal`'s `adc` on the PL10's ADC (IP 06272), on its inputs inside
//! the chip (the board has nothing analog on its pins):
//!
//! - VDDIO/10 against each internal reference (1.024, 2.048 and 2.5 V):
//!   VDD from each, 3.3 V on the board within 5 % (the references are good
//!   to 4 %), and against VDD itself a tenth of full scale;
//! - the same at 10 and 8 bits: on the 12-bit scale with the low 2 and
//!   4 bits zero, within a step of the 12-bit reading;
//! - the temperature sensor against 2.048 V with the factory's
//!   calibration: 10 to 45 °C on the bench (a sanity check: it reads about
//!   9 °C high there, the driver's known issue);
//! - a read's time, short and long sample times, blocking and async (the
//!   async reads on `ADC0`).
//!
//! Over the virtual COM port; LED0 blinks slowly when all passed, fast on a
//! failure.

#![no_std]
#![no_main]
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;

use embassy_executor::Spawner;
use embassy_time::{Duration, Timer};
use panic_halt as _;
use pic32c_hal::adc::{self, Adc, Calibration, Reference, Resolution, SampleTime, Vddio};
use pic32c_hal::bind_interrupts;
use pic32c_hal::gpio::{Level, Output};
use pic32cm_pl10_curiosity_nano::{Log, micros};

bind_interrupts!(struct Irqs {
    ADC0 => adc::InterruptHandler;
});

/// The board's VDD, set by its debugger.
const VDD_MV: u32 = 3300;

struct Tests<'a> {
    log: &'a mut Log,
    failures: u32,
}

impl Tests<'_> {
    fn check(&mut self, name: &str, good: bool, detail: core::fmt::Arguments<'_>) {
        let _ = writeln!(self.log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        self.failures += u32::from(!good);
    }
}

fn spread(n: u32, mut read: impl FnMut() -> u16) -> (u16, u32, u16) {
    let (mut least, mut most, mut sum) = (u16::MAX, 0, 0u32);
    for _ in 0..n {
        let v = read();
        least = least.min(v);
        most = most.max(v);
        sum += u32::from(v);
    }
    (least, sum / n, most)
}

fn config(reference: Reference, resolution: Resolution) -> adc::Config {
    let mut config = adc::Config::default();
    config.reference = reference;
    config.resolution = resolution;
    config
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let mut p = pic32cm_pl10_curiosity_nano::init();
    let mut log = Log::init(p.SERCOM1, p.PB00, p.PB01);
    let mut led = Output::new(p.PB02, Level::High);
    let _ = writeln!(log, "\npic32cm-pl10-curiosity-nano adc");
    let calibration = Calibration::read();
    let _ = writeln!(log, "TEMPSENSE gain {} offset {}", calibration.gain, calibration.offset);
    let mut t = Tests { log: &mut log, failures: 0 };

    // VDD from VDDIO/10 against each internal reference.
    let mut at_2v048 = 0;
    for reference in [Reference::Internal1V024, Reference::Internal2V048, Reference::Internal2V500] {
        let start = micros();
        let mut adc = Adc::new_blocking(p.ADC.reborrow(), config(reference, Resolution::Bits12)).unwrap();
        let us = micros() - start;
        let mut vddio = adc.enable_vddio();
        // The first conversion after enabling waits out the reference's
        // 40 µs; then 64 for the spread.
        let first = micros();
        let _ = adc.blocking_read(&mut vddio, SampleTime::LONG);
        let first = micros() - first;
        let (least, mean, most) = spread(64, || adc.blocking_read(&mut vddio, SampleTime::LONG));
        let ref_mv = reference.millivolts().unwrap();
        #[expect(clippy::cast_possible_truncation, reason = "a 12-bit mean")]
        let vdd = Vddio::millivolts(mean as u16, ref_mv);
        if reference == Reference::Internal2V048 {
            at_2v048 = mean;
        }
        t.check(
            "VDD",
            most - least <= 12 && vdd.abs_diff(VDD_MV) <= VDD_MV / 20,
            format_args!("{vdd} mV from VDDIO/10 against {ref_mv} mV: {least}..{most}, mean {mean} (set up in {us} us, first read {first} us)"),
        );
    }
    {
        let mut adc = Adc::new_blocking(p.ADC.reborrow(), config(Reference::Avdd, Resolution::Bits12)).unwrap();
        let mut vddio = adc.enable_vddio();
        let (_, mean, _) = spread(64, || adc.blocking_read(&mut vddio, SampleTime::LONG));
        t.check("against VDD", mean.abs_diff(410) <= 20, format_args!("VDDIO/10 reads {mean} of 4096, a tenth is 410"));
    }

    // Resolutions, against 2.048 V.
    for (resolution, shift) in [(Resolution::Bits10, 2), (Resolution::Bits8, 4)] {
        let mut adc = Adc::new_blocking(p.ADC.reborrow(), config(Reference::Internal2V048, resolution)).unwrap();
        let mut vddio = adc.enable_vddio();
        let _ = adc.blocking_read(&mut vddio, SampleTime::LONG);
        let mut low = 0u16;
        let (_, mean, _) = spread(64, || {
            let v = adc.blocking_read(&mut vddio, SampleTime::LONG);
            low |= v & ((1 << shift) - 1);
            v
        });
        let step = 1u32 << shift;
        t.check(
            "resolution",
            low == 0 && mean.abs_diff(at_2v048) <= step,
            format_args!("{} bits: VDDIO/10 mean {mean}, low {shift} bits {low:#x}, 12 bits' {at_2v048}", resolution.bits()),
        );
    }

    // Temperature, and read times, against 2.048 V.
    {
        let mut adc = Adc::new_blocking(p.ADC.reborrow(), config(Reference::Internal2V048, Resolution::Bits12)).unwrap();
        let mut temperature = adc.enable_temperature();
        let _ = adc.blocking_read(&mut temperature, SampleTime::LONG);
        let (least, mean, most) = spread(64, || adc.blocking_read(&mut temperature, SampleTime::LONG));
        #[expect(clippy::cast_possible_truncation, reason = "a 12-bit mean")]
        let tenths = calibration.celsius(mean as u16, 2048);
        t.check("temperature", (100..=450).contains(&tenths), format_args!("{}.{} C from {least}..{most}, mean {mean}", tenths / 10, (tenths % 10).abs()));

        let mut vddio = adc.enable_vddio();
        let mut time_read = |sample: SampleTime| {
            let start = micros();
            for _ in 0..100 {
                let _ = adc.blocking_read(&mut vddio, sample);
            }
            micros() - start
        };
        let short = time_read(SampleTime::SHORT);
        let long = time_read(SampleTime::LONG);
        let _ = writeln!(t.log, "100 reads: {short} us with SHORT, {long} us with LONG (CLK_ADC {} Hz)", adc.clock_hz());
    }

    // Async.
    let mut adc = Adc::new(p.ADC.reborrow(), Irqs, config(Reference::Internal2V048, Resolution::Bits12)).unwrap();
    let mut vddio = adc.enable_vddio();
    let _ = adc.read(&mut vddio, SampleTime::LONG).await;
    let start = micros();
    let mut sum = 0u32;
    for _ in 0..64 {
        sum += u32::from(adc.read(&mut vddio, SampleTime::LONG).await);
    }
    let us = micros() - start;
    let mean = sum / 64;
    t.check("async", mean.abs_diff(at_2v048) <= 4, format_args!("VDDIO/10 mean {mean} over 64 reads in {us} us"));

    let failures = t.failures;
    let _ = if failures == 0 { writeln!(log, "adc: all passed") } else { writeln!(log, "adc: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
