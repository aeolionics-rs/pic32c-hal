//! `pic32c-hal`'s `rtc` on the PL10. The board's 32.768 kHz crystal isn't
//! connected out of the box (its PA24/PA25 go to the edge connector until
//! two straps are cut and two pads bridged: user guide section 7.3), so:
//!
//! - the crystal tried first: on a stock board it must be refused as
//!   `NoCrystal` within a few seconds (a crystal that starts is used);
//! - otherwise the internal OSC32K: set up afresh or found running;
//! - its seconds timed against the time driver's clock (OSCHF, the internal
//!   24 MHz oscillator) over 10 s, in ppm, within the two oscillators'
//!   few percent;
//! - the calendar through 29 February and a new year;
//! - an alarm 3 s ahead, timed;
//! - a system reset request: on the PL10 it clears the RTC (unlike the CK
//!   and the SG00, whose RTC is in the backup domain), so after it the
//!   driver must report the RTC set up afresh, at 2000-01-01, not the
//!   marker time set before.
//!
//! Over the virtual COM port; LED0 blinks slowly when all passed, fast on a
//! failure.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;

use embassy_executor::Spawner;
use embassy_time::{Duration, Timer};
use panic_halt as _;
use pic32c_hal::bind_interrupts;
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::rtc::{self, DateTime, Rtc};
use pic32cm_pl10_curiosity_nano::{Log, micros};

bind_interrupts!(struct Irqs {
    RTC => rtc::InterruptHandler;
});

/// A word of SRAM a system reset keeps (as in `watchdog`): clear of the
/// boot ROM's stack at the bottom of SRAM, of `.bss` and of the stack.
const STAGE: *mut u32 = 0x2000_1C00 as *mut u32;
/// At [`STAGE`] across the reset this program asks for.
const RESET_ASKED: u32 = 0x5254_4352;

fn stage() -> u32 {
    // SAFETY: a word of SRAM nothing else uses; any bit pattern is a u32.
    unsafe { STAGE.read_volatile() }
}

fn set_stage(value: u32) {
    // SAFETY: as above.
    unsafe { STAGE.write_volatile(value) }
}

/// The time set before the reset.
const MARKER: DateTime = match DateTime::new(2030, 6, 15, 12, 0, 0) {
    Ok(t) => t,
    Err(_) => panic!("a valid marker"),
};

struct Tests<'a> {
    log: &'a mut Log,
    failures: u32,
}

impl Tests<'_> {
    fn check(&mut self, name: &str, good: bool, detail: core::fmt::Arguments<'_>) {
        let _ = writeln!(self.log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        self.failures += u32::from(!good);
    }
}

/// Waits for the seconds to change, by polling: the microsecond it did.
fn next_second(rtc: &Rtc<'_>) -> u64 {
    let start = rtc.now();
    while rtc.now() == start {}
    micros()
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32cm_pl10_curiosity_nano::init();
    let mut log = Log::init(p.SERCOM1, p.PB00, p.PB01);
    let mut led = Output::new(p.PB02, Level::High);
    let _ = writeln!(log, "\npic32cm-pl10-curiosity-nano rtc");
    let after_reset = stage() == RESET_ASKED;
    set_stage(0);
    let mut t = Tests { log: &mut log, failures: 0 };
    let mut rtc_peripheral = p.RTC;
    let start = micros();
    let crystal = Rtc::new(rtc_peripheral.reborrow(), Irqs, rtc::Config::default()).map(|rtc| rtc.was_running());
    let us = micros() - start;
    let made = match crystal {
        Ok(was_running) => {
            let _ = writeln!(t.log, "crystal: started (was running {was_running}) in {us} us");
            Rtc::new(rtc_peripheral, Irqs, rtc::Config::default())
        }
        Err(e) => {
            t.check("no crystal", e == rtc::ConfigError::NoCrystal && us < 10_000_000, format_args!("{e:?} after {} ms", us / 1000));
            let mut config = rtc::Config::default();
            config.source = rtc::Source::UltraLowPower;
            Rtc::new(rtc_peripheral, Irqs, config)
        }
    };
    let us = micros() - start;
    let Ok(mut rtc) = made else {
        t.check("RTC", false, format_args!("not set up ({made:?})", made = made.err()));
        loop {
            Timer::after(Duration::from_secs(1)).await;
        }
    };
    let now = rtc.now();

    // After the reset this program asks for: the RTC cleared by it.
    if after_reset {
        let fresh = !rtc.was_running() && now.to_unix() < DateTime::MIN.to_unix() + 10;
        t.check(
            "after a system reset",
            fresh,
            format_args!("RTC {} at {now} (the marker was {MARKER})", if rtc.was_running() { "found running" } else { "set up afresh" }),
        );
    } else {
        let _ = writeln!(t.log, "RTC {} in {us} us, at {now}", if rtc.was_running() { "found running" } else { "set up afresh" });

        // The seconds against OSCHF over 10 s.
        let first = next_second(&rtc);
        let mut last = first;
        for _ in 0..10 {
            last = next_second(&rtc);
        }
        let elapsed = last - first;
        #[expect(clippy::cast_possible_wrap, reason = "about ten seconds in microseconds")]
        let ppm = (elapsed as i64 - 10_000_000) / 10;
        t.check("rate", ppm.abs() < 50_000, format_args!("10 s in {elapsed} us: {ppm} ppm against OSCHF"));

        // The calendar through 29 February and a new year.
        for (set, expected) in [
            (DateTime::new(2024, 2, 28, 23, 59, 58), DateTime::new(2024, 2, 29, 0, 0, 0)),
            (DateTime::new(2025, 12, 31, 23, 59, 58), DateTime::new(2026, 1, 1, 0, 0, 0)),
        ] {
            let (set, expected) = (set.unwrap(), expected.unwrap());
            rtc.set(set);
            let back = rtc.now();
            Timer::after(Duration::from_millis(2500)).await;
            let later = rtc.now();
            t.check("calendar", back == set && later >= expected && later.to_unix() <= expected.to_unix() + 1, format_args!("set {set}, read {back}, 2.5 s later {later}"));
        }

        // An alarm 3 s ahead.
        let at = DateTime::from_unix(rtc.now().to_unix() + 3).unwrap();
        let start = micros();
        rtc.wait_until(at).await;
        let us = micros() - start;
        t.check("alarm", (2_000_000..=3_100_000).contains(&us) && rtc.now() >= at, format_args!("{at} came after {us} us"));

        // The reset: the marker, then the chip reset by software.
        if t.failures == 0 {
            rtc.set(MARKER);
            let _ = writeln!(t.log, "marker {MARKER} set; resetting");
            Timer::after(Duration::from_millis(1500)).await;
            set_stage(RESET_ASKED);
            cortex_m::peripheral::SCB::sys_reset();
        }
    }

    let failures = t.failures;
    let _ = if failures == 0 { writeln!(log, "rtc: all passed") } else { writeln!(log, "rtc: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
