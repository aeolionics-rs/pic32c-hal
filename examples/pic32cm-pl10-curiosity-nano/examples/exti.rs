//! `pic32c-hal`'s `exti` on the PL10 (one EIC vector for all 16 lines),
//! with two jumpers: PA08 to PA09 and PA10 to PA11, each pair an output
//! driving an EIC input (EXTINT9, EXTINT11). The PL10's internal pull is
//! off while the EIC has a pin, so a bare pin can't make edges; and these
//! pins are clear of the board's SPI, I2C and virtual COM port pins.
//!
//! - each jumper found, by toggling its output;
//! - on each pair, every wait (rising, falling, any edge, high, low) must
//!   end soon after the edge that meets it, and not before; a level already
//!   met ends at once; then a hundred alternate edges, each awaited;
//! - both lines at once on the one vector: both inputs waited together,
//!   both outputs raised together, both waits must end;
//! - SW0 (PB03, EXTINT3): reported, not checked. It has no pull-up but the
//!   PORT's, which the EIC's function turns off, so through the EIC it
//!   floats while released.
//!
//! Results go out over the virtual COM port; LED0 blinks slowly when all
//! passed, fast on a failure.

#![no_std]
#![no_main]
// Embassy's main macro passes `_spawner` on to the task it generates, where
// an attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;
use core::future::Future;

use embassy_executor::Spawner;
use embassy_futures::join::join;
use embassy_futures::select::{Either, select};
use embassy_time::{Duration, Timer, with_timeout};
use panic_halt as _;
use pic32c_hal::exti::ExtiInput;
use pic32c_hal::gpio::{Input, Level, Output, Pull};
use pic32c_hal::{Peri, gpio};
use pic32cm_pl10_curiosity_nano::{Log, micros};

/// PORT's OUTCLR and OUTSET (its one group).
const OUTCLR: usize = 0x4100_0014;
const OUTSET: usize = 0x4100_0018;
const PA08: u32 = 1 << 8;
const PA10: u32 = 1 << 10;
/// Long enough for a jumpered input to follow its output.
const SETTLE: Duration = Duration::from_micros(200);

fn set(address: usize, bits: u32) {
    // SAFETY: PORT's OUTSET or OUTCLR: only the bits given change.
    unsafe { core::ptr::write_volatile(address as *mut u32, bits) }
}

/// The outputs driven behind their `Output`s' backs, for exact timing.
fn pa08_high() {
    set(OUTSET, PA08);
}
fn pa08_low() {
    set(OUTCLR, PA08);
}
fn pa10_high() {
    set(OUTSET, PA10);
}
fn pa10_low() {
    set(OUTCLR, PA10);
}

/// Whether `output` drives `input`: low, then high, follows.
async fn jumpered(output: Peri<'_, impl gpio::Pin>, input: Peri<'_, impl gpio::Pin>) -> bool {
    let mut out = Output::new(output, Level::Low);
    let input = Input::new(input, Pull::None);
    Timer::after(SETTLE).await;
    let low = input.is_low();
    out.set_high();
    Timer::after(SETTLE).await;
    low && input.is_high()
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let mut p = pic32cm_pl10_curiosity_nano::init();
    let mut log = Log::init(p.SERCOM1, p.PB00, p.PB01);
    let led0 = Output::new(p.PB02, Level::High);
    let _ = writeln!(log, "\npic32cm-pl10-curiosity-nano exti");
    let mut failures = 0;

    let first = jumpered(p.PA08.reborrow(), p.PA09.reborrow()).await;
    let second = jumpered(p.PA10.reborrow(), p.PA11.reborrow()).await;
    let _ = writeln!(log, "PA08 to PA09 jumper: {}; PA10 to PA11 jumper: {}", if first { "yes" } else { "no" }, if second { "yes" } else { "no" });
    failures += u32::from(!first) + u32::from(!second);

    if first {
        let _ = writeln!(log, "PA08 into PA09 (EXTINT9):");
        let _out = Output::new(p.PA08.reborrow(), Level::Low);
        let mut pin = ExtiInput::new(p.PA09.reborrow(), p.EXTINT9.reborrow(), Pull::None);
        Timer::after(SETTLE).await;
        failures += edges(&mut log, &mut pin, pa08_high, pa08_low).await;
    }
    if second {
        let _ = writeln!(log, "PA10 into PA11 (EXTINT11):");
        let _out = Output::new(p.PA10.reborrow(), Level::Low);
        let mut pin = ExtiInput::new(p.PA11.reborrow(), p.EXTINT11.reborrow(), Pull::None);
        Timer::after(SETTLE).await;
        failures += edges(&mut log, &mut pin, pa10_high, pa10_low).await;
    }
    if first && second {
        // Two lines on the one vector, rising together; then each alone,
        // the other's wait left pending.
        let _out8 = Output::new(p.PA08.reborrow(), Level::Low);
        let _out10 = Output::new(p.PA10.reborrow(), Level::Low);
        let mut a = ExtiInput::new(p.PA09.reborrow(), p.EXTINT9.reborrow(), Pull::None);
        let mut b = ExtiInput::new(p.PA11.reborrow(), p.EXTINT11.reborrow(), Pull::None);
        Timer::after(SETTLE).await;
        let flip = async {
            Timer::after(Duration::from_millis(5)).await;
            set(OUTSET, PA08 | PA10);
            Timer::after(Duration::from_millis(20)).await;
        };
        let both = matches!(select(join(a.wait_for_rising_edge(), b.wait_for_rising_edge()), flip).await, Either::First(_));
        let _ = writeln!(log, "both lines at once: {}", if both { "both woke" } else { "NOT both woken" });
        failures += u32::from(!both);
        // PA09 falls; PA11's falling-edge wait must not end with it.
        let flip = async {
            Timer::after(Duration::from_millis(5)).await;
            pa08_low();
            Timer::after(Duration::from_millis(20)).await;
        };
        let (woke_a, woke_b) = match select(join(a.wait_for_falling_edge(), with_timeout(Duration::from_millis(15), b.wait_for_falling_edge())), flip).await {
            Either::First(((), b)) => (true, b.is_ok()),
            Either::Second(()) => (false, false),
        };
        let _ = writeln!(log, "one line of two: PA09 {}, PA11 {}", if woke_a { "woke" } else { "NOT woken" }, if woke_b { "WOKE TOO" } else { "left waiting" });
        failures += u32::from(!woke_a || woke_b);
    }

    // SW0, floating while released (reported, not checked).
    let mut sw0 = ExtiInput::new(p.PB03, p.EXTINT3, Pull::Up);
    Timer::after(SETTLE).await;
    let _ = writeln!(log, "SW0 reads {:?} (floating while released); press it within 10 s", sw0.get_level());
    match with_timeout(Duration::from_secs(10), sw0.wait_for_falling_edge()).await {
        Ok(()) => {
            let pressed = micros();
            let released = with_timeout(Duration::from_secs(10), sw0.wait_for_rising_edge()).await.is_ok();
            let _ = writeln!(log, "SW0 pressed, {} {} ms", if released { "released after" } else { "not released within 10 s of" }, (micros() - pressed) / 1000);
        }
        Err(_) => {
            let _ = writeln!(log, "SW0 not pressed (not a failure)");
        }
    }

    if failures == 0 {
        let _ = writeln!(log, "exti: all passed");
    } else {
        let _ = writeln!(log, "exti: {failures} failures");
    }
    halt(&mut log, failures, led0).await;
}

/// Every kind of wait on `pin`, which `high` and `low` move.
async fn edges(log: &mut Log, pin: &mut ExtiInput<'_>, high: fn(), low: fn()) -> u32 {
    let mut failures = 0;
    failures += edge(log, "rising edge", pin.wait_for_rising_edge(), high).await;
    failures += edge(log, "falling edge", pin.wait_for_falling_edge(), low).await;
    failures += edge(log, "any edge (rising)", pin.wait_for_any_edge(), high).await;
    failures += edge(log, "any edge (falling)", pin.wait_for_any_edge(), low).await;
    failures += edge(log, "high", pin.wait_for_high(), high).await;
    failures += edge(log, "low", pin.wait_for_low(), low).await;
    // Already there: a level wait ends at once.
    let immediate = with_timeout(Duration::from_millis(10), pin.wait_for_low()).await.is_ok();
    let _ = writeln!(log, "  low while low: {}", if immediate { "at once" } else { "NOT at once" });
    failures += u32::from(!immediate);
    // A hundred edges back to back, each awaited.
    let mut missed = 0;
    for n in 0..100 {
        let caught = if n % 2 == 0 { caught(pin.wait_for_rising_edge(), high).await } else { caught(pin.wait_for_falling_edge(), low).await };
        missed += u32::from(!caught);
    }
    let _ = writeln!(log, "  100 alternate edges: {missed} missed");
    failures + u32::from(missed != 0)
}

/// `wait` mustn't end before `flip`, and must end within 10 ms after.
async fn edge(log: &mut Log, name: &str, wait: impl Future<Output = ()>, flip: fn()) -> u32 {
    let mut flipped_at = 0;
    let flipper = async {
        Timer::after(Duration::from_millis(5)).await;
        flipped_at = micros();
        flip();
        Timer::after(Duration::from_millis(10)).await;
    };
    match select(wait, flipper).await {
        Either::First(()) if flipped_at != 0 => {
            let latency = micros() - flipped_at;
            let _ = writeln!(log, "  {name}: woke {latency} µs after the flip");
            0
        }
        Either::First(()) => {
            let _ = writeln!(log, "  {name}: woke BEFORE the flip");
            1
        }
        Either::Second(()) => {
            let _ = writeln!(log, "  {name}: NOT woken within 10 ms of the flip");
            1
        }
    }
}

/// Whether `wait` ends within 20 ms of `flip`, 100 µs in.
async fn caught(wait: impl Future<Output = ()>, flip: fn()) -> bool {
    let flipped = async {
        Timer::after(Duration::from_micros(100)).await;
        flip();
        Timer::after(Duration::from_millis(20)).await;
    };
    matches!(select(wait, flipped).await, Either::First(()))
}

async fn halt(log: &mut Log, failures: u32, mut led: Output<'static>) -> ! {
    log.flush();
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
