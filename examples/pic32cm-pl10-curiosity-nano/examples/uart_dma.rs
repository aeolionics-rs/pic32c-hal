//! Echoes the virtual COM port (SERCOM1, PB00/PB01) by DMA: a `Uart` with
//! DMA channels 0 (receive) and 1 (transmit) reads 256-byte blocks, each a
//! single DMA transfer paced by the SERCOM's receive request, and writes
//! each back as one transfer paced by its transmit request. Send it a block
//! at a time, each after the last one's echo: while it writes a block it
//! reads nothing, and SERCOM v1 holds only a byte or two, so a stream
//! overruns it (`uart_ring` takes a stream): `tools/host/uart_dma_test.py`
//! does. LED0 toggles with each block.
//! 115,200 baud unless `UART_BAUD` says otherwise when building. The banner
//! goes out on a blocking `Uart` first, dropped while still enabled, so the
//! DMA one takes over a SERCOM that's running.

#![no_std]
#![no_main]
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use embassy_executor::Spawner;
use panic_halt as _;
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::uart::{self, Uart};
use pic32c_hal::{bind_interrupts, peripherals};

bind_interrupts!(struct Irqs {
    SERCOM1 => uart::InterruptHandler<peripherals::SERCOM1>;
});

const BLOCK: usize = 256;

/// `UART_BAUD` when building, else 115,200.
const BAUD: u32 = match option_env!("UART_BAUD") {
    Some(value) => parse(value.as_bytes()),
    None => 115_200,
};

const fn parse(digits: &[u8]) -> u32 {
    let mut value = 0;
    let mut i = 0;
    while i < digits.len() {
        assert!(digits[i].is_ascii_digit(), "UART_BAUD is a number");
        value = value * 10 + (digits[i] - b'0') as u32;
        i += 1;
    }
    value
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let mut p = pic32cm_pl10_curiosity_nano::init();
    let mut led = Output::new(p.PB02, Level::High);
    let mut config = uart::Config::default();
    config.baudrate = BAUD;
    // The banner from a blocking UART on the same SERCOM, dropped still
    // enabled: the DMA one's setup must reset it from there.
    {
        let mut banner = Uart::new_blocking(p.SERCOM1.reborrow(), p.PB00.reborrow(), p.PB01.reborrow(), config).unwrap();
        banner.blocking_write(b"\r\npic32cm-pl10-curiosity-nano uart_dma\r\n");
        banner.blocking_flush();
    }
    let mut uart = Uart::new(p.SERCOM1, p.PB00, p.PB01, Irqs, p.DMA_CH1, p.DMA_CH0, config).unwrap();
    let _ = uart.write(b"uart_dma: ready\r\n").await;
    let mut block = [0u8; BLOCK];
    loop {
        // A receive error comes after the block, which is still echoed.
        let _ = uart.read(&mut block).await;
        let _ = uart.write(&block).await;
        led.toggle();
    }
}
