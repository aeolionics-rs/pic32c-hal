//! `pic32c-hal`'s `OutputOpenDrain` on the PL10, whose PORT has no open
//! drain (the HAL switches the pin's direction instead), with the jumper
//! from PA10 to PA11 that `exti` uses.
//!
//! - the jumper found, by toggling PA10 push-pull;
//! - PA10 open drain without a pull, PA11 an input with the pull-up: driven
//!   low the line reads low at both ends; let go, PA11's pull-up takes it
//!   high (its rise time reported, in CPU cycles);
//! - PA10 never drives high: the line taken low by PA11, then left
//!   floating (the PL10's PORT has no pull-down), stays low while PA10 lets
//!   go;
//! - both ends open drain, PA10 with the PORT's pull-up: the line is high
//!   only while both let go, and either end reads what the other drives;
//! - `toggle` alternates, and `is_set_high` follows;
//! - a dropped pin goes back to its reset state (DIR, OUT and PINCFG 0);
//! - square waves on PA10 through the pull-up, for the edge rate reported.
//!
//! Results go out over the virtual COM port; the LED blinks slowly when all
//! passed, fast on a failure.

#![no_std]
#![no_main]
// Embassy's main macro passes `_spawner` on to the task it generates, where
// an attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;

use cortex_m::peripheral::SYST;
use cortex_m::peripheral::syst::SystClkSource;
use embassy_executor::Spawner;
use embassy_time::{Duration, Timer};
use panic_halt as _;
use pic32c_hal::gpio::{Input, Level, Output, OutputOpenDrain, Pull};
use pic32c_hal::{Peri, gpio};
use pic32cm_pl10_curiosity_nano::Log;

/// PORT group A's DIR, OUT and PINCFG10.
const DIR: usize = 0x4100_0000;
const OUT: usize = 0x4100_0010;
const PINCFG10: usize = 0x4100_0040 + 10;
const PA10: u32 = 1 << 10;
/// Long enough for the line to follow through the PORT's pull.
const SETTLE: Duration = Duration::from_micros(200);

/// `SysTick` counting CPU cycles, down from 2^24 - 1, free-running.
fn start_cycles(mut syst: SYST) {
    syst.set_clock_source(SystClkSource::Core);
    syst.set_reload(0x00FF_FFFF);
    syst.clear_current();
    syst.enable_counter();
}

fn cycles() -> u32 {
    SYST::get_current()
}

fn since(start: u32) -> u32 {
    start.wrapping_sub(cycles()) & 0x00FF_FFFF
}

fn verdict(good: bool) -> &'static str {
    if good { "" } else { ", WRONG" }
}

fn read32(address: usize) -> u32 {
    // SAFETY: a PORT register, read whole.
    unsafe { core::ptr::read_volatile(address as *const u32) }
}

fn read8(address: usize) -> u8 {
    // SAFETY: a PINCFG byte.
    unsafe { core::ptr::read_volatile(address as *const u8) }
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32cm_pl10_curiosity_nano::init();
    let mut log = Log::init(p.SERCOM1, p.PB00, p.PB01);
    // LED0 is active low.
    let led = Output::new(p.PB02, Level::High);
    start_cycles(cortex_m::Peripherals::take().unwrap().SYST);
    let cpu = pic32c_hal::clocks::frequencies().map_or(0, |f| f.cpu());
    let _ = writeln!(log, "\npic32cm-pl10-curiosity-nano open_drain, CPU {cpu} Hz");

    let mut pa10 = p.PA10;
    let mut pa11 = p.PA11;
    let mut failures = 0;

    let found = jumpered(pa10.reborrow(), pa11.reborrow()).await;
    let _ = writeln!(log, "jumper PA10-PA11: {}", if found { "found" } else { "NOT FOUND" });
    if !found {
        halt(&mut log, 1, led).await;
    }

    failures += against_pull_up(&mut log, pa10.reborrow(), pa11.reborrow()).await;
    failures += never_drives_high(&mut log, pa10.reborrow(), pa11.reborrow()).await;
    failures += wired_and(&mut log, pa10.reborrow(), pa11.reborrow()).await;
    failures += toggles(&mut log, pa10.reborrow(), pa11.reborrow()).await;
    failures += reset_on_drop(&mut log, pa10.reborrow());
    square_wave(&mut log, pa10.reborrow(), pa11.reborrow(), cpu);

    if failures == 0 {
        let _ = writeln!(log, "open_drain: all passed");
    } else {
        let _ = writeln!(log, "open_drain: {failures} failures");
    }
    halt(&mut log, failures, led).await;
}

async fn halt(log: &mut Log, failures: u32, mut led: Output<'static>) -> ! {
    log.flush();
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}

async fn jumpered(output: Peri<'_, impl gpio::Pin>, input: Peri<'_, impl gpio::Pin>) -> bool {
    let mut out = Output::new(output, Level::Low);
    let input = Input::new(input, Pull::None);
    Timer::after(SETTLE).await;
    let low = input.is_low();
    out.set_high();
    Timer::after(SETTLE).await;
    low && input.is_high()
}

/// Driven low, both ends read low; let go, the far end's pull-up takes the
/// line high.
async fn against_pull_up(log: &mut Log, a: Peri<'_, impl gpio::Pin>, b: Peri<'_, impl gpio::Pin>) -> u32 {
    let b = Input::new(b, Pull::Up);
    let mut a = OutputOpenDrain::new(a, Level::Low);
    Timer::after(SETTLE).await;
    let low = a.is_low() && b.is_low() && a.is_set_low();
    let start = cycles();
    a.set_high();
    let mut rise = None;
    while since(start) < 100_000 {
        if b.is_high() {
            rise = Some(since(start));
            break;
        }
    }
    Timer::after(SETTLE).await;
    let high = a.is_high() && b.is_high() && a.is_set_high();
    let good = low && high && rise.is_some();
    let _ = writeln!(log, "PA10 open drain, PA11 pull-up: driven low reads low {low}, let go reads high {high}, rise {rise:?} cycles{}", verdict(good));
    u32::from(!good)
}

/// Let go, the pin doesn't drive: the line, taken low by the far end and
/// then left floating, stays low (its own charge holds it for far longer
/// than this waits).
async fn never_drives_high(log: &mut Log, a: Peri<'_, impl gpio::Pin>, mut b: Peri<'_, impl gpio::Pin>) -> u32 {
    let mut a = OutputOpenDrain::new(a, Level::High);
    let mut results = [false; 2];
    for (i, result) in results.iter_mut().enumerate() {
        {
            let _low = Output::new(b.reborrow(), Level::Low);
            Timer::after(SETTLE).await;
        }
        let input = Input::new(b.reborrow(), Pull::None);
        if i == 1 {
            a.set_low();
            a.set_high();
        }
        Timer::after(SETTLE).await;
        *result = input.is_low() && a.is_set_high();
    }
    let good = results == [true, true];
    let _ = writeln!(log, "PA10 let go, line taken low then floating: low {}, after PA10 low then let go low {}{}", results[0], results[1], verdict(good));
    u32::from(!good)
}

/// Both ends open drain, PA10 with the pull-up: high only while both let go.
async fn wired_and(log: &mut Log, a: Peri<'_, impl gpio::Pin>, b: Peri<'_, impl gpio::Pin>) -> u32 {
    let mut a = OutputOpenDrain::new_with_pull_up(a, Level::High);
    let mut b = OutputOpenDrain::new(b, Level::High);
    let mut seen = [(false, false); 4];
    for (i, (a_level, b_level)) in [(Level::High, Level::High), (Level::High, Level::Low), (Level::Low, Level::High), (Level::Low, Level::Low)].into_iter().enumerate() {
        a.set_level(a_level);
        b.set_level(b_level);
        Timer::after(SETTLE).await;
        seen[i] = (a.is_high(), b.is_high());
    }
    a.set_high();
    b.set_high();
    Timer::after(SETTLE).await;
    let released = a.is_high() && b.is_high();
    let good = seen == [(true, true), (false, false), (false, false), (false, false)] && released;
    let _ = writeln!(log, "both open drain, PA10 pull-up: (PA10, PA11) read for HH, HL, LH, LL {seen:?}, both let go again high {released}{}", verdict(good));
    u32::from(!good)
}

/// `toggle` alternates the line, and `is_set_high` follows.
async fn toggles(log: &mut Log, a: Peri<'_, impl gpio::Pin>, b: Peri<'_, impl gpio::Pin>) -> u32 {
    let mut a = OutputOpenDrain::new_with_pull_up(a, Level::High);
    let b = Input::new(b, Pull::None);
    let mut seen = [(false, false); 4];
    for (i, entry) in seen.iter_mut().enumerate() {
        if i > 0 {
            a.toggle();
        }
        Timer::after(SETTLE).await;
        *entry = (b.is_high(), a.is_set_high());
    }
    let good = seen == [(true, true), (false, false), (true, true), (false, false)];
    let _ = writeln!(log, "PA10 pull-up, toggled three times: (PA11, set high) {seen:?}{}", verdict(good));
    u32::from(!good)
}

/// A dropped pin goes back to its reset state.
fn reset_on_drop(log: &mut Log, a: Peri<'_, impl gpio::Pin>) -> u32 {
    let a = OutputOpenDrain::new_with_pull_up(a, Level::Low);
    let held = (read32(DIR) & PA10 != 0, read32(OUT) & PA10 != 0, read8(PINCFG10));
    drop(a);
    let dropped = (read32(DIR) & PA10 != 0, read32(OUT) & PA10 != 0, read8(PINCFG10));
    let good = held == (true, false, 0b110) && dropped == (false, false, 0);
    let _ = writeln!(log, "PA10 (DIR, OUT, PINCFG) driven low with pull-up {held:?}, dropped {dropped:?}{}", verdict(good));
    u32::from(!good)
}

/// Square waves through the pull-up, each edge awaited at PA11: reported.
fn square_wave(log: &mut Log, a: Peri<'_, impl gpio::Pin>, b: Peri<'_, impl gpio::Pin>, cpu: u32) {
    const PERIODS: u32 = 1000;
    let mut a = OutputOpenDrain::new_with_pull_up(a, Level::High);
    let b = Input::new(b, Pull::None);
    let start = cycles();
    for _ in 0..PERIODS {
        a.set_low();
        while b.is_high() {}
        a.set_high();
        while b.is_low() {}
    }
    let elapsed = since(start);
    let khz = u64::from(cpu) * u64::from(PERIODS) / u64::from(elapsed.max(1)) / 1000;
    let _ = writeln!(log, "square wave through the pull-up: {PERIODS} periods in {elapsed} cycles, {khz} kHz");
}
