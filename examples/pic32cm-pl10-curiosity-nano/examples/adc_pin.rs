//! `pic32c-hal`'s `adc` on a pin: PA03 (AIN3, the board's edge connector),
//! for a voltage source wired to it (0 V to VDD; share the ground). Every
//! 50 ms a line of `name=value` fields goes out over the virtual COM port,
//! each the mean of 16 12-bit reads:
//!
//! - `vdd`: against VDD;
//! - `int2v048`: against the internal 2.048 V reference (4,095 above it);
//! - `vddio_mv`: VDD in mV, from VDDIO/10 against the internal 1.024 V
//!   reference, to scale `vdd` by.
//!
//! A host stepping the source can fit these against what it set. LED0
//! toggles with each line.

#![no_std]
#![no_main]
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;

use embassy_executor::Spawner;
use embassy_time::{Duration, Ticker};
use panic_halt as _;
use pic32c_hal::adc::{self, Adc, Reference, SampleTime, Vddio};
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::{Peri, peripherals};
use pic32cm_pl10_curiosity_nano::Log;

/// The mean of 16 reads of PA03 against `reference`.
fn mean(adc: Peri<'_, peripherals::ADC>, pin: &mut Peri<'_, peripherals::PA03>, reference: Reference) -> u32 {
    let mut config = adc::Config::default();
    config.reference = reference;
    let mut adc = Adc::new_blocking(adc, config).unwrap();
    // The first read after enabling waits out an internal reference.
    let _ = adc.blocking_read(pin, SampleTime::LONG);
    (0..16).map(|_| u32::from(adc.blocking_read(pin, SampleTime::LONG))).sum::<u32>() / 16
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let mut p = pic32cm_pl10_curiosity_nano::init();
    let mut log = Log::init(p.SERCOM1, p.PB00, p.PB01);
    let mut led = Output::new(p.PB02, Level::High);
    let _ = writeln!(log, "\npic32cm-pl10-curiosity-nano adc_pin: PA03 (AIN3)");
    let mut ticker = Ticker::every(Duration::from_millis(50));
    loop {
        let vdd = mean(p.ADC.reborrow(), &mut p.PA03, Reference::Avdd);
        let int = mean(p.ADC.reborrow(), &mut p.PA03, Reference::Internal2V048);
        let vddio_mv = {
            let mut config = adc::Config::default();
            config.reference = Reference::Internal1V024;
            let mut adc = Adc::new_blocking(p.ADC.reborrow(), config).unwrap();
            let mut vddio = adc.enable_vddio();
            let _ = adc.blocking_read(&mut vddio, SampleTime::LONG);
            let counts = (0..16).map(|_| u32::from(adc.blocking_read(&mut vddio, SampleTime::LONG))).sum::<u32>() / 16;
            #[expect(clippy::cast_possible_truncation, reason = "a 12-bit mean")]
            Vddio::millivolts(counts as u16, 1024)
        };
        let _ = writeln!(log, "vdd={vdd} int2v048={int} vddio_mv={vddio_mv}");
        led.toggle();
        ticker.next().await;
    }
}
