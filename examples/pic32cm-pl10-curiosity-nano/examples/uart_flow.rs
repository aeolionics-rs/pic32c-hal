//! `pic32c-hal`'s UART hardware flow control (RTS/CTS) on the PL10, against
//! an echo that drains slowly: SERCOM0 (function C: TX PA04 pad 0, RX PA05
//! pad 1, RTS PA06 pad 2, CTS PA07 pad 3) at 1 Mbaud to `uart_peer` on a
//! Curiosity Ultra (its EXT2: TX pin 16, RX pin 18, RTS pin 17, CTS pin 6),
//! crossed (TX to RX, RTS to CTS, both ways), with GND. Start `uart_peer`
//! first. The CK board's `uart_flow`, sized for 8 KB of SRAM: the pattern
//! is made 512 bytes at a time and the echo checked as it comes.
//!
//! - CTS: 6 KiB sent at once, more than `uart_peer`'s 2 KiB receive ring
//!   holds at its half-rate drain, the echo read meanwhile. Its full ring
//!   leaves bytes in its SERCOM, whose RTS stops this board's transmitter:
//!   every byte must come back, and CTS must be seen holding.
//! - RTS: 2 KiB sent, then nothing read for 200 ms while the echo comes
//!   back: this board's RTS must stop `uart_peer`, so a late read still gets
//!   every byte, and the receiver no overflow.
//!
//! Each runs again without flow control (`Uart::new`, PA06 driven low so
//! `uart_peer` always may send), where bytes should be lost: the control.
//! Then the same with a `BufferedUart` and 256-byte rings. Over the virtual
//! COM port; LED0 blinks slowly when all passed, fast on a failure.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;
use core::ptr::{read_volatile, write_volatile};

use embassy_executor::Spawner;
use embassy_futures::join::join;
use embassy_futures::select::{Either, select};
use embassy_time::{Duration, Timer};
use panic_halt as _;
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::mode::Async;
use pic32c_hal::uart::{self, BufferedUart, BufferedUartRx, BufferedUartTx, Uart, UartRx, UartTx};
use pic32c_hal::{Peri, bind_interrupts, peripherals};
use pic32cm_pl10_curiosity_nano::{Log, micros};

bind_interrupts!(struct Irqs {
    SERCOM0 => uart::InterruptHandler<peripherals::SERCOM0>;
});

const SERCOM0_BASE: usize = 0x4200_0400;
const STATUS: usize = SERCOM0_BASE + 0x1A;
const BUFOVF: u16 = 1 << 2;
const CTS: u16 = 1 << 3;
/// Bytes in the CTS burst and the RTS test.
const BURST: usize = 6144;
const HELD: usize = 2048;
/// The pattern made, and the echo checked, this many bytes at a time.
const CHUNK: usize = 512;
/// The `BufferedUart`'s rings.
const RING: usize = 256;

#[expect(non_snake_case, reason = "named as the peripherals")]
struct Parts {
    SERCOM0: Peri<'static, peripherals::SERCOM0>,
    PA04: Peri<'static, peripherals::PA04>,
    PA05: Peri<'static, peripherals::PA05>,
    PA06: Peri<'static, peripherals::PA06>,
    PA07: Peri<'static, peripherals::PA07>,
    DMA_CH0: Peri<'static, peripherals::DMA_CH0>,
    DMA_CH1: Peri<'static, peripherals::DMA_CH1>,
}

struct Tests<'a> {
    log: &'a mut Log,
    failures: u32,
}

impl Tests<'_> {
    fn check(&mut self, name: &str, good: bool, detail: core::fmt::Arguments<'_>) {
        let _ = writeln!(self.log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        self.failures += u32::from(!good);
    }
}

/// Byte `i` of the pattern.
#[expect(clippy::cast_possible_truncation, reason = "a pattern")]
fn pattern(i: usize) -> u8 {
    (i * 13 + i / 256) as u8
}

/// The pattern's bytes `at..at + chunk.len()`, into `chunk`.
fn fill(chunk: &mut [u8], at: usize) {
    for (i, b) in chunk.iter_mut().enumerate() {
        *b = pattern(at + i);
    }
}

fn overflowed() -> bool {
    // SAFETY: SERCOM0's STATUS, read and its BUFOVF cleared.
    unsafe {
        let status = read_volatile(STATUS as *const u16);
        write_volatile(STATUS as *mut u16, status & BUFOVF);
        status & BUFOVF != 0
    }
}

/// CTS as the SERCOM sees it: STATUS.CTS clear.
fn tx_clear() -> bool {
    // SAFETY: SERCOM0's STATUS, read only.
    unsafe { read_volatile(STATUS as *const u16) & CTS == 0 }
}

/// Sends the pattern's first `n` bytes by DMA, a chunk at a time, counting
/// how often CTS is seen holding: (µs, holds).
async fn send_dma(tx: &mut UartTx<'_, Async>, n: usize) -> (u64, u32) {
    let start = micros();
    let mut held = 0u32;
    let send = async {
        let mut chunk = [0u8; CHUNK];
        for at in (0..n).step_by(CHUNK) {
            let len = CHUNK.min(n - at);
            fill(&mut chunk[..len], at);
            let _ = tx.write(&chunk[..len]).await;
        }
    };
    let watch = async {
        loop {
            if !tx_clear() {
                held += 1;
            }
            Timer::after(Duration::from_micros(200)).await;
        }
    };
    let _ = select(send, watch).await;
    (micros() - start, held)
}

/// Reads `n` bytes by DMA, a chunk at a time, within `limit` all told: how
/// many matched the pattern.
async fn read_dma(rx: &mut UartRx<'_, Async>, n: usize, limit: Duration) -> usize {
    let mut good = 0;
    let read = async {
        let mut chunk = [0u8; CHUNK];
        for at in (0..n).step_by(CHUNK) {
            let len = CHUNK.min(n - at);
            chunk[..len].fill(0);
            // Receive errors are the overflow check's (and the controls').
            let _ = rx.read(&mut chunk[..len]).await;
            good += chunk[..len].iter().enumerate().filter(|&(i, &b)| b == pattern(at + i)).count();
        }
    };
    let _ = select(read, Timer::after(limit)).await;
    good
}

/// Reads whatever comes until 20 ms pass with nothing.
async fn drain_dma(rx: &mut UartRx<'_, Async>) {
    let mut scratch = [0u8; 1];
    while matches!(select(rx.read(&mut scratch), Timer::after(Duration::from_millis(20))).await, Either::First(_)) {}
}

async fn drain_buffered(rx: &mut BufferedUartRx<'_>) {
    let mut scratch = [0u8; 64];
    while matches!(select(rx.read(&mut scratch), Timer::after(Duration::from_millis(20))).await, Either::First(_)) {}
}

/// Sends the pattern's first `n` bytes through a `BufferedUart`.
async fn send_buffered(tx: &mut BufferedUartTx<'_>, n: usize) -> bool {
    let mut chunk = [0u8; CHUNK];
    for at in (0..n).step_by(CHUNK) {
        let len = CHUNK.min(n - at);
        fill(&mut chunk[..len], at);
        if tx.write_all(&chunk[..len]).await.is_err() {
            return false;
        }
    }
    true
}

/// Reads `n` bytes through a `BufferedUart` within `limit`: (matched,
/// overrun seen).
async fn read_buffered(rx: &mut BufferedUartRx<'_>, n: usize, limit: Duration) -> (usize, bool) {
    let mut good = 0;
    let mut overrun = false;
    let read = async {
        let mut chunk = [0u8; 64];
        let mut at = 0;
        while at < n {
            let len = chunk.len().min(n - at);
            match rx.read(&mut chunk[..len]).await {
                Ok(got) => {
                    good += chunk[..got].iter().enumerate().filter(|&(i, &b)| b == pattern(at + i)).count();
                    at += got;
                }
                Err(uart::Error::Overrun) => overrun = true,
                Err(_) => {}
            }
        }
    };
    let _ = select(read, Timer::after(limit)).await;
    (good, overrun)
}

async fn tests(p: &mut Parts, t: &mut Tests<'_>) {
    let mut config = uart::Config::default();
    config.baudrate = 1_000_000;

    for flow in [true, false] {
        let name = if flow { "with RTS/CTS" } else { "without (control)" };
        // The control drives `uart_peer`'s CTS low by hand, so it always sends.
        let (mut tx, mut rx, rts) = if flow {
            let uart = Uart::new_with_rtscts(
                p.SERCOM0.reborrow(),
                p.PA04.reborrow(),
                p.PA05.reborrow(),
                p.PA06.reborrow(),
                p.PA07.reborrow(),
                Irqs,
                p.DMA_CH1.reborrow(),
                p.DMA_CH0.reborrow(),
                config,
            )
            .unwrap();
            let (tx, rx) = uart.split();
            (tx, rx, None)
        } else {
            let uart = Uart::new(p.SERCOM0.reborrow(), p.PA04.reborrow(), p.PA05.reborrow(), Irqs, p.DMA_CH1.reborrow(), p.DMA_CH0.reborrow(), config).unwrap();
            let (tx, rx) = uart.split();
            (tx, rx, Some(Output::new(p.PA06.reborrow(), Level::Low)))
        };
        // Let the echo drain anything left from before.
        Timer::after(Duration::from_millis(300)).await;
        drain_dma(&mut rx).await;
        let _ = overflowed();

        // CTS: a burst the echo can't keep up with.
        let ((us, held), good) = join(send_dma(&mut tx, BURST), read_dma(&mut rx, BURST, Duration::from_secs(2))).await;
        if flow {
            t.check(
                "CTS holds the sender",
                good == BURST && held > 0,
                format_args!("{name}: 6 KiB sent in {us} us (line rate 61 ms), CTS seen holding {held} times, {good} of {BURST} back"),
            );
        } else {
            let _ = writeln!(t.log, "CTS control {name}: 6 KiB sent in {us} us, {good} of {BURST} back (some should be lost)");
            t.check("the CTS control loses bytes", good < BURST, format_args!(""));
        }
        Timer::after(Duration::from_millis(300)).await;
        drain_dma(&mut rx).await;
        let _ = overflowed();

        // RTS: nothing read while the echo comes back.
        let _ = send_dma(&mut tx, HELD).await;
        tx.flush().await;
        Timer::after(Duration::from_millis(200)).await;
        let good = read_dma(&mut rx, HELD, Duration::from_secs(1)).await;
        let lost = overflowed();
        if flow {
            t.check("RTS holds the far end", good == HELD && !lost, format_args!("{name}: {good} of {HELD} back after 200 ms unread, overflow {lost}"));
        } else {
            let _ = writeln!(t.log, "RTS control {name}: {good} of {HELD} back after 200 ms unread, overflow {lost}");
            t.check("the RTS control loses bytes", lost || good < HELD, format_args!(""));
        }
        drop(rts);
        Timer::after(Duration::from_millis(300)).await;
    }

    // A BufferedUart, 256-byte rings: with flow control the full receive ring
    // must hold the far end through RTS, and the transmit ring be held by CTS.
    let (mut tx_ring, mut rx_ring) = ([0u8; RING], [0u8; RING]);
    for flow in [true, false] {
        let name = if flow { "buffered, with RTS/CTS" } else { "buffered, without (control)" };
        let (uart, rts) = if flow {
            let uart = BufferedUart::new_with_rtscts(p.SERCOM0.reborrow(), p.PA04.reborrow(), p.PA05.reborrow(), p.PA06.reborrow(), p.PA07.reborrow(), Irqs, &mut tx_ring[..], &mut rx_ring[..], config).unwrap();
            (uart, None)
        } else {
            let uart = BufferedUart::new(p.SERCOM0.reborrow(), p.PA04.reborrow(), p.PA05.reborrow(), Irqs, &mut tx_ring[..], &mut rx_ring[..], config).unwrap();
            (uart, Some(Output::new(p.PA06.reborrow(), Level::Low)))
        };
        let (mut tx, mut rx) = uart.split();
        drain_buffered(&mut rx).await;

        if flow {
            // CTS: 6 KiB through a 256-byte ring, the echo read meanwhile.
            let start = micros();
            let (sent, (good, _)) = join(send_buffered(&mut tx, BURST), read_buffered(&mut rx, BURST, Duration::from_secs(2))).await;
            let us = micros() - start;
            t.check("buffered: CTS holds the sender", sent && good == BURST, format_args!("{name}: 6 KiB in {us} us, {good} of {BURST} back"));
            drain_buffered(&mut rx).await;
        }

        // RTS: nothing read for 200 ms while 2 KiB come back into a 256-byte ring.
        let _ = send_buffered(&mut tx, HELD).await;
        let _ = tx.flush().await;
        Timer::after(Duration::from_millis(200)).await;
        let waiting = rx.available();
        let (good, overrun) = read_buffered(&mut rx, HELD, Duration::from_millis(600)).await;
        if flow {
            t.check(
                "buffered: RTS holds the far end",
                good == HELD && !overrun,
                format_args!("{name}: {waiting} waiting in the ring after 200 ms, then {good} of {HELD} back, overrun {overrun}"),
            );
        } else {
            let _ = writeln!(t.log, "buffered RTS control {name}: {good} of {HELD} back, overrun {overrun}");
            t.check("the buffered RTS control loses bytes", overrun || good < HELD, format_args!(""));
        }
        drop(rts);
        drop((tx, rx));
        Timer::after(Duration::from_millis(300)).await;
    }
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32cm_pl10_curiosity_nano::init();
    let mut log = Log::init(p.SERCOM1, p.PB00, p.PB01);
    let mut led = Output::new(p.PB02, Level::High);
    let _ = writeln!(log, "\npic32cm-pl10-curiosity-nano uart_flow");
    let mut parts = Parts {
        SERCOM0: p.SERCOM0,
        PA04: p.PA04,
        PA05: p.PA05,
        PA06: p.PA06,
        PA07: p.PA07,
        DMA_CH0: p.DMA_CH0,
        DMA_CH1: p.DMA_CH1,
    };
    let mut t = Tests { log: &mut log, failures: 0 };
    tests(&mut parts, &mut t).await;
    let failures = t.failures;
    let _ = if failures == 0 { writeln!(log, "uart_flow: all passed") } else { writeln!(log, "uart_flow: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
