//! `pic32c-hal`'s `spi` against a real device: a `WIZnet` W5500 on a
//! `MikroElektronika` ETH WIZ Click in the mikroBUS socket (SERCOM2: MOSI
//! PC15, SCK PC16, MISO PC17; CS PD15, RST PD21 and INT PD18 as GPIOs),
//! powered from the board's 3.3 V. Frames are the W5500's variable-length
//! ones: a 16-bit address, a control byte (block, read/write) and the data
//! while CS is low.
//!
//! The socket's SPI pins are also EXT2's UART (`uart_link`, `uart_peer`) and
//! `spi`'s loopback: plug the click in, and unplug the UART link, only for
//! this program. Its RST is also the on-board Ethernet PHY's reset, so the
//! PHY resets with it.
//!
//! - a hardware reset (RST low 1 ms, then 2 ms for the PLL); INT idle (high);
//! - blocking, 1 MHz: VERSIONR (0x0039) reads 0x04; a software reset
//!   (MR.RST) clears;
//! - the MAC address (SHAR) and IP address (SIPR) written and read back;
//! - the PHY (PHYCFGR): link, speed and duplex, reported;
//! - by DMA, SCK and MOSI slew-limited (`Slow4`; at `Fast` the 15 cm
//!   leads ring and reads slip a bit now and then): socket 0's 2 KiB
//!   transmit buffer filled with a pattern and
//!   read back at 1, 6 and 12 MHz from generator 3 (48 MHz; asking for 24
//!   gives 12, the SERCOM being rated to 21.3 MHz), at 12 MHz in mode 3,
//!   and at 20 MHz from generator 2 (80 MHz), timed.
//!
//! Over the virtual COM port; LED0 blinks slowly when all passed, fast on a
//! failure.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;

use embassy_executor::Spawner;
use embassy_time::{Duration, Timer};
use embedded_hal::spi::{MODE_0, MODE_3, SpiBus};
use panic_halt as _;
use pic32c_hal::gpio::{Input, Level, Output, Pull, Slew};
use pic32c_hal::mode::{Async, Blocking};
use pic32c_hal::spi::{Config, Spi};
use pic32ck_curiosity_ultra::time;
use pic32ck_curiosity_ultra::uart::Uart;

pic32ck_curiosity_ultra::boot!();

/// The common registers' block, and socket 0's transmit buffer's.
const COMMON: u8 = 0b00000;
const SOCKET0_TX: u8 = 0b00010;

const MR: u16 = 0x0000;
const SHAR: u16 = 0x0009;
const SIPR: u16 = 0x000F;
const PHYCFGR: u16 = 0x002E;
const VERSIONR: u16 = 0x0039;

/// A locally administered address, and one from TEST-NET-1 (RFC 5737):
/// only written to the registers and read back.
const MAC: [u8; 6] = [0x02, 0x00, 0x00, 0x12, 0x34, 0x56];
const IP: [u8; 4] = [192, 0, 2, 250];

const BUFFER: usize = 2048;

struct Tests<'a> {
    log: &'a mut Uart,
    failures: u32,
}

impl Tests<'_> {
    fn check(&mut self, name: &str, good: bool, detail: core::fmt::Arguments<'_>) {
        let _ = writeln!(self.log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        self.failures += u32::from(!good);
    }
}

fn header(address: u16, block: u8, write: bool) -> [u8; 3] {
    let [high, low] = address.to_be_bytes();
    [high, low, (block << 3) | (u8::from(write) << 2)]
}

fn pattern(buffer: &mut [u8], seed: u8) {
    for (i, b) in buffer.iter_mut().enumerate() {
        #[expect(clippy::cast_possible_truncation, reason = "a pattern")]
        let v = (i as u8).wrapping_mul(37).wrapping_add(seed) ^ (i >> 8) as u8;
        *b = v;
    }
}

struct Blocked<'a, 's, 'c> {
    spi: Spi<'s, Blocking>,
    cs: &'a mut Output<'c>,
}

impl Blocked<'_, '_, '_> {
    fn read(&mut self, address: u16, block: u8, data: &mut [u8]) {
        self.cs.set_low();
        let _ = self.spi.write(&header(address, block, false));
        let _ = SpiBus::read(&mut self.spi, data);
        let _ = SpiBus::flush(&mut self.spi);
        self.cs.set_high();
    }

    fn write(&mut self, address: u16, block: u8, data: &[u8]) {
        self.cs.set_low();
        let _ = self.spi.write(&header(address, block, true));
        let _ = self.spi.write(data);
        let _ = SpiBus::flush(&mut self.spi);
        self.cs.set_high();
    }

    fn byte(&mut self, address: u16) -> u8 {
        let mut b = [0];
        self.read(address, COMMON, &mut b);
        b[0]
    }
}

async fn dma_read(spi: &mut Spi<'_, Async>, cs: &mut Output<'_>, address: u16, block: u8, data: &mut [u8]) {
    cs.set_low();
    let _ = spi.write(&header(address, block, false)).await;
    let _ = spi.read(data).await;
    cs.set_high();
}

async fn dma_write(spi: &mut Spi<'_, Async>, cs: &mut Output<'_>, address: u16, block: u8, data: &[u8]) {
    cs.set_low();
    let _ = spi.write(&header(address, block, true)).await;
    let _ = spi.write(data).await;
    cs.set_high();
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let mut p = pic32ck_curiosity_ultra::init();
    time::init(cortex_m::Peripherals::take().unwrap());
    let mut log = Uart::init(p.SERCOM5, p.PA24, p.PA25);
    let mut led = Output::new(p.PD20, Level::High);
    let _ = writeln!(log, "\npic32ck-curiosity-ultra w5500");
    let mut t = Tests { log: &mut log, failures: 0 };
    let mut cs = Output::new(p.PD15, Level::High);
    // The hardware reset: at least 500 us low, then the PLL's lock time.
    let mut rst = Output::new(p.PD21, Level::Low);
    Timer::after(Duration::from_millis(1)).await;
    rst.set_high();
    Timer::after(Duration::from_millis(2)).await;
    let int = Input::new(p.PD18, Pull::Up);
    t.check("INT idle", int.is_high(), format_args!("INT {}", if int.is_high() { "high" } else { "low" }));
    {
        let mut config = Config::default();
        config.frequency = 1_000_000;
        config.slew = Slew::Slow4;
        let spi = Spi::new_blocking(p.SERCOM2.reborrow(), p.PC16.reborrow(), p.PC15.reborrow(), p.PC17.reborrow(), config).unwrap();
        let mut w = Blocked { spi, cs: &mut cs };

        let version = w.byte(VERSIONR);
        t.check("version", version == 0x04, format_args!("VERSIONR {version:#04x}"));

        w.write(MR, COMMON, &[0x80]);
        let start = time::micros();
        let mut mr = 0x80;
        while mr & 0x80 != 0 && time::micros() - start < 100_000 {
            mr = w.byte(MR);
        }
        t.check("reset", mr & 0x80 == 0, format_args!("MR {mr:#04x} after {} us", time::micros() - start));

        w.write(SHAR, COMMON, &MAC);
        w.write(SIPR, COMMON, &IP);
        let (mut mac, mut ip) = ([0u8; 6], [0u8; 4]);
        w.read(SHAR, COMMON, &mut mac);
        w.read(SIPR, COMMON, &mut ip);
        t.check("registers", mac == MAC && ip == IP, format_args!("SHAR {mac:02x?}, SIPR {ip:?}"));

        // The link may take a few seconds after the reset.
        let start = time::micros();
        let mut phy = w.byte(PHYCFGR);
        while phy & 1 == 0 && time::micros() - start < 5_000_000 {
            Timer::after(Duration::from_millis(100)).await;
            phy = w.byte(PHYCFGR);
        }
        let _ = writeln!(
            t.log,
            "PHYCFGR {phy:#04x}: link {}, {} Mbit/s, {} duplex",
            if phy & 1 != 0 { "up" } else { "down" },
            if phy & 2 != 0 { 100 } else { 10 },
            if phy & 4 != 0 { "full" } else { "half" }
        );
    }

    let mut out = [0u8; BUFFER];
    let mut back = [0u8; BUFFER];
    let runs = [(1_000_000, MODE_0, 3), (6_000_000, MODE_0, 3), (12_000_000, MODE_0, 3), (24_000_000, MODE_0, 3), (12_000_000, MODE_3, 3), (20_000_000, MODE_0, 2)];
    #[expect(clippy::cast_possible_truncation, reason = "a seed")]
    for (i, &(frequency, mode, generator)) in runs.iter().enumerate() {
        let mut config = Config::default();
        config.frequency = frequency;
        config.mode = mode;
        config.generator = generator;
        config.slew = Slew::Slow4;
        let mut spi = Spi::new(p.SERCOM2.reborrow(), p.PC16.reborrow(), p.PC15.reborrow(), p.PC17.reborrow(), p.DMA0_CH0.reborrow(), p.DMA0_CH1.reborrow(), config).unwrap();
        let actual = spi.frequency();
        for repeat in 0..5u8 {
            pattern(&mut out, i as u8 * 11 + repeat * 3 + 1);
            back.fill(0);
            let start = time::micros();
            dma_write(&mut spi, &mut cs, 0, SOCKET0_TX, &out).await;
            let wrote = time::micros() - start;
            let start = time::micros();
            dma_read(&mut spi, &mut cs, 0, SOCKET0_TX, &mut back).await;
            let read = time::micros() - start;
            let wrong = out.iter().zip(back.iter()).filter(|(a, b)| a != b).count();
            let mode3 = mode == MODE_3;
            let detail = format_args!("{actual} Hz{}: {BUFFER} bytes written in {wrote} us, read in {read} us, {wrong} wrong", if mode3 { ", mode 3" } else { "" });
            t.check("buffer", wrong == 0, detail);
            if wrong != 0 {
                // Which side: read it again; the same wrong data means the
                // write went wrong, right data the first read.
                let first = out.iter().zip(back.iter()).position(|(a, b)| a != b).unwrap_or(0);
                let mut again = [0u8; BUFFER];
                dma_read(&mut spi, &mut cs, 0, SOCKET0_TX, &mut again).await;
                let wrong_again = out.iter().zip(again.iter()).filter(|(a, b)| a != b).count();
                let to = (first + 6).min(BUFFER);
                let _ = writeln!(
                    t.log,
                    "  first wrong at {first}: sent {:02x?}, read {:02x?}; read again: {wrong_again} wrong, {:02x?}",
                    &out[first..to],
                    &back[first..to],
                    &again[first..to]
                );
            }
        }
    }

    let failures = t.failures;
    let _ = if failures == 0 { writeln!(log, "w5500: all passed") } else { writeln!(log, "w5500: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
