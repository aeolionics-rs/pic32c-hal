//! `pic32c-hal`'s UART hardware flow control (RTS/CTS), against an echo that
//! drains slowly: SERCOM2 on the EXT2 header (TX PC15 pin 16, RX PC16 pin
//! 18, RTS PC17 pin 17, CTS PC18 pin 6) at 1 Mbaud to `uart_peer` on a second board
//! (RTS/CTS on, about 50 KB/s, half the line's rate). The FIFO is on unless
//! `UART_FLOW_FIFO=0` (all pass either way).
//!
//! - CTS: 8 KiB sent at once, the echo read by DMA meanwhile. `uart_peer`'s
//!   receive ring fills and its RTS stops this board's transmitter: every
//!   byte must come back, and CTS must be seen holding.
//! - RTS: 2 KiB sent, then nothing read for 200 ms while the echo comes
//!   back: this board's RTS must stop `uart_peer`, so a late read still gets
//!   every byte, and the receiver no overflow.
//!
//! Each runs again without flow control (`Uart::new`, PC17 driven low so
//! `uart_peer` always may send), where bytes should be lost: the control. Then the
//! same with a `BufferedUart` and 256-byte rings: 8 KiB through its transmit
//! ring held by CTS, and 2 KiB unread for 200 ms, its full receive ring
//! leaving bytes in the SERCOM so that RTS holds `uart_peer` (the control must
//! overrun). Over the
//! virtual COM port; LED0 blinks slowly when all passed, fast on a failure.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;
use core::ptr::{read_volatile, write_volatile};

use embassy_executor::Spawner;
use embassy_futures::join::join;
use embassy_futures::select::{Either, select};
use embassy_time::{Duration, Timer};
use panic_halt as _;
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::mode::Async;
use pic32c_hal::uart::{self, BufferedUart, BufferedUartRx, Uart, UartRx, UartTx};
use pic32c_hal::{Peri, bind_interrupts, peripherals};
use pic32ck_curiosity_ultra::time;
use pic32ck_curiosity_ultra::uart::Uart as Log;
use static_cell::ConstStaticCell;

pic32ck_curiosity_ultra::boot!();

bind_interrupts!(struct Irqs {
    SERCOM2_0 => uart::InterruptHandler<peripherals::SERCOM2>;
    SERCOM2_1 => uart::InterruptHandler<peripherals::SERCOM2>;
    SERCOM2_2 => uart::InterruptHandler<peripherals::SERCOM2>;
    SERCOM2_56 => uart::InterruptHandler<peripherals::SERCOM2>;
});

const SERCOM2: usize = 0x4481_4000;
const STATUS: usize = SERCOM2 + 0x1A;
const BUFOVF: u16 = 1 << 2;
/// The SERCOM's FIFO, unless `UART_FLOW_FIFO=0` when building.
const FIFO: bool = match option_env!("UART_FLOW_FIFO") {
    Some(value) => !matches!(value.as_bytes(), [b'0']),
    None => true,
};
const BURST: usize = 8192;
const HELD: usize = 2048;
/// The `BufferedUart`'s rings.
const RING: usize = 256;

static OUT: ConstStaticCell<[u8; BURST]> = ConstStaticCell::new([0; BURST]);
static BACK: ConstStaticCell<[u8; BURST]> = ConstStaticCell::new([0; BURST]);

#[expect(non_snake_case, reason = "named as the peripherals")]
struct Parts {
    SERCOM2: Peri<'static, peripherals::SERCOM2>,
    PC15: Peri<'static, peripherals::PC15>,
    PC16: Peri<'static, peripherals::PC16>,
    PC17: Peri<'static, peripherals::PC17>,
    PC18: Peri<'static, peripherals::PC18>,
    DMA0_CH0: Peri<'static, peripherals::DMA0_CH0>,
    DMA0_CH1: Peri<'static, peripherals::DMA0_CH1>,
}

struct Tests<'a> {
    log: &'a mut Log,
    failures: u32,
}

impl Tests<'_> {
    fn check(&mut self, name: &str, good: bool, detail: core::fmt::Arguments<'_>) {
        let _ = writeln!(self.log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        self.failures += u32::from(!good);
    }
}

fn overflowed() -> bool {
    // SAFETY: SERCOM2's STATUS, read and its BUFOVF cleared.
    unsafe {
        let status = read_volatile(STATUS as *const u16);
        write_volatile(STATUS as *mut u16, status & BUFOVF);
        status & BUFOVF != 0
    }
}

/// Bytes of `back` that match `out`.
fn matching(out: &[u8], back: &[u8]) -> usize {
    out.iter().zip(back).filter(|(a, b)| a == b).count()
}

/// Sends `out` while counting how often CTS is seen holding.
async fn send_watching(tx: &mut UartTx<'_, Async>, out: &[u8]) -> (u64, u32) {
    let start = time::micros();
    let mut held = 0u32;
    let send = tx.write(out);
    let watch = async {
        loop {
            if !tx_clear() {
                held += 1;
            }
            Timer::after(Duration::from_micros(200)).await;
        }
    };
    let _ = select(send, watch).await;
    (time::micros() - start, held)
}

/// CTS as the SERCOM sees it: STATUS.CTS clear.
fn tx_clear() -> bool {
    // SAFETY: SERCOM2's STATUS, read only.
    unsafe { read_volatile(STATUS as *const u16) & (1 << 3) == 0 }
}

/// Reads `buffer` (by DMA, the UART having it), giving up after `limit`: whether it
/// all came (receive errors are the overflow check's).
async fn read_dma(rx: &mut UartRx<'_, Async>, buffer: &mut [u8], limit: Duration) -> bool {
    matches!(select(rx.read(buffer), Timer::after(limit)).await, Either::First(Ok(()) | Err(uart::Error::Overrun | uart::Error::Framing | uart::Error::Parity)))
}

#[expect(clippy::too_many_lines, reason = "one test after another")]
async fn tests(p: &mut Parts, t: &mut Tests<'_>, out: &mut [u8; BURST], back: &mut [u8; BURST]) {
    for (i, b) in out.iter_mut().enumerate() {
        #[expect(clippy::cast_possible_truncation, reason = "a pattern")]
        let v = (i * 13 + i / 256) as u8;
        *b = v;
    }
    let mut config = uart::Config::default();
    config.baudrate = 1_000_000;
    // The FIFO unless `UART_FLOW_FIFO=0` when building.
    config.fifo = FIFO;

    for flow in [true, false] {
        let name = if flow { "with RTS/CTS" } else { "without (control)" };
        // The control drives `uart_peer`'s CTS low by hand, so it always sends.
        let (mut tx, mut rx, rts) = if flow {
            let uart = Uart::new_with_rtscts(
                p.SERCOM2.reborrow(),
                p.PC15.reborrow(),
                p.PC16.reborrow(),
                p.PC17.reborrow(),
                p.PC18.reborrow(),
                Irqs,
                p.DMA0_CH1.reborrow(),
                p.DMA0_CH0.reborrow(),
                config,
            )
            .unwrap();
            let (tx, rx) = uart.split();
            (tx, rx, None)
        } else {
            let uart = Uart::new(p.SERCOM2.reborrow(), p.PC15.reborrow(), p.PC16.reborrow(), Irqs, p.DMA0_CH1.reborrow(), p.DMA0_CH0.reborrow(), config).unwrap();
            let (tx, rx) = uart.split();
            (tx, rx, Some(Output::new(p.PC17.reborrow(), Level::Low)))
        };
        // Let the echo drain anything left from before.
        Timer::after(Duration::from_millis(300)).await;
        let _ = overflowed();
        let mut scratch = [0u8; 1];
        while matches!(select(rx.read(&mut scratch), Timer::after(Duration::from_millis(20))).await, Either::First(_)) {}

        // CTS: a burst the echo can't keep up with.
        back.fill(0);
        let (sent, came) = join(send_watching(&mut tx, &out[..]), read_dma(&mut rx, &mut back[..], Duration::from_secs(2))).await;
        let (us, held) = sent;
        let good = matching(&out[..], &back[..]);
        if flow {
            t.check(
                "CTS holds the sender",
                came && good == BURST && held > 0,
                format_args!("{name}: 8 KiB sent in {us} us (line rate 82 ms), CTS seen holding {held} times, {good} of {BURST} back"),
            );
        } else {
            let _ = writeln!(t.log, "CTS control {name}: 8 KiB sent in {us} us, {good} of {BURST} back (some should be lost)");
            t.check("the CTS control loses bytes", good < BURST, format_args!(""));
        }
        Timer::after(Duration::from_millis(300)).await;
        while matches!(select(rx.read(&mut scratch), Timer::after(Duration::from_millis(20))).await, Either::First(_)) {}
        let _ = overflowed();

        // RTS: nothing read while the echo comes back.
        back.fill(0);
        let _ = tx.write(&out[..HELD]).await;
        tx.flush().await;
        Timer::after(Duration::from_millis(200)).await;
        let came = read_dma(&mut rx, &mut back[..HELD], Duration::from_secs(1)).await;
        let lost = overflowed();
        let good = matching(&out[..HELD], &back[..HELD]);
        if flow {
            t.check("RTS holds the far end", came && good == HELD && !lost, format_args!("{name}: {good} of {HELD} back after 200 ms unread, overflow {lost}"));
        } else {
            let _ = writeln!(t.log, "RTS control {name}: {good} of {HELD} back after 200 ms unread, overflow {lost}");
            t.check("the RTS control loses bytes", lost || good < HELD, format_args!(""));
        }
        drop(rts);
        Timer::after(Duration::from_millis(300)).await;
    }

    // A BufferedUart, 256-byte rings: with flow control the full receive ring
    // must hold the far end through RTS, and the transmit ring be held by CTS.
    let (mut tx_ring, mut rx_ring) = ([0u8; RING], [0u8; RING]);
    for flow in [true, false] {
        let name = if flow { "buffered, with RTS/CTS" } else { "buffered, without (control)" };
        let (uart, rts) = if flow {
            let uart = BufferedUart::new_with_rtscts(p.SERCOM2.reborrow(), p.PC15.reborrow(), p.PC16.reborrow(), p.PC17.reborrow(), p.PC18.reborrow(), Irqs, &mut tx_ring[..], &mut rx_ring[..], config).unwrap();
            (uart, None)
        } else {
            let uart = BufferedUart::new(p.SERCOM2.reborrow(), p.PC15.reborrow(), p.PC16.reborrow(), Irqs, &mut tx_ring[..], &mut rx_ring[..], config).unwrap();
            (uart, Some(Output::new(p.PC17.reborrow(), Level::Low)))
        };
        let (mut tx, mut rx) = uart.split();
        drain_buffered(&mut rx).await;

        if flow {
            // CTS: 8 KiB through a 256-byte ring, the echo read meanwhile.
            back.fill(0);
            let start = time::micros();
            let (sent, came) = join(tx.write_all(&out[..]), async { matches!(select(rx.read_exact(&mut back[..]), Timer::after(Duration::from_secs(2))).await, Either::First(Ok(()))) }).await;
            let us = time::micros() - start;
            let good = matching(&out[..], &back[..]);
            t.check("buffered: CTS holds the sender", sent.is_ok() && came && good == BURST, format_args!("{name}: 8 KiB in {us} us, {good} of {BURST} back"));
            drain_buffered(&mut rx).await;
        }

        // RTS: nothing read for 200 ms while 2 KiB come back into a 256-byte ring.
        back.fill(0);
        let _ = tx.write_all(&out[..HELD]).await;
        let _ = tx.flush().await;
        Timer::after(Duration::from_millis(200)).await;
        let waiting = rx.available();
        let mut got = 0;
        let mut overrun = false;
        while got < HELD {
            match select(rx.read(&mut back[got..HELD]), Timer::after(Duration::from_millis(300))).await {
                Either::First(Ok(n)) => got += n,
                Either::First(Err(uart::Error::Overrun)) => overrun = true,
                Either::First(Err(_)) => {}
                Either::Second(()) => break,
            }
        }
        let good = matching(&out[..HELD], &back[..HELD]);
        if flow {
            t.check(
                "buffered: RTS holds the far end",
                good == HELD && !overrun,
                format_args!("{name}: {waiting} waiting in the ring after 200 ms, then {good} of {HELD} back, overrun {overrun}"),
            );
        } else {
            let _ = writeln!(t.log, "buffered RTS control {name}: {good} of {HELD} back, overrun {overrun}");
            t.check("the buffered RTS control loses bytes", overrun || good < HELD, format_args!(""));
        }
        drop(rts);
        drop((tx, rx));
        Timer::after(Duration::from_millis(300)).await;
    }
}

/// Reads whatever comes until 20 ms pass with nothing.
async fn drain_buffered(rx: &mut BufferedUartRx<'_>) {
    let mut scratch = [0u8; 64];
    while matches!(select(rx.read(&mut scratch), Timer::after(Duration::from_millis(20))).await, Either::First(_)) {}
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32ck_curiosity_ultra::init();
    time::init(cortex_m::Peripherals::take().unwrap());
    let mut log = Log::init(p.SERCOM5, p.PA24, p.PA25);
    let mut led = Output::new(p.PD20, Level::High);
    let _ = writeln!(log, "\npic32ck-curiosity-ultra uart_flow, FIFO {FIFO}");
    let mut parts = Parts {
        SERCOM2: p.SERCOM2,
        PC15: p.PC15,
        PC16: p.PC16,
        PC17: p.PC17,
        PC18: p.PC18,
        DMA0_CH0: p.DMA0_CH0,
        DMA0_CH1: p.DMA0_CH1,
    };
    let mut t = Tests { log: &mut log, failures: 0 };
    tests(&mut parts, &mut t, OUT.take(), BACK.take()).await;
    let failures = t.failures;
    let _ = if failures == 0 { writeln!(log, "uart_flow: all passed") } else { writeln!(log, "uart_flow: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
