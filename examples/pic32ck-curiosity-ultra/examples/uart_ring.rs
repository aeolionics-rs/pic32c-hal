//! `pic32c-hal`'s `RingBufferedUartRx`: a receiver whose DMA channel fills a
//! 512-byte ring continuously, against `uart_peer` on a second board's EXT2 header
//! (SERCOM2, TX PC15, RX PC16, RTS PC17, CTS PC18, 1 Mbaud, RTS/CTS on; the
//! echo drains about 50 KB/s).
//!
//! - Continuity: 16 KiB of a counting pattern echoed and read through the
//!   ring in odd-sized chunks with pauses between, wrapping it some 32
//!   times: every byte must come, in order.
//! - Wake: one byte sent with the ring idle, and the time until the read
//!   returns: the echo's own wait (up to 20 ms) and a byte's time, not the
//!   wait for half the ring.
//! - Overrun: 2 KiB echoed while nothing reads for 200 ms: the ring must say
//!   [`Overrun`], then carry on with what comes next.
//!
//! The FIFO is on unless `UART_RING_FIFO=0` when building. Over the virtual
//! COM port; LED0 blinks slowly when all passed, fast on a failure.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;

use embassy_executor::Spawner;
use embassy_futures::join::join;
use embassy_futures::select::{Either, select};
use embassy_time::{Duration, Timer};
use panic_halt as _;
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::uart::{self, RingBufferedUartRx, Uart};
use pic32c_hal::{bind_interrupts, peripherals};
use pic32ck_curiosity_ultra::time;
use pic32ck_curiosity_ultra::uart::Uart as Log;
use static_cell::ConstStaticCell;

pic32ck_curiosity_ultra::boot!();

bind_interrupts!(struct Irqs {
    SERCOM2_0 => uart::InterruptHandler<peripherals::SERCOM2>;
    SERCOM2_1 => uart::InterruptHandler<peripherals::SERCOM2>;
    SERCOM2_2 => uart::InterruptHandler<peripherals::SERCOM2>;
    SERCOM2_56 => uart::InterruptHandler<peripherals::SERCOM2>;
});

/// The SERCOM's FIFO, unless `UART_RING_FIFO=0` when building.
const FIFO: bool = match option_env!("UART_RING_FIFO") {
    Some(value) => !matches!(value.as_bytes(), [b'0']),
    None => true,
};
const RING: usize = 512;
const STREAM: usize = 16_384;

static RING_BUFFER: ConstStaticCell<[u8; RING]> = ConstStaticCell::new([0; RING]);
static OUT: ConstStaticCell<[u8; STREAM]> = ConstStaticCell::new([0; STREAM]);

struct Tests<'a> {
    log: &'a mut Log,
    failures: u32,
}

impl Tests<'_> {
    fn check(&mut self, name: &str, good: bool, detail: core::fmt::Arguments<'_>) {
        let _ = writeln!(self.log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        self.failures += u32::from(!good);
    }
}

fn pattern(i: usize) -> u8 {
    #[expect(clippy::cast_possible_truncation, reason = "a pattern")]
    let b = (i * 7 + i / 251) as u8;
    b
}

/// Reads whatever comes until 30 ms pass with nothing.
async fn drain(rx: &mut RingBufferedUartRx<'_>) {
    let mut scratch = [0u8; 64];
    while matches!(select(rx.read(&mut scratch), Timer::after(Duration::from_millis(30))).await, Either::First(_)) {}
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32ck_curiosity_ultra::init();
    time::init(cortex_m::Peripherals::take().unwrap());
    let mut log = Log::init(p.SERCOM5, p.PA24, p.PA25);
    let mut led = Output::new(p.PD20, Level::High);
    let _ = writeln!(log, "\npic32ck-curiosity-ultra uart_ring, FIFO {FIFO}, a {RING}-byte ring");
    let mut config = uart::Config::default();
    config.baudrate = 1_000_000;
    config.fifo = FIFO;
    let uart = Uart::new_with_rtscts(p.SERCOM2, p.PC15, p.PC16, p.PC17, p.PC18, Irqs, p.DMA0_CH1, p.DMA0_CH0, config).unwrap();
    let (mut tx, rx) = uart.split();
    let mut rx = rx.into_ring_buffered(RING_BUFFER.take());
    let out = OUT.take();
    for (i, b) in out.iter_mut().enumerate() {
        *b = pattern(i);
    }
    let mut t = Tests { log: &mut log, failures: 0 };

    drain(&mut rx).await;

    // Continuity through many wraps.
    let mut at = 0usize;
    let mut wrong = 0usize;
    let mut errors = 0u32;
    let start = time::micros();
    let send = async {
        let _ = tx.write(&out[..]).await;
        tx.flush().await;
    };
    let receive = async {
        let mut chunk = [0u8; 37];
        let mut pause = 0u64;
        while at < STREAM {
            match select(rx.read(&mut chunk), Timer::after(Duration::from_secs(1))).await {
                Either::First(Ok(n)) => {
                    for &b in &chunk[..n] {
                        if at < STREAM && b != out[at] {
                            wrong += 1;
                        }
                        at += 1;
                    }
                }
                Either::First(Err(_)) => errors += 1,
                Either::Second(()) => break,
            }
            // Now and then, a pause of up to 3 ms (150 bytes at 50 KB/s).
            pause = (pause + 7) % 13;
            if pause < 3 {
                Timer::after(Duration::from_micros(pause * 1000)).await;
            }
        }
    };
    join(send, receive).await;
    let us = time::micros() - start;
    t.check(
        "continuity",
        at >= STREAM && wrong == 0 && errors == 0,
        format_args!("{at} of {STREAM} bytes in {us} us, {wrong} wrong, {errors} errors, about {} wraps", STREAM / RING),
    );

    // Wake: one byte with the ring idle.
    drain(&mut rx).await;
    let mut one = [0u8; 8];
    let start = time::micros();
    let _ = tx.write(&[0x5A]).await;
    let got = select(rx.read(&mut one), Timer::after(Duration::from_millis(100))).await;
    let us = time::micros() - start;
    // `uart_peer` holds a byte up to 20 ms waiting for more; a reader that
    // missed the byte would wait out the 100 ms.
    t.check("wake on a byte", matches!(got, Either::First(Ok(1))) && one[0] == 0x5A && us < 50_000, format_args!("back in {us} us, the echo's wait included"));

    // Overrun: nothing read for 200 ms while 2 KiB come.
    drain(&mut rx).await;
    let _ = tx.write(&out[..2048]).await;
    tx.flush().await;
    Timer::after(Duration::from_millis(200)).await;
    let mut chunk = [0u8; 64];
    let first = rx.read(&mut chunk).await;
    let overran = first == Err(uart::Error::Overrun);
    drain(&mut rx).await;
    let _ = tx.write(&out[..100]).await;
    let mut after = [0u8; 100];
    let again = select(rx.read_exact(&mut after), Timer::after(Duration::from_millis(500))).await;
    let resumed = matches!(again, Either::First(Ok(()))) && after[..] == out[..100];
    t.check("overrun", overran && resumed, format_args!("first read {first:?}, then 100 fresh bytes right {resumed}"));

    let failures = t.failures;
    let _ = if failures == 0 { writeln!(log, "uart_ring: all passed") } else { writeln!(log, "uart_ring: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
