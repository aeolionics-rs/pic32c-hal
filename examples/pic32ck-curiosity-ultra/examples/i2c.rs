//! `pic32c-hal`'s `i2c` on the boards' target I2C bus (SERCOM4: SDA PB09,
//! SCL PB10, shared with the mikroBUS, Arduino and Xplained headers), whose
//! one device is the AT24MAC402 (U600): 256 bytes of EEPROM at 0x50 + A and
//! its factory EUI-48 and 128-bit serial number at 0x58 + A, A set by
//! J601-J603. Blocking: a scan, a NACK from an empty address, the EUI-48
//! and serial number, then a 16-byte page of the EEPROM's writable half
//! (offset 0x70) written, read back and put back as it was, each write
//! cycle waited out by acknowledge polling. On interrupts: the same reads at
//! 100 kHz, 400 kHz and 1 MHz, timed.
//!
//! Then, at 400 kHz, each sensor the scan found that `common/sensors.rs`
//! knows (an `SHT4x` at 0x44-0x46; a BMP280 or BME280 at 0x76 or 0x77, such as
//! a `MikroElektronika` `TempHum` 15 or Weather Click in the mikroBUS socket):
//! its identity (the `SHT4x`'s CRC-checked serial number, the Bosch parts'
//! chip ID) and a measurement within reason. None is fine; other devices
//! (the board's ATECC608B at 0x36) are listed, not tested.
//!
//! Over the virtual COM port; LED0 blinks slowly when all passed, fast on a
//! failure.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;

use embassy_executor::Spawner;
use embassy_time::{Duration, Timer};
use panic_halt as _;
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::i2c::{self, Config, Error, I2c};
use pic32c_hal::mode::Async;
use pic32c_hal::{Peri, bind_interrupts, peripherals};
use pic32ck_curiosity_ultra::time;
use pic32ck_curiosity_ultra::uart::Uart;
#[path = "common/sensors.rs"]
#[allow(dead_code, reason = "shared by several examples; each uses some of it")]
mod sensors;

use sensors::{BMX280, Bmx280, Centi, Reading, SHT4X};

pic32ck_curiosity_ultra::boot!();

bind_interrupts!(struct Irqs {
    SERCOM4_0 => i2c::InterruptHandler<peripherals::SERCOM4>;
    SERCOM4_1 => i2c::InterruptHandler<peripherals::SERCOM4>;
});

/// The EEPROM's word addresses: the EUI-48, the serial number, the page
/// written.
const EUI48: u8 = 0x9A;
const SERIAL: u8 = 0x80;
const PAGE: u8 = 0x70;

struct Tests<'a> {
    log: &'a mut Uart,
    failures: u32,
}

impl Tests<'_> {
    fn check(&mut self, name: &str, good: bool, detail: core::fmt::Arguments<'_>) {
        let _ = writeln!(self.log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        self.failures += u32::from(!good);
    }
}

/// Waits out the EEPROM's write cycle (5 ms at most): it NACKs its address
/// until done.
fn poll_written<M>(bus: &mut I2c<'_, M>, eeprom: u8) -> Option<u64> {
    let start = time::micros();
    while time::micros() - start < 20_000 {
        if bus.blocking_write(eeprom, &[]).is_ok() {
            return Some(time::micros() - start);
        }
    }
    None
}

async fn tests(sercom: &mut Peri<'static, peripherals::SERCOM4>, sda: &mut Peri<'static, peripherals::PB09>, scl: &mut Peri<'static, peripherals::PB10>, t: &mut Tests<'_>) {
    let mut bus = I2c::new_blocking(sercom.reborrow(), sda.reborrow(), scl.reborrow(), Config::default()).unwrap();
    let _ = writeln!(t.log, "SCL {} Hz", bus.frequency());

    // A scan.
    let mut found = [0u8; 16];
    let mut n = 0;
    for address in 0x08..0x78u8 {
        match bus.blocking_write(address, &[]) {
            Ok(()) => {
                if n < found.len() {
                    found[n] = address;
                    n += 1;
                }
            }
            Err(Error::AddressNack) => {}
            Err(e) => {
                t.check("scan", false, format_args!("{address:#04x}: {e:?}"));
                return;
            }
        }
    }
    let found = &found[..n];
    let _ = writeln!(t.log, "found {found:02x?}");
    let Some(&eeprom) = found.iter().find(|&&a| a & 0xF8 == 0x50) else {
        t.check("an AT24MAC402", false, format_args!("no device at 0x50-0x57"));
        return;
    };
    let eui = eeprom | 0x08;
    t.check("scan", found.contains(&eui), format_args!("EEPROM {eeprom:#04x}, EUI and serial {eui:#04x}"));

    // An empty address.
    let empty = (0x08..0x78u8).find(|a| !found.contains(a)).unwrap_or(0x08);
    let nack = bus.blocking_write(empty, &[0]);
    t.check("an empty address", nack == Err(Error::AddressNack), format_args!("{empty:#04x}: {nack:?}"));

    // The EUI-48 and serial number.
    let mut mac = [0u8; 6];
    let result = bus.blocking_write_read(eui, &[EUI48], &mut mac);
    t.check("EUI-48", result.is_ok() && mac != [0xFF; 6] && mac != [0; 6], format_args!("{mac:02x?} ({result:?})"));
    let mut serial = [0u8; 16];
    let result = bus.blocking_write_read(eui, &[SERIAL], &mut serial);
    t.check("serial number", result.is_ok() && serial != [0xFF; 16], format_args!("{serial:02x?} ({result:?})"));

    // A page written, read back, restored.
    let mut original = [0u8; 16];
    let result = bus.blocking_write_read(eeprom, &[PAGE], &mut original);
    t.check("read the page", result.is_ok(), format_args!("{original:02x?} ({result:?})"));
    let mut frame = [0u8; 17];
    frame[0] = PAGE;
    for (i, b) in frame[1..].iter_mut().enumerate() {
        #[expect(clippy::cast_possible_truncation, reason = "a pattern")]
        let v = original[i] ^ (0xA5 ^ i as u8);
        *b = v;
    }
    let written = bus.blocking_write(eeprom, &frame);
    let cycle = poll_written(&mut bus, eeprom);
    let mut back = [0u8; 16];
    let read = bus.blocking_write_read(eeprom, &[PAGE], &mut back);
    t.check(
        "write the page",
        written.is_ok() && read.is_ok() && back == frame[1..] && cycle.is_some(),
        format_args!("write cycle {cycle:?} us ({written:?}, {read:?})"),
    );
    frame[1..].copy_from_slice(&original);
    let restored = bus.blocking_write(eeprom, &frame);
    let cycle = poll_written(&mut bus, eeprom);
    let read = bus.blocking_write_read(eeprom, &[PAGE], &mut back);
    t.check("restore the page", restored.is_ok() && cycle.is_some() && read.is_ok() && back == original, format_args!("({restored:?}, {read:?})"));

    // Reads one byte at a time, a run of reads across two operations.
    let mut first = [0u8; 3];
    let mut rest = [0u8; 3];
    let result = bus.blocking_transaction(
        eui,
        &mut [embedded_hal::i2c::Operation::Write(&[EUI48]), embedded_hal::i2c::Operation::Read(&mut first), embedded_hal::i2c::Operation::Read(&mut rest)],
    );
    t.check("two reads in a row", result.is_ok() && first == mac[..3] && rest == mac[3..], format_args!("({result:?})"));
    drop(bus);

    // On interrupts, at three rates: one bus, moved between them by
    // `set_config`.
    let mut bus = I2c::new(sercom.reborrow(), sda.reborrow(), scl.reborrow(), Irqs, Config::default()).unwrap();
    for frequency in [100_000, 400_000, 1_000_000] {
        let mut config = Config::default();
        config.frequency = frequency;
        bus.set_config(&config).unwrap();
        let start = time::micros();
        let mut again = [0u8; 16];
        let a = bus.write_read(eui, &[SERIAL], &mut again).await;
        let mut mac_again = [0u8; 6];
        let b = bus.write_read(eui, &[EUI48], &mut mac_again).await;
        let us = time::micros() - start;
        let nack = bus.write(empty, &[]).await;
        t.check(
            "async",
            a.is_ok() && b.is_ok() && again == serial && mac_again == mac && nack == Err(Error::AddressNack),
            format_args!("at {} Hz: 24 bytes read in {us} us; empty address {nack:?}", bus.frequency()),
        );
    }

    sensors_found(&mut bus, found, &[eeprom, eui], t).await;
}

/// Tests each sensor in `found` that `sensors` knows, at 400 kHz, skipping
/// the addresses in `skip`.
async fn sensors_found(bus: &mut I2c<'_, Async>, found: &[u8], skip: &[u8], t: &mut Tests<'_>) {
    let mut config = Config::default();
    config.frequency = 400_000;
    bus.set_config(&config).unwrap();
    let mut tested = 0;
    for &address in found {
        if skip.contains(&address) {
            continue;
        }
        if SHT4X.contains(&address) {
            tested += 1;
            let serial = sensors::sht4x_serial(bus, address).await;
            t.check("SHT4x serial", serial.is_ok(), format_args!("at {address:#04x}: {serial:08x?}"));
            let reading = sensors::sht4x_measure(bus, address).await;
            check_reading(t, "SHT4x", address, reading);
        } else if BMX280.contains(&address) {
            let Some(id) = sensors::bmx280_id(bus, address).await else {
                let _ = writeln!(t.log, "{address:#04x}: not a BMP280 or BME280 (chip ID), not tested");
                continue;
            };
            tested += 1;
            let name = if id == 0x60 { "BME280" } else { "BMP280" };
            let _ = writeln!(t.log, "{name} at {address:#04x}: chip ID {id:#04x}");
            let reading = match Bmx280::new(bus, address, id).await {
                Ok(part) => part.measure(bus).await,
                Err(e) => Err(e),
            };
            check_reading(t, name, address, reading);
        } else {
            let _ = writeln!(t.log, "{address:#04x}: not a known sensor, not tested");
        }
    }
    let _ = writeln!(t.log, "sensors tested: {tested}");
}

/// A sensor's reading within reason: -10 to 60 C, 0 to 100 %RH, 300 to
/// 1100 hPa.
fn check_reading(t: &mut Tests<'_>, name: &str, address: u8, reading: Result<Reading, &'static str>) {
    match reading {
        Ok(r) => {
            let good = (-1000..=6000).contains(&r.centidegrees) && r.centi_rh.is_none_or(|rh| (0..=10_000).contains(&rh)) && r.pascals.is_none_or(|pa| (30_000..=110_000).contains(&pa));
            let _ = write!(t.log, "{name} at {address:#04x}: {} C", Centi(r.centidegrees));
            if let Some(rh) = r.centi_rh {
                let _ = write!(t.log, ", {} %RH", Centi(rh));
            }
            if let Some(pa) = r.pascals {
                let _ = write!(t.log, ", {} hPa", Centi(pa));
            }
            let _ = writeln!(t.log);
            t.check(name, good, format_args!("measurement within reason"));
        }
        Err(e) => t.check(name, false, format_args!("at {address:#04x}: {e}")),
    }
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32ck_curiosity_ultra::init();
    time::init(cortex_m::Peripherals::take().unwrap());
    let mut log = Uart::init(p.SERCOM5, p.PA24, p.PA25);
    let mut led = Output::new(p.PD20, Level::High);
    let _ = writeln!(log, "\npic32ck-curiosity-ultra i2c");
    let (mut sercom, mut sda, mut scl) = (p.SERCOM4, p.PB09, p.PB10);

    let mut t = Tests { log: &mut log, failures: 0 };
    tests(&mut sercom, &mut sda, &mut scl, &mut t).await;
    let failures = t.failures;
    let _ = if failures == 0 { writeln!(log, "i2c: all passed") } else { writeln!(log, "i2c: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
