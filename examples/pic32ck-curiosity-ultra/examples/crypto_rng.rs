//! `pic32c-hal`'s `embassy-crypto-rng`: the TRNG as embassy-crypto's random
//! number driver, in the construction this build chose (`PIC32C_HAL_RNG`,
//! `drbg` or `raw`). Reports the first call (the TRNG's start and start-up
//! health test, one critical section), the time per call for 32 B, 64 B and
//! 1 KiB (median of 5), odd sizes, and the sanity statistics over 2 Mbit of
//! output (`common/rng_stats.rs`); then the driver's counters, which must show
//! no restart. Over the virtual COM port. Build with `--features
//! <board>,crypto-rng`, without `tls` (whose code needs a heap).

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;

use embassy_crypto::rng_fill_bytes;
use embassy_executor::Spawner;
use panic_halt as _;
use pic32c_hal::trng;
use pic32ck_curiosity_ultra::clocks::CPU_HZ;
use pic32ck_curiosity_ultra::time;
use pic32ck_curiosity_ultra::uart::Uart;

pic32ck_curiosity_ultra::boot!();

#[path = "common/rng_stats.rs"]
mod rng_stats;
use rng_stats::{Stats, WORDS};

/// CPU cycles as microseconds.
fn micros(cycles: u64) -> u64 {
    cycles * 1_000_000 / u64::from(CPU_HZ)
}

/// The median time of five calls filling `len` bytes, in microseconds.
fn per_call(buf: &mut [u8]) -> u64 {
    let mut runs = [0; 5];
    for run in &mut runs {
        let start = time::cycles();
        rng_fill_bytes(buf);
        *run = micros(time::cycles() - start);
    }
    runs.sort_unstable();
    runs[2]
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32ck_curiosity_ultra::init();
    time::init(cortex_m::Peripherals::take().unwrap());
    let mut log = Uart::init(p.SERCOM5, p.PA24, p.PA25);
    let _ = writeln!(log, "\npic32ck-curiosity-ultra crypto_rng (construction {})", trng::CONSTRUCTION);
    let mut failures = 0_u32;

    let mut buf = [0_u8; 1024];
    let start = time::cycles();
    rng_fill_bytes(&mut buf[..32]);
    let first = micros(time::cycles() - start);
    let _ = writeln!(log, "first call (start, start-up test): {first} us, {} words", trng::stats().words);

    for len in [32, 64, 1024] {
        let us = per_call(&mut buf[..len]);
        let _ = writeln!(log, "{len:5} B: {us} us a call");
    }

    // Odd sizes, and two outputs in a row that must differ.
    for len in [0, 1, 3, 5, 63, 65, 1023] {
        rng_fill_bytes(&mut buf[..len]);
    }
    let (mut a, mut b) = ([0_u8; 32], [0_u8; 32]);
    rng_fill_bytes(&mut a);
    rng_fill_bytes(&mut b);
    if a == b {
        let _ = writeln!(log, "two calls gave the same 32 bytes: FAILED");
        failures += 1;
    }

    let mut stats = Stats::new();
    let words_per_buf = u32::try_from(buf.len() / 4).unwrap_or(u32::MAX);
    for _ in 0..WORDS / words_per_buf {
        rng_fill_bytes(&mut buf);
        for word in buf.as_chunks::<4>().0 {
            stats.add(u32::from_le_bytes(*word));
        }
    }
    failures += stats.report(&mut log);

    let counters = trng::stats();
    let _ = writeln!(log, "TRNG: {} words, {} restarts", counters.words, counters.restarts);
    if counters.restarts != 0 {
        let _ = writeln!(log, "a health test failed and the TRNG restarted: FAILED");
        failures += 1;
    }

    if failures == 0 {
        let _ = writeln!(log, "crypto_rng: all passed");
    } else {
        let _ = writeln!(log, "crypto_rng: {failures} failures");
    }
    loop {
        cortex_m::asm::wfi();
    }
}
