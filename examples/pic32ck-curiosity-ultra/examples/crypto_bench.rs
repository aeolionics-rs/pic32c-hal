//! The cost of each public-key step in `eth_https`'s handshake, with the
//! crates and calls `tls::provider` and rustls-rustcrypto use: X25519 and
//! P-256 key generation and agreement, and a randomized ECDSA P-256
//! signature (with `certs/key.der`), plus SHA-256 for scale. Each is the
//! median of a few runs, in ms at 120 MHz, over the virtual COM port.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::cell::RefCell;
use core::fmt::Write;

use critical_section::Mutex;
use pic32ck_curiosity_ultra::time;
use pic32ck_curiosity_ultra::uart::Uart;
use embassy_executor::Spawner;
use getrandom::rand_core::UnwrapErr;
use p256::ecdsa::signature::RandomizedSigner;
use p256::elliptic_curve::Generate as _;
use p256::pkcs8::DecodePrivateKey as _;
use panic_halt as _;
use pic32c_hal::bind_interrupts;
use pic32c_hal::trng::{self, Trng};
use sha2::Digest as _;

pic32ck_curiosity_ultra::boot!();

bind_interrupts!(struct Irqs {
    TRNG => trng::InterruptHandler;
});

/// For `to_sec1_bytes` (and the board crate's `tls`, which links alloc).
#[global_allocator]
static HEAP: embedded_alloc::TlsfHeap = embedded_alloc::TlsfHeap::empty();
const HEAP_SIZE: usize = 8 * 1024;

static KEY: &[u8] = include_bytes!("../certs/key.der");
static RNG: Mutex<RefCell<Option<Trng<'static>>>> = Mutex::new(RefCell::new(None));

/// getrandom's custom backend: the TRNG.
///
/// # Safety
/// getrandom passes a writable buffer of `len` bytes.
#[unsafe(no_mangle)]
unsafe extern "Rust" fn __getrandom_v03_custom(dest: *mut u8, len: usize) -> Result<(), getrandom::Error> {
    // SAFETY: as getrandom promises.
    let buf = unsafe { core::slice::from_raw_parts_mut(dest, len) };
    critical_section::with(|cs| match RNG.borrow_ref_mut(cs).as_mut() {
        Some(rng) => {
            rng.fill_blocking(buf);
            Ok(())
        }
        None => Err(getrandom::Error::UNSUPPORTED),
    })
}

/// `rand_core` 0.6 over getrandom (P256-Cortex-M4's bindings take 0.6).
struct Getrandom06;

impl rand_core_06::RngCore for Getrandom06 {
    fn next_u32(&mut self) -> u32 {
        let mut b = [0; 4];
        self.fill_bytes(&mut b);
        u32::from_le_bytes(b)
    }

    fn next_u64(&mut self) -> u64 {
        let mut b = [0; 8];
        self.fill_bytes(&mut b);
        u64::from_le_bytes(b)
    }

    fn fill_bytes(&mut self, dest: &mut [u8]) {
        getrandom::fill(dest).unwrap();
    }

    fn try_fill_bytes(&mut self, dest: &mut [u8]) -> Result<(), rand_core_06::Error> {
        self.fill_bytes(dest);
        Ok(())
    }
}

impl rand_core_06::CryptoRng for Getrandom06 {}

/// The median of `RUNS` timings of `f`, in µs.
fn time<R>(mut f: impl FnMut() -> R) -> u64 {
    const RUNS: usize = 5;
    let mut times = [0u64; RUNS];
    for t in &mut times {
        let start = time::cycles();
        core::hint::black_box(f());
        *t = (time::cycles() - start) / 120;
    }
    times.sort_unstable();
    times[RUNS / 2]
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32ck_curiosity_ultra::init();
    time::init(cortex_m::Peripherals::take().unwrap());
    let mut log = Uart::init(p.SERCOM5, p.PA24, p.PA25);
    let _ = writeln!(log, "\npic32ck-curiosity-ultra crypto_bench (median of 5, ms)");
    static mut HEAP_MEMORY: [core::mem::MaybeUninit<u8>; HEAP_SIZE] = [core::mem::MaybeUninit::uninit(); HEAP_SIZE];
    // SAFETY: once, before anything allocates; the memory is ours alone.
    unsafe { HEAP.init((&raw mut HEAP_MEMORY) as usize, HEAP_SIZE) };
    let rng = Trng::new(p.TRNG, Irqs);
    critical_section::with(|cs| RNG.borrow_ref_mut(cs).replace(rng));
    let mut rng = UnwrapErr(getrandom::SysRng);

    let report = |name: &str, us: u64| {
        let _ = writeln!(Uart, "{name:32} {:4}.{:03}", us / 1000, us % 1000);
    };

    // X25519: our key share (a base-point multiplication), then the shared
    // secret (a variable-point one).
    report("x25519 key share", time(|| {
        let secret = x25519_dalek::EphemeralSecret::random_from_rng(&mut rng);
        x25519_dalek::PublicKey::from(&secret)
    }));
    let peer = x25519_dalek::PublicKey::from(&x25519_dalek::EphemeralSecret::random_from_rng(&mut rng));
    report("x25519 shared secret", time(|| {
        let secret = x25519_dalek::EphemeralSecret::random_from_rng(&mut rng);
        secret.diffie_hellman(&peer)
    }));

    // salty's X25519 (Haase's assembly): the key share is a multiplication of
    // the base point u = 9, the secret one of the peer's point.
    let mut base = [0u8; 32];
    base[0] = 9;
    let mut seed = [0u8; 32];
    report("salty x25519 key share", time(|| {
        getrandom::fill(&mut seed).unwrap();
        salty::agreement::x25519(seed, base)
    }));
    let their_u = salty::agreement::x25519([7; 32], base);
    report("salty x25519 shared secret", time(|| salty::agreement::x25519(seed, their_u)));
    // Cross-check against x25519-dalek.
    let ours = x25519_dalek::StaticSecret::from(seed);
    let same = ours.diffie_hellman(&x25519_dalek::PublicKey::from(their_u)).to_bytes() == salty::agreement::x25519(seed, their_u);
    let _ = writeln!(Uart, "salty and x25519-dalek agree: {same}");

    // P-256 the same way.
    report("p256 key share", time(|| {
        let secret = p256::ecdh::EphemeralSecret::try_generate_from_rng(&mut rng).unwrap();
        p256::PublicKey::from(&secret).to_sec1_bytes()
    }));
    let peer = p256::PublicKey::from(&p256::ecdh::EphemeralSecret::try_generate_from_rng(&mut rng).unwrap());
    report("p256 shared secret", time(|| {
        let secret = p256::ecdh::EphemeralSecret::try_generate_from_rng(&mut rng).unwrap();
        secret.diffie_hellman(&peer)
    }));

    // The CertificateVerify signature: randomized ECDSA P-256 over the
    // 130-byte TLS 1.3 signed content, as rustls-rustcrypto signs.
    let key = p256::ecdsa::SigningKey::from_pkcs8_der(KEY).unwrap();
    let message = [0x20u8; 130];
    report("p256 ecdsa sign", time(|| {
        let signature: p256::ecdsa::DerSignature = key.try_sign_with_rng(&mut rng, &message).unwrap();
        signature
    }));
    // The same with P256-Cortex-M4 (assembly), its RNG the TRNG through
    // getrandom, over a SHA-256 prehash as a TLS signer would pass it.
    let mut rng06 = Getrandom06;
    let secret = p256_cortex_m4::SecretKey::from_bytes(key.to_bytes()).unwrap();
    report("p256-cortex-m4 ecdsa sign", time(|| {
        let digest = sha2::Sha256::digest(message);
        secret.sign_prehashed(&digest, &mut rng06)
    }));
    report("p256-cortex-m4 key share", time(|| p256_cortex_m4::SecretKey::random(&mut rng06).public_key()));
    let theirs = p256_cortex_m4::SecretKey::random(&mut rng06).public_key();
    report("p256-cortex-m4 shared secret", time(|| p256_cortex_m4::SecretKey::random(&mut rng06).agree(&theirs)));
    // Cross-check: p256 verifies what P256-Cortex-M4 signed.
    let signature = secret.sign_prehashed(&sha2::Sha256::digest(message), &mut rng06).to_untagged_bytes();
    let signature = p256::ecdsa::Signature::from_slice(&signature).unwrap();
    let verified = p256::ecdsa::signature::Verifier::verify(key.verifying_key(), &message, &signature).is_ok();
    let _ = writeln!(Uart, "p256 verifies the p256-cortex-m4 signature: {verified}");
    report("p256 key load (pkcs8)", time(|| p256::ecdsa::SigningKey::from_pkcs8_der(KEY).unwrap()));

    let block = [0x5au8; 1024];
    report("sha256 of 1 KiB", time(|| sha2::Sha256::digest(block)));
    let _ = writeln!(Uart, "crypto_bench: done");
    loop {
        cortex_m::asm::wfi();
    }
}
