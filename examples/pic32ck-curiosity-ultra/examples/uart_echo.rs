//! `pic32c-hal`'s `uart` under test, async, on the virtual COM port
//! (SERCOM5, PA24/PA25), split: the receiver counts receive errors by kind
//! and passes every byte through a 256-byte pipe to the transmitter, which
//! echoes it (so the two sides needn't keep in step, nor the two ends'
//! clocks agree exactly). ENQ (0x05) isn't echoed: it asks for a line of
//! counts (`errors: framing F parity P overrun O; echoed N; fifo on`), and
//! BEL (0x07) stops the receiver for 500 µs, to see what the FIFO holds
//! meanwhile (`UART_FIFO=0` when building turns it off). The baud rate is
//! `UART_BAUD` (decimal, read when building), 115,200 by default; the host's
//! `uart_echo_test.py` drives it, and opens the port at the wrong rate for
//! a while to make framing errors.

#![no_std]
#![no_main]
// Embassy's main macro passes `_spawner` on to the task it generates, where
// an attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::cell::Cell;
use core::fmt::Write as _;

use embassy_executor::Spawner;
use embassy_futures::join::join;
use embassy_sync::blocking_mutex::raw::NoopRawMutex;
use embassy_sync::pipe::Pipe;
use panic_halt as _;
use pic32c_hal::uart::{self, BufferedUart, Error};
use pic32c_hal::{bind_interrupts, peripherals};
use static_cell::ConstStaticCell;

pic32ck_curiosity_ultra::boot!();

const BAUD: u32 = match option_env!("UART_BAUD") {
    Some(text) => match u32::from_str_radix(text, 10) {
        Ok(baud) => baud,
        Err(_) => panic!("UART_BAUD must be decimal"),
    },
    None => 115_200,
};
const ENQ: u8 = 0x05;
/// Stops the receiver for 500 µs (the whole program, in fact: it spins).
const BEL: u8 = 0x07;
/// The FIFO, unless `UART_FIFO=0` when building.
const FIFO: bool = match option_env!("UART_FIFO") {
    Some(value) => !matches!(value.as_bytes(), [b'0']),
    None => true,
};

static TX_BUFFER: ConstStaticCell<[u8; 256]> = ConstStaticCell::new([0; 256]);
static RX_BUFFER: ConstStaticCell<[u8; 256]> = ConstStaticCell::new([0; 256]);

bind_interrupts!(struct Irqs {
    SERCOM5_0 => uart::InterruptHandler<peripherals::SERCOM5>;
    SERCOM5_1 => uart::InterruptHandler<peripherals::SERCOM5>;
    SERCOM5_2 => uart::InterruptHandler<peripherals::SERCOM5>;
    SERCOM5_56 => uart::InterruptHandler<peripherals::SERCOM5>;
});

/// A line of text, formatted without allocating.
struct Line {
    bytes: [u8; 96],
    len: usize,
}

impl core::fmt::Write for Line {
    fn write_str(&mut self, s: &str) -> core::fmt::Result {
        let end = self.len + s.len();
        self.bytes.get_mut(self.len..end).ok_or(core::fmt::Error)?.copy_from_slice(s.as_bytes());
        self.len = end;
        Ok(())
    }
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32ck_curiosity_ultra::init();
    let mut config = uart::Config::default();
    config.baudrate = BAUD;
    config.fifo = FIFO;
    let mut uart = BufferedUart::new(p.SERCOM5, p.PA24, p.PA25, Irqs, TX_BUFFER.take(), RX_BUFFER.take(), config).unwrap();
    let mut line = Line { bytes: [0; 96], len: 0 };
    let _ = write!(line, "\r\npic32ck-curiosity-ultra uart_echo: {} baud (asked {BAUD})\r\n", uart.baudrate());
    let _ = embedded_io_async::Write::write_all(&mut uart, &line.bytes[..line.len]).await;

    let (framing, parity, overrun, echoed) = (Cell::new(0u32), Cell::new(0u32), Cell::new(0u32), Cell::new(0u32));
    let pipe: Pipe<NoopRawMutex, 256> = Pipe::new();
    let (mut tx, mut rx) = uart.split();
    let receive = async {
        let mut chunk = [0u8; 64];
        loop {
            match rx.read(&mut chunk).await {
                Ok(n) => {
                    for &byte in &chunk[..n] {
                        if byte == BEL {
                            // 500 µs at 120 MHz; the interrupts keep receiving.
                            cortex_m::asm::delay(60_000);
                        } else {
                            pipe.write_all(&[byte]).await;
                        }
                    }
                }
                Err(Error::Framing) => framing.set(framing.get() + 1),
                Err(Error::Parity) => parity.set(parity.get() + 1),
                Err(Error::Overrun) => overrun.set(overrun.get() + 1),
                Err(_) => {}
            }
        }
    };
    let transmit = async {
        let mut chunk = [0; 64];
        loop {
            let n = pipe.read(&mut chunk).await;
            for &byte in &chunk[..n] {
                if byte == ENQ {
                    line.len = 0;
                    let _ = write!(
                        line,
                        "errors: framing {} parity {} overrun {}; echoed {}; fifo {}\r\n",
                        framing.get(),
                        parity.get(),
                        overrun.get(),
                        echoed.get(),
                        if FIFO { "on" } else { "off" }
                    );
                    let _ = tx.write_all(&line.bytes[..line.len]).await;
                } else {
                    let _ = tx.write_all(&[byte]).await;
                    echoed.set(echoed.get() + 1);
                }
            }
        }
    };
    join(receive, transmit).await;
}
