//! TCP and HTTP on `pic32c-hal`'s `eth` with embassy-net, after `eth_ping`'s
//! DHCP and SLAAC:
//! - a TCP echo server on port 7 (one connection at a time);
//! - picoserve on port 80, two connections at a time: `/` a page,
//!   `/status` the uptime, addresses and link as text, `/blob` 64 KiB of a
//!   known pattern (bytes 0 to 255, over and over) to measure throughput.
//!
//! The servers run as futures joined in `main` (no spawned tasks, so the
//! router needn't be a nameable `'static` type). The addresses and each
//! echo connection's byte count go out over the virtual COM port. The host's
//! `eth_http_test.py` drives it.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;
use core::net::Ipv6Addr;

use pic32ck_curiosity_ultra::clocks;
use pic32ck_curiosity_ultra::uart::Uart;
use embassy_executor::Spawner;
use embassy_futures::join::join4;
use embassy_net::tcp::TcpSocket;
use embassy_net::{Config, ConfigV6, DhcpConfig, EthernetAddress, HardwareAddress, Runner, Stack, StackResources};
use embassy_time::{Duration, Instant, Timer, with_timeout};
use embedded_io_async::Write as _;
use panic_halt as _;
use pic32c_hal::eth::{self, Ethernet, PacketQueue, Pins};
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::{bind_interrupts, uid};
use picoserve::response::IntoResponse;
use picoserve::routing::{get, get_service};
use static_cell::StaticCell;

pic32ck_curiosity_ultra::boot!();

bind_interrupts!(struct Irqs {
    ETH => eth::InterruptHandler;
});

static QUEUE: StaticCell<PacketQueue<4, 8>> = StaticCell::new();
/// Sockets: DHCP, DNS, the echo server, two HTTP servers, and spare.
static RESOURCES: StaticCell<StackResources<8>> = StaticCell::new();
static CONFIG: picoserve::Config = picoserve::Config::new(picoserve::Timeouts {
    start_read_request: Duration::from_secs(5),
    persistent_start_read_request: Duration::from_secs(2),
    read_request: Duration::from_secs(2),
    write: Duration::from_secs(5),
})
.keep_connection_alive();

/// The pattern `/blob` serves: bytes 0 to 255, 256 times.
static BLOB: [u8; 65_536] = {
    let mut blob = [0; 65_536];
    let mut i = 0;
    while i < blob.len() {
        #[expect(clippy::cast_possible_truncation, reason = "the low byte")]
        let byte = i as u8;
        blob[i] = byte;
        i += 1;
    }
    blob
};

#[embassy_executor::task]
async fn net(mut runner: Runner<'static, Ethernet<'static>>) -> ! {
    runner.run().await
}

/// The link-local address embassy-net gives the interface (`fe80::/64` with
/// the modified EUI-64 from the MAC), which it doesn't report.
fn link_local(stack: Stack<'_>) -> Ipv6Addr {
    let HardwareAddress::Ethernet(EthernetAddress(m)) = stack.hardware_address();
    let eui = [m[0] ^ 0x02, m[1], m[2], 0xff, 0xfe, m[3], m[4], m[5]];
    let mut octets = [0; 16];
    octets[..2].copy_from_slice(&[0xfe, 0x80]);
    octets[8..].copy_from_slice(&eui);
    Ipv6Addr::from(octets)
}

fn status(stack: Stack<'_>) -> impl IntoResponse {
    let mut text = heapless::String::<320>::new();
    let _ = write!(
        text,
        "up {} s\nlink {}\nIPv4 {:?}\nIPv6 {:?}\nIPv6 link-local {}\n",
        Instant::now().as_secs(),
        if stack.is_link_up() { "up" } else { "down" },
        stack.config_v4().map(|c| c.address),
        stack.config_v6().map(|c| c.address),
        link_local(stack)
    );
    text
}

/// One echo connection at a time on port 7.
async fn echo(stack: Stack<'_>) -> ! {
    let mut rx = [0; 2048];
    let mut tx = [0; 2048];
    loop {
        let mut socket = TcpSocket::new(stack, &mut rx, &mut tx);
        socket.set_timeout(Some(Duration::from_secs(10)));
        if socket.accept(7).await.is_err() {
            continue;
        }
        let mut buffer = [0; 1024];
        let mut echoed = 0usize;
        loop {
            match socket.read(&mut buffer).await {
                Ok(0) | Err(_) => break,
                Ok(n) => {
                    if socket.write_all(&buffer[..n]).await.is_err() {
                        break;
                    }
                    echoed += n;
                }
            }
        }
        let _ = socket.flush().await;
        socket.close();
        let mut log = Uart;
        let _ = writeln!(log, "echo: {echoed} bytes");
    }
}

/// One HTTP connection at a time on port 80. picoserve's own
/// `listen_and_serve` leaves Nagle on, which holds a response's last partial
/// segment until the host acknowledges the one before; with the host's
/// delayed ACK that adds up to ~100 ms to every response that ends short.
async fn http<P: picoserve::routing::PathRouter>(app: &picoserve::Router<P>, stack: Stack<'_>) -> ! {
    let mut rx = [0; 2048];
    let mut tx = [0; 8192];
    let mut buffer = [0; 2048];
    loop {
        let mut socket = TcpSocket::new(stack, &mut rx, &mut tx);
        if socket.accept(80).await.is_err() {
            continue;
        }
        socket.set_nagle_enabled(false);
        socket.set_keep_alive(Some(Duration::from_secs(30)));
        socket.set_timeout(Some(Duration::from_secs(45)));
        let _ = picoserve::Server::new(app, &CONFIG, &mut buffer).serve(socket).await;
    }
}

#[embassy_executor::main]
async fn main(spawner: Spawner) {
    let p = pic32ck_curiosity_ultra::init();
    let mut log = Uart::init(p.SERCOM5, p.PA24, p.PA25);
    let mut led = Output::new(p.PD20, Level::High);
    let _ = writeln!(log, "\npic32ck-curiosity-ultra eth_http");

    let id = uid::unique_id();
    let mac = [0x02, id[1], id[2], id[3], id[4], id[5]];
    let pins = Pins { ref_clk: p.PC00, mdc: p.PC03, mdio: p.PC04, crs_dv: p.PC10, rx_er: p.PC09, rxd0: p.PC07, rxd1: p.PC06, tx_en: p.PC11, txd0: p.PC12, txd1: p.PC13 };
    let Ok(ethernet) = Ethernet::new(p.ETH, Irqs, pins, p.PD21, QUEUE.init(PacketQueue::new()), mac, clocks::GEN_TIMER).await else {
        let _ = writeln!(log, "eth: no PHY");
        loop {
            led.toggle();
            Timer::after(Duration::from_millis(100)).await;
        }
    };
    let mut config = Config::dhcpv4(DhcpConfig::default());
    config.ipv6 = ConfigV6::Slaac;
    let seed = u64::from_le_bytes([id[8], id[9], id[10], id[11], id[12], id[13], id[14], id[15]]);
    let (stack, runner) = embassy_net::new(ethernet, config, RESOURCES.init(StackResources::new()), seed);
    spawner.spawn(net(runner).unwrap());
    let _ = with_timeout(Duration::from_secs(30), stack.wait_config_up()).await;
    let _ = writeln!(log, "IPv4 {:?}; IPv6 {:?}; link-local {}", stack.config_v4().map(|c| c.address), stack.config_v6().map(|c| c.address), link_local(stack));

    let app = picoserve::Router::new()
        .route("/", get_service(picoserve::response::File::html("<!doctype html><title>PIC32CK</title><h1>Hello from the PIC32CK</h1><p>pic32c-hal, embassy-net and picoserve.</p>\n")))
        .route("/status", get(move || async move { status(stack) }))
        .route("/blob", get_service(picoserve::response::File::with_content_type("application/octet-stream", &BLOB)));

    let server0 = http(&app, stack);
    let server1 = http(&app, stack);
    let blink = async {
        loop {
            led.toggle();
            Timer::after(Duration::from_millis(500)).await;
        }
    };
    #[expect(clippy::large_futures, reason = "main's future lives in the executor's static task storage, not on a stack")]
    join4(echo(stack), server0, server1, blink).await;
}
