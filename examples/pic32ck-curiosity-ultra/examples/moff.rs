//! The die temperature sensor's offset, which the PIC32CK errata (2.18.1)
//! call "Moff": the PTAT reading the factory calibration expects at the
//! die's temperature, less the one measured. The air's temperature stands in
//! for the die's, from an `SHT4x` (good to about 0.2 C, under one count) on the
//! boards' target I2C bus (SERCOM4, SDA PB09, SCL PB10): a
//! `MikroElektronika` `TempHum` 15 Click in the mikroBUS socket, or any `SHT4x`
//! breakout at 0x44-0x46. It needs one; without, it fails.
//!
//! The sensor and the bandgap through `adc`, 256 reads each a round: the
//! PTAT reading scaled to the calibration's reference by AVDD (from the
//! bandgap), and the offset from the calibration's line at the air's
//! temperature, in counts. The die runs a little warmer than the air, so the
//! true offset is a few counts (about 3.4 a degree) less than reported.
//!
//! Built with `ADC_VREF=external` (J302 powered, so the board's MCP1501
//! gives 2.048 V on PB01), the sensor is also read against it, in
//! millivolts, for the offset as a voltage.
//!
//! Five rounds, two seconds apart; it passes when every round read and the
//! offsets agree within 15 counts. Over the virtual COM port; LED0 blinks
//! slowly when all passed, fast on a failure.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;

use embassy_executor::Spawner;
use embassy_time::{Duration, Timer};
use panic_halt as _;
use pic32c_hal::adc::{self, Adc, Calibration, SampleTime};
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::i2c::{self, Config, I2c};
use pic32c_hal::{bind_interrupts, peripherals};
use pic32ck_curiosity_ultra::uart::Uart;
#[path = "common/sensors.rs"]
#[allow(dead_code, reason = "shared by several examples; each uses some of it")]
mod sensors;

use sensors::{Centi, SHT4X};

pic32ck_curiosity_ultra::boot!();

bind_interrupts!(struct Irqs {
    SERCOM4_0 => i2c::InterruptHandler<peripherals::SERCOM4>;
    SERCOM4_1 => i2c::InterruptHandler<peripherals::SERCOM4>;
});

/// The MCP1501 powered (J302) for readings against its 2.048 V, if
/// `ADC_VREF=external` when building.
const EXTERNAL: bool = match option_env!("ADC_VREF") {
    Some(value) => matches!(value.as_bytes(), b"external"),
    None => false,
};

/// How far apart the rounds' offsets may be, in counts.
const SPREAD: i64 = 15;

struct Tests<'a> {
    log: &'a mut Uart,
    failures: u32,
}

impl Tests<'_> {
    fn check(&mut self, name: &str, good: bool, detail: core::fmt::Arguments<'_>) {
        let _ = writeln!(self.log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        self.failures += u32::from(!good);
    }
}

/// The PTAT reading the factory calibration expects at `centidegrees`,
/// against its own reference.
fn expected_ptat(cal: &Calibration, centidegrees: i64) -> i64 {
    let room = i64::from(cal.room_decidegrees) * 10;
    let hot = i64::from(cal.hot_decidegrees) * 10;
    i64::from(cal.room_ptat) + (centidegrees - room) * (i64::from(cal.hot_ptat) - i64::from(cal.room_ptat)) / (hot - room)
}

async fn finish(log: &mut Uart, led: &mut Output<'_>, failures: u32) -> ! {
    let _ = if failures == 0 { writeln!(log, "moff: all passed") } else { writeln!(log, "moff: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32ck_curiosity_ultra::init();
    let mut log = Uart::init(p.SERCOM5, p.PA24, p.PA25);
    let mut led = Output::new(p.PD20, Level::High);
    let _ = writeln!(log, "\npic32ck-curiosity-ultra moff");
    let mut t = Tests { log: &mut log, failures: 0 };
    let mut config = Config::default();
    config.frequency = 400_000;
    let mut bus = I2c::new(p.SERCOM4, p.PB09, p.PB10, Irqs, config).unwrap();
    let mut adc_peripheral = p.ADC;
    let mut adc = Adc::new_blocking(adc_peripheral.reborrow(), adc::Config::default()).unwrap();
    let mut vref = adc.enable_vrefint();
    let mut sensor = adc.enable_temperature();
    let cal = Calibration::read();
    if EXTERNAL {
        pic32c_hal::gpio::set_as_function(p.PB01, pic32c_hal::gpio::Function::B);
    }

    // The SHT4x.
    let mut sht = None;
    for address in SHT4X {
        if let Ok(serial) = sensors::sht4x_serial(&mut bus, address).await {
            let _ = writeln!(t.log, "SHT4x at {address:#04x}, serial {serial:08x}");
            sht = Some(address);
            break;
        }
    }
    let Some(sht) = sht else {
        t.check("an SHT4x", false, format_args!("none at 0x44-0x46: this test needs one"));
        let failures = t.failures;
        finish(&mut log, &mut led, failures).await
    };

    Timer::after(Duration::from_millis(300)).await;
    let (mut lowest, mut highest) = (i64::MAX, i64::MIN);
    let mut rounds = 0;
    for round in 0..5 {
        let air = match sensors::sht4x_measure(&mut bus, sht).await {
            Ok(reading) => reading,
            Err(e) => {
                t.check("SHT4x", false, format_args!("round {round}: {e}"));
                continue;
            }
        };
        // The die.
        let mut ptat_sum = 0u32;
        let mut bandgap_sum = 0u32;
        for _ in 0..256 {
            ptat_sum += u32::from(adc.blocking_read(&mut sensor, SampleTime::LONG));
            bandgap_sum += u32::from(adc.blocking_read(&mut vref, SampleTime::LONG));
        }
        let (ptat, bandgap) = (ptat_sum / 256, bandgap_sum / 256);
        #[expect(clippy::cast_possible_truncation, reason = "12-bit means")]
        let avdd = cal.millivolts(bandgap as u16).unwrap_or(0);
        // The reading as the factory's reference would have given it, and the
        // offset from what the calibration expects at the air's temperature.
        let scaled = i64::from(ptat) * i64::from(avdd) / i64::from(cal.reference_mv);
        let expected = expected_ptat(&cal, air.centidegrees);
        let offset = expected - scaled;
        lowest = lowest.min(offset);
        highest = highest.max(offset);
        rounds += 1;
        // Against the MCP1501 (2.048 V): the sensor in millivolts, and the
        // offset from the calibration's line in millivolts.
        let mcp1501 = if EXTERNAL {
            drop(adc);
            let mut config = adc::Config::default();
            config.reference = adc::Reference::External;
            let mut external = Adc::new_blocking(adc_peripheral.reborrow(), config).unwrap();
            let mut sensor = external.enable_temperature();
            let mut vref = external.enable_vrefint();
            let (mut s_sum, mut b_sum) = (0u32, 0u32);
            for _ in 0..256 {
                s_sum += u32::from(external.blocking_read(&mut sensor, SampleTime::LONG));
                b_sum += u32::from(external.blocking_read(&mut vref, SampleTime::LONG));
            }
            drop(external);
            adc = Adc::new_blocking(adc_peripheral.reborrow(), adc::Config::default()).unwrap();
            // Millivolts = mean counts × 2048 / 4096.
            let sensor_mv = i64::from(s_sum / 256) / 2;
            let expected_mv = expected * i64::from(cal.reference_mv) / 4095;
            Some((sensor_mv, i64::from(b_sum / 256) / 2, expected_mv - sensor_mv))
        } else {
            None
        };
        let _ = writeln!(
            t.log,
            "round {round}: air {} C {} %RH; die PTAT {ptat} (scaled {scaled}), AVDD {avdd} mV; expected at the air's temperature {expected}: offset {offset} counts",
            Centi(air.centidegrees),
            Centi(air.centi_rh.unwrap_or(0)),
        );
        if let Some((sensor_mv, bandgap_mv, offset_mv)) = mcp1501 {
            let _ = writeln!(
                t.log,
                "  against the MCP1501: sensor {sensor_mv} mV, bandgap {bandgap_mv} mV; the calibration's line at the air's temperature less the sensor: {offset_mv} mV"
            );
        }
        Timer::after(Duration::from_secs(2)).await;
    }

    t.check("offset", rounds == 5 && highest - lowest <= SPREAD, format_args!("{lowest} to {highest} counts over {rounds} rounds (within {SPREAD})"));
    let failures = t.failures;
    finish(&mut log, &mut led, failures).await
}
