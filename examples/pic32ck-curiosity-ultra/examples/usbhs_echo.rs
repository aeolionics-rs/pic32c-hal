//! `pic32c-hal`'s `usbhs` with embassy-usb: a CDC-ACM serial port on the
//! board's high-speed USB connector (J202, the USB-C marked USB0) that
//! echoes everything it receives, in 512-byte bulk packets. The PHY's PLL
//! runs from the 12 MHz crystal. Progress, and once a second the
//! controller's state and the bytes echoed, go out over the virtual COM
//! port.
//!
//! An echoed packet of exactly 512 bytes leaves the host's read waiting
//! for the rest of a transfer, so when no more data follows within 200 µs
//! the echo ends the transfer with a zero-length packet.
//!
//! The bus's events (power, reset, configuration, suspend and resume) go to
//! the log as they happen. The device offers remote wakeup: suspended for
//! 5 s without the host resuming it, it wakes the host if the host allowed
//! that. Build with `USBHS_FULL_SPEED=1` to keep the controller at full
//! speed, with 64-byte packets, and `USBHS_DMA=1` to move the bulk packets
//! by the driver's DMA (the buffer is word-aligned for it).

#![no_std]
#![no_main]
// Embassy's main macro passes `_spawner` on to the task it generates, where
// an attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;
use core::sync::atomic::{AtomicBool, AtomicUsize, Ordering};

use embassy_executor::Spawner;
use embassy_futures::select::{Either, select};
use embassy_time::Timer;
use embassy_usb::class::cdc_acm::device::{self as cdc_acm, CdcAcmClass, State};
use embassy_usb::driver::EndpointError;
use embassy_usb::{Builder, Config, Handler, UsbDeviceSpeed};
use panic_halt as _;
use pic32c_hal::{bind_interrupts, usbhs};
use pic32ck_curiosity_ultra::time;
use pic32ck_curiosity_ultra::uart::Uart;
use static_cell::StaticCell;

pic32ck_curiosity_ultra::boot!();

bind_interrupts!(struct Irqs {
    USBHS => usbhs::InterruptHandler;
});

/// Full speed instead (`USBHS_FULL_SPEED=1`), and the bulk endpoints'
/// packet size: 512 at high speed, 64 at full.
const FULL_SPEED: bool = option_env!("USBHS_FULL_SPEED").is_some();
const PACKET: u16 = if FULL_SPEED { 64 } else { 512 };
/// The driver's DMA for the bulk packets (`USBHS_DMA=1`).
const USE_DMA: bool = option_env!("USBHS_DMA").is_some();

/// A packet buffer on a word boundary.
#[repr(C, align(4))]
struct Aligned([u8; PACKET as usize]);

/// The bus's events, to the log.
struct Events;

impl Handler for Events {
    fn enabled(&mut self, enabled: bool) {
        POWERED.store(enabled, Ordering::Relaxed);
        let _ = writeln!(Uart, "bus: power {}", if enabled { "detected" } else { "removed" });
    }

    fn reset(&mut self) {
        let _ = writeln!(Uart, "bus: reset");
    }

    fn configured(&mut self, configured: bool) {
        let _ = writeln!(Uart, "bus: configured {configured}, high speed {}", usbhs::is_high_speed());
    }

    fn suspended(&mut self, suspended: bool) {
        if suspended { &SUSPENDS } else { &RESUMES }.fetch_add(1, Ordering::Relaxed);
        let _ = writeln!(Uart, "bus: {}", if suspended { "suspended" } else { "resumed" });
    }

    fn remote_wakeup_enabled(&mut self, enabled: bool) {
        let _ = writeln!(Uart, "bus: remote wakeup enabled {enabled}");
    }
}

/// Bytes read, bytes echoed, and zero-length packets sent.
static RECEIVED: AtomicUsize = AtomicUsize::new(0);
static ECHOED: AtomicUsize = AtomicUsize::new(0);
static ZLPS: AtomicUsize = AtomicUsize::new(0);
/// Whether VBUS is there (embassy-usb still counts a device suspended
/// when its cable goes).
static POWERED: AtomicBool = AtomicBool::new(false);
/// Suspends, resumes, and remote wakeups sent, for the log (which a
/// sleeping host doesn't read).
static SUSPENDS: AtomicUsize = AtomicUsize::new(0);
static RESUMES: AtomicUsize = AtomicUsize::new(0);
static WAKEUPS: AtomicUsize = AtomicUsize::new(0);
static EVENTS: StaticCell<Events> = StaticCell::new();

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let peripherals = pic32ck_curiosity_ultra::init();
    time::init(cortex_m::Peripherals::take().unwrap());
    let mut log = Uart::init(peripherals.SERCOM5, peripherals.PA24, peripherals.PA25);
    let _ = writeln!(log, "\npic32ck-curiosity-ultra usbhs_echo: CPU {} Hz", pic32c_hal::clocks::generator_hz(0).unwrap_or(0));
    // SAFETY: CAL OTP, always readable.
    let trim = unsafe { core::ptr::read_volatile(0x0A00_718C as *const u32) };
    let _ = writeln!(log, "PHY trim (FCCFG67) {trim:#010x}");
    let mut usbhs_config = usbhs::Config::default();
    usbhs_config.high_speed = !FULL_SPEED;
    usbhs_config.dma = USE_DMA;
    let driver = usbhs::Driver::new(peripherals.USBHS, Irqs, usbhs_config);
    let _ = writeln!(log, "PHY ready; {}", registers());
    // A test VID/PID (pid.codes' test range; usb_echo is 000A).
    let mut config = Config::new(0x1209, 0x000B);
    config.manufacturer = Some("Aeolionics");
    config.product = Some("PIC32CK USB HS echo");
    config.serial_number = Some("pic32ck-curiosity-ultra-hs");
    config.max_power = 100;
    config.max_packet_size_0 = 64;
    config.supports_remote_wakeup = true;
    // The class's bulk packets: 512 bytes at high speed.
    config.max_speed = if FULL_SPEED { UsbDeviceSpeed::Full } else { UsbDeviceSpeed::High };

    let mut config_descriptor = [0; 256];
    let mut bos_descriptor = [0; 256];
    let mut control_buf = [0; 64];
    let mut state = State::new();
    let mut builder = Builder::new(driver, config, &mut config_descriptor, &mut bos_descriptor, &mut [], &mut control_buf);
    builder.handler(EVENTS.init(Events));
    let mut class = CdcAcmClass::new(&mut builder, &mut state, cdc_acm::Config::new());
    let mut usb = builder.build();
    let _ = writeln!(log, "USB device built; attaching");

    let echo = async {
        loop {
            class.wait_connection().await;
            let _ = writeln!(Uart, "connected, high speed: {}", usbhs::is_high_speed());
            // On a word boundary, so the driver's DMA can take it.
            let mut aligned = Aligned([0; PACKET as usize]);
            let buf = &mut aligned.0;
            let mut full = false;
            loop {
                // After a full packet, a quiet 200 µs ends the transfer.
                let read = if full {
                    match select(class.read_packet(buf), Timer::after_micros(200)).await {
                        Either::First(read) => read,
                        Either::Second(()) => {
                            full = false;
                            if class.write_packet(&[]).await.is_err() {
                                break;
                            }
                            ZLPS.fetch_add(1, Ordering::Relaxed);
                            continue;
                        }
                    }
                } else {
                    class.read_packet(buf).await
                };
                match read {
                    Ok(n) => {
                        RECEIVED.fetch_add(n, Ordering::Relaxed);
                        if class.write_packet(&buf[..n]).await.is_err() {
                            break;
                        }
                        full = n == usize::from(PACKET);
                        ECHOED.fetch_add(n, Ordering::Relaxed);
                    }
                    Err(EndpointError::BufferOverflow) => {}
                    Err(_) => break,
                }
            }
            let _ = writeln!(Uart, "disconnected");
        }
    };
    // Once a second: the controller's state and the bytes echoed so far.
    let watch = async {
        loop {
            Timer::after_secs(1).await;
            let _ = writeln!(
                Uart,
                "{} received {} echoed {} zlps {} suspends {} resumes {} wakeups {}",
                registers(),
                RECEIVED.load(Ordering::Relaxed),
                ECHOED.load(Ordering::Relaxed),
                ZLPS.load(Ordering::Relaxed),
                SUSPENDS.load(Ordering::Relaxed),
                RESUMES.load(Ordering::Relaxed),
                WAKEUPS.load(Ordering::Relaxed)
            );
        }
    };
    // Suspended for 5 s without a resume, still powered: wake the host, if
    // it let us.
    let run = async {
        loop {
            usb.run_until_suspend().await;
            if let Either::Second(()) = select(usb.wait_resume(), Timer::after_secs(5)).await
                && POWERED.load(Ordering::Relaxed)
            {
                let result = usb.remote_wakeup().await;
                if result.is_ok() {
                    WAKEUPS.fetch_add(1, Ordering::Relaxed);
                }
                let _ = writeln!(Uart, "remote wakeup: {result:?}");
            }
        }
    };
    embassy_futures::join::join3(run, echo, watch).await;
}

/// The wrapper's STATUS and INTFLAG, the core's POWR, DEVCTL, FADDR and
/// endpoint 0's CSR0, for the log.
fn registers() -> Registers {
    let r8 = |offset: usize| unsafe { core::ptr::read_volatile((0x4600_0000 + offset) as *const u8) };
    let r32 = |offset: usize| unsafe { core::ptr::read_volatile((0x4600_0000 + offset) as *const u32) };
    Registers {
        status: r32(0x18),
        intflag: r32(0x14),
        powr: r8(0x1001),
        devctl: r8(0x1060),
        faddr: r8(0x1000),
        raminfo: r8(0x1079),
    }
}

struct Registers {
    status: u32,
    intflag: u32,
    powr: u8,
    devctl: u8,
    faddr: u8,
    raminfo: u8,
}

impl core::fmt::Display for Registers {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        write!(
            f,
            "usbhs: STATUS {:#04x} INTFLAG {:#04x} POWR {:#04x} DEVCTL {:#04x} FADDR {} RAMINFO {:#04x}",
            self.status, self.intflag, self.powr, self.devctl, self.faddr, self.raminfo
        )
    }
}
