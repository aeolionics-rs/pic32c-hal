//! `pic32c-hal`'s `time`, the embassy-time driver (on TCC0, or the TCC a
//! `pic32c-hal/time-driver-tccN` feature names when building), under test:
//! - a crossing: if the count reaches a multiple of 2^31 within 30 s, timers
//!   of 37 µs back to back for half a second either side of it, and one
//!   timer at the crossing itself;
//! - `Instant::now`: its cost, and the tick rate against the CPU's cycle
//!   counter for 2 s, spinning;
//! - `Timer::after` from 0 µs to 1 s, five of each;
//! - eight `Ticker`s at once, every 1 to 17 ms, for 3 s;
//! - timers 2,000 s and 4,000 s away (one armed at once, one armed by a
//!   later period) mustn't fire before one 1 s away.
//!
//! No timer may wake early or more than [`LATE_US`] late, and `now` mustn't go
//! back. The count starts at 0, or at `TIMER_START` (hex, read when building)
//! to put a crossing within reach: `7FB3B4C0` is 5 s before 2^31, `FFB3B4C0`
//! 5 s before 2^32. Results go out over the virtual COM port, each line with
//! the count, so the host's timestamps check the rate; LED0 blinks slowly when
//! all passed, fast on a failure.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;
use core::sync::atomic::{AtomicU32, Ordering};

use pic32ck_curiosity_ultra::uart::Uart;
use pic32ck_curiosity_ultra::time;
use embassy_executor::Spawner;
use embassy_futures::join::join;
use embassy_futures::select::{Either, select};
use embassy_time::{Duration, Instant, Ticker, Timer};
use panic_halt as _;
use pic32c_hal::gpio::{Level, Output};

pic32ck_curiosity_ultra::boot!();

/// Where the count starts.
const START: u32 = match option_env!("TIMER_START") {
    Some(hex) => match u32::from_str_radix(hex, 16) {
        Ok(start) => start,
        Err(_) => panic!("TIMER_START must be hex"),
    },
    None => 0,
};
/// The latest a timer may wake, in µs (ticks).
const LATE_US: u64 = 50;
/// The latest a ticker may wake: when all eight fall due together the
/// executor polls them one after another, at about 6 µs each.
const TICKER_LATE_US: u64 = LATE_US + 8 * 10;
const HALF: u64 = 1 << 31;

/// The tickers' periods, in ms.
const PERIODS: [u64; 8] = [1, 2, 3, 5, 7, 11, 13, 17];
const TICKER_RUN_MS: u64 = 3000;
static TICKS: [AtomicU32; 8] = [const { AtomicU32::new(0) }; 8];
static TICKER_LATEST: [AtomicU32; 8] = [const { AtomicU32::new(0) }; 8];
static TICKER_EARLY: AtomicU32 = AtomicU32::new(0);

fn ticks() -> u64 {
    Instant::now().as_ticks()
}

#[embassy_executor::main]
async fn main(spawner: Spawner) {
    let peripherals = pic32ck_curiosity_ultra::init_at(START);
    let led = Output::new(peripherals.PD20, Level::High);
    time::init(cortex_m::Peripherals::take().unwrap());
    let mut log = Uart::init(peripherals.SERCOM5, peripherals.PA24, peripherals.PA25);
    let _ = writeln!(log, "\npic32ck-curiosity-ultra timer: CPU {} Hz, start {START:#010x}", pic32c_hal::clocks::generator_hz(0).unwrap_or(0));
    let _ = writeln!(log, "[{}] started", ticks());

    let mut failures = 0;
    // The executor's own cost, against a timer already due.
    let before = time::cycles();
    for _ in 0..100 {
        embassy_futures::yield_now().await;
    }
    let yield_cycles = (time::cycles() - before) / 100;
    let before = time::cycles();
    for _ in 0..100 {
        Timer::after_ticks(0).await;
    }
    let due_cycles = (time::cycles() - before) / 100;
    let _ = writeln!(log, "yield_now {yield_cycles} cycles, Timer::after_ticks(0) {due_cycles} cycles");
    failures += crossing(&mut log).await;
    failures += now_and_rate(&mut log);
    failures += after(&mut log).await;
    failures += tickers(&mut log, spawner).await;
    failures += far(&mut log).await;

    let _ = writeln!(log, "[{}] cycle counter {} µs since start", ticks(), time::micros());
    if failures == 0 {
        let _ = writeln!(log, "timer: all passed");
    } else {
        let _ = writeln!(log, "timer: {failures} failures");
    }
    halt(&mut log, failures, led).await;
}

async fn halt(log: &mut Uart, failures: u32, mut led: Output<'static>) -> ! {
    log.flush();
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after_millis(period).await;
    }
}

/// Timers back to back across the next multiple of 2^31, if it's near.
async fn crossing(log: &mut Uart) -> u32 {
    let now = ticks();
    let at = (now / HALF + 1) * HALF;
    if at - now > 30_000_000 {
        let _ = writeln!(log, "[{now}] crossing: none within 30 s (next at {at:#x})");
        return 0;
    }
    let _ = writeln!(log, "[{now}] crossing at {at:#x}: waiting");
    Timer::at(Instant::from_ticks(at - 500_000)).await;
    let mut failures = 0;
    let (mut count, mut latest, mut last) = (0u32, 0u64, 0u64);
    let mut backwards = 0u32;
    let back_to_back = async {
        while ticks() < at + 500_000 {
            let due = ticks() + 37;
            Timer::at(Instant::from_ticks(due)).await;
            let woke = ticks();
            if woke < due || woke < last {
                backwards += 1;
            }
            latest = latest.max(woke.saturating_sub(due));
            last = woke;
            count += 1;
        }
    };
    let exact = async {
        Timer::at(Instant::from_ticks(at)).await;
        ticks().checked_sub(at)
    };
    let ((), exact_late) = join(back_to_back, exact).await;
    let _ = writeln!(log, "[{}] crossing: {count} timers, latest {latest} µs, {backwards} early or backwards; the one at the crossing {exact_late:?} µs late", ticks());
    if backwards != 0 || latest > LATE_US || exact_late.is_none_or(|late| late > LATE_US) {
        failures += 1;
    }
    failures
}

/// `now`'s cost, and the tick rate against the cycle counter, spinning (the
/// cycle counter may stop while the CPU sleeps).
fn now_and_rate(log: &mut Uart) -> u32 {
    let mut failures = 0;
    let before = time::cycles();
    for _ in 0..1000 {
        core::hint::black_box(Instant::now());
    }
    let cost = (time::cycles() - before) / 1000;

    let (start_ticks, start_us) = (ticks(), time::micros());
    let (mut last, mut backwards) = (start_ticks, 0u32);
    while time::micros() - start_us < 2_000_000 {
        let now = ticks();
        if now < last {
            backwards += 1;
        }
        last = now;
    }
    let (elapsed_ticks, elapsed_us) = (ticks() - start_ticks, time::micros() - start_us);
    let difference = elapsed_ticks.abs_diff(elapsed_us);
    let _ = writeln!(log, "[{}] now: {cost} cycles a call; {elapsed_ticks} ticks in {elapsed_us} µs of cycles, {backwards} backwards", ticks());
    if backwards != 0 || difference > 3 {
        failures += 1;
    }
    failures
}

/// `Timer::after`, from 0 µs to 1 s.
async fn after(log: &mut Uart) -> u32 {
    let mut failures = 0;
    for micros in [0, 1, 10, 100, 1000, 10_000, 100_000, 1_000_000] {
        let (mut latest, mut early) = (0u64, 0u32);
        let (mut slept_ticks, mut slept_us) = (0u64, 0u64);
        for _ in 0..5 {
            let (start, start_us) = (ticks(), time::micros());
            Timer::after_micros(micros).await;
            let woke = ticks();
            slept_ticks += woke - start;
            slept_us += time::micros() - start_us;
            if woke < start + micros {
                early += 1;
            }
            latest = latest.max(woke.saturating_sub(start + micros));
        }
        let _ = writeln!(log, "[{}] after {micros} µs: latest {latest} µs late, {early} early; cycle counter saw {slept_us} µs of {slept_ticks}", ticks());
        if early != 0 || latest > LATE_US {
            failures += 1;
        }
    }
    failures
}

#[embassy_executor::task(pool_size = 8)]
async fn ticker(index: usize, end: Instant) {
    let period = Duration::from_millis(PERIODS[index]);
    let mut ticker = Ticker::every(period);
    let mut due = Instant::now() + period;
    while due <= end {
        ticker.next().await;
        let now = Instant::now();
        if now < due {
            TICKER_EARLY.fetch_add(1, Ordering::Relaxed);
        }
        #[expect(clippy::cast_possible_truncation, reason = "lateness in µs, well under 2^32")]
        let late = now.saturating_duration_since(due).as_micros() as u32;
        TICKER_LATEST[index].fetch_max(late, Ordering::Relaxed);
        TICKS[index].fetch_add(1, Ordering::Relaxed);
        due += period;
    }
}

/// Eight tickers at once.
async fn tickers(log: &mut Uart, spawner: Spawner) -> u32 {
    let mut failures = 0;
    let end = Instant::now() + Duration::from_millis(TICKER_RUN_MS);
    for index in 0..PERIODS.len() {
        spawner.spawn(ticker(index, end).unwrap());
    }
    Timer::at(end + Duration::from_millis(50)).await;
    for (index, period) in PERIODS.iter().enumerate() {
        let (count, latest) = (TICKS[index].load(Ordering::Relaxed), TICKER_LATEST[index].load(Ordering::Relaxed));
        let expected = TICKER_RUN_MS / period;
        let _ = writeln!(log, "[{}] ticker every {period} ms: {count} ticks of {expected}, latest {latest} µs late", ticks());
        if u64::from(count).abs_diff(expected) > 1 || u64::from(latest) > TICKER_LATE_US {
            failures += 1;
        }
    }
    let early = TICKER_EARLY.load(Ordering::Relaxed);
    if early != 0 {
        let _ = writeln!(log, "tickers: {early} early");
        failures += 1;
    }
    failures
}

/// Far timers mustn't fire before a near one.
async fn far(log: &mut Uart) -> u32 {
    let mut failures = 0;
    for secs in [2000, 4000] {
        let start = ticks();
        let first = select(Timer::after_secs(secs), Timer::after_secs(1)).await;
        let took = ticks() - start;
        let near = matches!(first, Either::Second(()));
        let _ = writeln!(log, "[{}] {secs} s against 1 s: {} first, after {took} µs", ticks(), if near { "1 s" } else { "the far one" });
        if !near || took.abs_diff(1_000_000) > LATE_US {
            failures += 1;
        }
    }
    failures
}
