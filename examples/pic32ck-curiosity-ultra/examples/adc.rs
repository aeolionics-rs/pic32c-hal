//! `pic32c-hal`'s `adc` against what the chip has inside:
//!
//! - the factory calibration (FCCFG65's CALCTRL, FCCFG69-71's readings);
//! - the 1.2 V bandgap, 64 reads: its spread, and AVDD worked out from it
//!   (3.3 V on the boards, within 5 %);
//! - the temperature sensor, read after it settles, and the factory's
//!   calibration applied (reported, not checked: the readings don't match
//!   the calibration yet);
//! - the bandgap at 10 and 8 bits: on the 12-bit scale with the low 2 and
//!   4 bits zero, within a step of the 12-bit reading;
//!   reading within a count or two;
//! - a read's time, short and long sample times, blocking and async;
//! - the Arduino header's analog pins A0-A2, A4, A5 (PA12, PA09, PA10,
//!   PB00, PA11) as they are, for a look; built with `ADC_JUMPERS=1`, A1
//!   jumpered to 3V3 must read full scale (4090 or more) and A2 jumpered to
//!   GND zero (5 or less), at short and long sample times.
//!
//! - built with `ADC_VREF=external` (J302 powered, so the board's MCP1501
//!   gives 2.048 V on PB01): the bandgap and the temperature sensor in
//!   millivolts against it, beside the same against AVDD (reported).
//!
//! Over the virtual COM port; LED0 blinks slowly when all passed, fast on a
//! failure.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;

use embassy_executor::Spawner;
use embassy_time::{Duration, Timer};
use panic_halt as _;
use pic32c_hal::adc::{self, Adc, AdcChannel, Calibration, Resolution, SampleTime};
use pic32c_hal::bind_interrupts;
use pic32c_hal::gpio::{Level, Output};
use pic32ck_curiosity_ultra::time;
use pic32ck_curiosity_ultra::uart::Uart;

pic32ck_curiosity_ultra::boot!();

bind_interrupts!(struct Irqs {
    ADC_CORE1 => adc::InterruptHandler;
});

/// The MCP1501 powered (J302) for the external-reference readings, if
/// `ADC_VREF=external` when building.
const EXTERNAL: bool = match option_env!("ADC_VREF") {
    Some(value) => matches!(value.as_bytes(), b"external"),
    None => false,
};

/// A1 to 3V3 and A2 to GND, if `ADC_JUMPERS=1` when building.
const JUMPERS: bool = match option_env!("ADC_JUMPERS") {
    Some(value) => matches!(value.as_bytes(), [b'1']),
    None => false,
};

struct Tests<'a> {
    log: &'a mut Uart,
    failures: u32,
}

impl Tests<'_> {
    fn check(&mut self, name: &str, good: bool, detail: core::fmt::Arguments<'_>) {
        let _ = writeln!(self.log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        self.failures += u32::from(!good);
    }
}

/// The least, mean and most of `n` reads.
fn spread(n: u32, mut read: impl FnMut() -> u16) -> (u16, u32, u16) {
    let (mut least, mut most, mut sum) = (u16::MAX, 0, 0u32);
    for _ in 0..n {
        let v = read();
        least = least.min(v);
        most = most.max(v);
        sum += u32::from(v);
    }
    (least, sum / n, most)
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let mut p = pic32ck_curiosity_ultra::init();
    time::init(cortex_m::Peripherals::take().unwrap());
    let mut log = Uart::init(p.SERCOM5, p.PA24, p.PA25);
    let mut led = Output::new(p.PD20, Level::High);
    let _ = writeln!(log, "\npic32ck-curiosity-ultra adc");
    // SAFETY: the CAL OTP, read only.
    let fccfg65 = unsafe { core::ptr::read_volatile(0x0A00_7184 as *const u32) };
    let cal = Calibration::read();
    let _ = writeln!(log, "FCCFG65 (CALCTRL) {fccfg65:#010x}; {cal:?}");
    let mut t = Tests { log: &mut log, failures: 0 };

    let start = time::micros();
    let mut adc = match Adc::new_blocking(p.ADC.reborrow(), adc::Config::default()) {
        Ok(adc) => adc,
        Err(e) => {
            t.check("setup", false, format_args!("{e:?}"));
            loop {
                Timer::after(Duration::from_secs(1)).await;
            }
        }
    };
    let us = time::micros() - start;
    let _ = writeln!(t.log, "set up in {us} us");

    // The bandgap.
    let mut vref = adc.enable_vrefint();
    let (least, bandgap, most) = spread(64, || adc.blocking_read(&mut vref, SampleTime::LONG));
    #[expect(clippy::cast_possible_truncation, reason = "a 12-bit mean")]
    let avdd = cal.millivolts(bandgap as u16).unwrap_or(0);
    t.check(
        "bandgap",
        most - least <= 12 && (3135..=3465).contains(&avdd),
        format_args!("{least}..{most}, mean {bandgap} (factory {}): AVDD {avdd} mV", cal.room_bandgap),
    );

    // The temperature sensor.
    let mut temperature = adc.enable_temperature();
    Timer::after(Duration::from_millis(150)).await;
    let (least, ptat, most) = spread(64, || adc.blocking_read(&mut temperature, SampleTime::LONG));
    #[expect(clippy::cast_possible_truncation, reason = "a 12-bit mean")]
    let decidegrees = cal.celsius(ptat as u16, avdd).unwrap_or(i32::MIN);
    let _ = writeln!(
        t.log,
        "temperature (not checked): {least}..{most}, mean {ptat} (factory {} at 25 C): {}.{} C",
        cal.room_ptat,
        decidegrees / 10,
        decidegrees.rem_euclid(10)
    );

    // Times.
    let mut time_read = |sample: SampleTime| {
        let start = time::micros();
        for _ in 0..100 {
            let _ = adc.blocking_read(&mut vref, sample);
        }
        time::micros() - start
    };
    let short = time_read(SampleTime::SHORT);
    let long = time_read(SampleTime::LONG);
    let _ = writeln!(t.log, "100 reads: {short} us with SHORT, {long} us with LONG");

    // The header's pins, for a look.
    let mut pins = [
        p.PA12.reborrow().degrade_adc(),
        p.PA09.reborrow().degrade_adc(),
        p.PA10.reborrow().degrade_adc(),
        p.PB00.reborrow().degrade_adc(),
        p.PA11.reborrow().degrade_adc(),
    ];
    for (name, pin) in ["A0", "A1", "A2", "A4", "A5"].iter().zip(pins.iter_mut()) {
        let (least, mean, most) = spread(16, || adc.blocking_read(pin, SampleTime::SHORT));
        let _ = writeln!(t.log, "{name} AIN{}: {least}..{most}, mean {mean}", pin.channel());
    }
    if JUMPERS {
        for sample in [SampleTime::SHORT, SampleTime::LONG] {
            let (high_least, high, _) = spread(64, || adc.blocking_read(&mut pins[1], sample));
            let (_, low, low_most) = spread(64, || adc.blocking_read(&mut pins[2], sample));
            t.check(
                "jumpers",
                high_least >= 4090 && low_most <= 5,
                format_args!("sample {}: A1 at 3V3 {high_least}.. mean {high}, A2 at GND ..{low_most} mean {low}", sample.0),
            );
        }
    }
    drop(adc);

    // Resolutions.
    for (resolution, shift) in [(Resolution::Bits10, 2), (Resolution::Bits8, 4)] {
        let mut config = adc::Config::default();
        config.resolution = resolution;
        let mut adc = Adc::new_blocking(p.ADC.reborrow(), config).unwrap();
        let mut vref = adc.enable_vrefint();
        let mut low = 0u16;
        let (_, mean, _) = spread(64, || {
            let v = adc.blocking_read(&mut vref, SampleTime::LONG);
            low |= v & ((1 << shift) - 1);
            v
        });
        let step = 1u32 << shift;
        t.check(
            "resolution",
            low == 0 && mean.abs_diff(bandgap) <= step,
            format_args!("{} bits: bandgap mean {mean}, low {shift} bits {low:#x}, 12 bits' {bandgap}", resolution.bits()),
        );
    }

    // Async.
    let mut adc = Adc::new(p.ADC.reborrow(), Irqs, adc::Config::default()).unwrap();
    let mut vref = adc.enable_vrefint();
    let start = time::micros();
    let mut sum = 0u32;
    for _ in 0..64 {
        sum += u32::from(adc.read(&mut vref, SampleTime::LONG).await);
    }
    let us = time::micros() - start;
    let mean = sum / 64;
    t.check("async", mean.abs_diff(bandgap) <= 4, format_args!("bandgap mean {mean} over 64 reads in {us} us"));
    drop(adc);

    // With `ADC_VREF=external`: the bandgap and the temperature sensor
    // against the board's MCP1501 (2.048 V, 0.1 %, on PB01 once J302 is
    // powered), in millivolts, beside the same against AVDD. Reported.
    if EXTERNAL {
        pic32c_hal::gpio::set_as_function(p.PB01.reborrow(), pic32c_hal::gpio::Function::B);
        let mut both = [[0u32; 2]; 2];
        for (k, reference) in [adc::Reference::Avdd, adc::Reference::External].into_iter().enumerate() {
            let mut config = adc::Config::default();
            config.reference = reference;
            let mut adc = Adc::new_blocking(p.ADC.reborrow(), config).unwrap();
            let mut vref = adc.enable_vrefint();
            let mut sensor = adc.enable_temperature();
            Timer::after(Duration::from_millis(200)).await;
            let (_, b, _) = spread(256, || adc.blocking_read(&mut vref, SampleTime::LONG));
            let (_, s, _) = spread(256, || adc.blocking_read(&mut sensor, SampleTime::LONG));
            both[k] = [b, s];
        }
        let [[b_avdd, s_avdd], [b_ext, s_ext]] = both;
        // Against 2.048 V: millivolts = counts × 2048 / 4096.
        let (b_mv, s_mv) = (b_ext / 2, s_ext / 2);
        let avdd_mv = b_mv * 4096 / b_avdd.max(1);
        // What the factory's readings were in millivolts (against 3299 mV).
        let factory = |counts: u16| u32::from(counts) * u32::from(cal.reference_mv) / 4095;
        let _ = writeln!(
            t.log,
            "against AVDD: bandgap {b_avdd}, sensor {s_avdd}; against the MCP1501: bandgap {b_ext} ({b_mv} mV), sensor {s_ext} ({s_mv} mV); so AVDD is {avdd_mv} mV, and the sensor against AVDD reads {} mV",
            s_avdd * avdd_mv / 4096
        );
        let _ = writeln!(
            t.log,
            "the factory's: bandgap {} mV, sensor {} mV at {} C and {} mV at {} C",
            factory(cal.room_bandgap),
            factory(cal.room_ptat),
            cal.room_decidegrees / 10,
            factory(cal.hot_ptat),
            cal.hot_decidegrees / 10
        );
    }

    let failures = t.failures;
    let _ = if failures == 0 { writeln!(log, "adc: all passed") } else { writeln!(log, "adc: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
