/// Full speed's echo: 64-byte packets back as they come.
#[embassy_executor::task]
async fn fs_echo(mut class: CdcAcmClass<'static, FsDriver>) -> ! {
    loop {
        class.wait_connection().await;
        FS.connects.fetch_add(1, Ordering::Relaxed);
        let mut buf = [0; 64];
        loop {
            match class.read_packet(&mut buf).await {
                Ok(n) => {
                    if class.write_packet(&buf[..n]).await.is_err() {
                        break;
                    }
                    FS.bytes.fetch_add(n, Ordering::Relaxed);
                    // A packet can be ready at once, over and over, and a
                    // task only gives way when it waits.
                    yield_now().await;
                }
                Err(EndpointError::BufferOverflow) => {}
                Err(_) => break,
            }
        }
    }
}

/// High speed's echo, ending a transfer that stops on a full packet with a
/// zero-length one.
#[embassy_executor::task]
async fn hs_echo(mut class: CdcAcmClass<'static, HsDriver>) -> ! {
    loop {
        class.wait_connection().await;
        HS.connects.fetch_add(1, Ordering::Relaxed);
        let mut buf = [0; 512];
        let mut full = false;
        loop {
            let read = if full {
                match select(class.read_packet(&mut buf), Timer::after_micros(200)).await {
                    Either::First(read) => read,
                    Either::Second(()) => {
                        full = false;
                        if class.write_packet(&[]).await.is_err() {
                            break;
                        }
                        HS.zlps.fetch_add(1, Ordering::Relaxed);
                        continue;
                    }
                }
            } else {
                class.read_packet(&mut buf).await
            };
            match read {
                Ok(n) => {
                    if class.write_packet(&buf[..n]).await.is_err() {
                        break;
                    }
                    full = n == buf.len();
                    HS.bytes.fetch_add(n, Ordering::Relaxed);
                    // As in `fs_echo`: under a stream the next packet is
                    // already there, and the other tasks would starve.
                    yield_now().await;
                }
                Err(EndpointError::BufferOverflow) => {}
                Err(_) => break,
            }
        }
    }
}

/// The echo of a test frame: its standard identifier with bit 10 set, same
/// length and data; none for anything else.
fn can_echo(frame: &Frame) -> Option<Frame> {
    let Frame::Can(can) = frame else { return None };
    let CanId::Standard(id) = can.id() else { return None };
    if id & 0x400 != 0 || can.is_remote_frame() {
        return None;
    }
    CanFrame::new_with_dlc(CanId::new_standard(id | 0x400)?, can.data(), can.dlc()).map(Frame::Can)
}

/// CAN0: echoes the test frames, counts the rest, and keeps the bus state
/// and error counters for the report.
#[embassy_executor::task]
async fn can_task(mut can: can0::Channel) -> ! {
    // Echoes waiting for a transmit buffer.
    let mut pending: heapless::Deque<Frame, 64> = heapless::Deque::new();
    loop {
        // An event, or a second without one (to refresh the counters).
        if let Either::First(event) = select(can.next_event(), Timer::after_secs(1)).await {
            match event {
                Event::Received(frame) => match frame.frame().id() {
                    CanId::Standard(id) if id & 0x400 == 0 => {
                        CAN_TEST.fetch_add(1, Ordering::Relaxed);
                        if let Some(reply) = can_echo(frame.frame())
                            && pending.push_back(reply).is_err()
                        {
                            CAN_DROPPED.fetch_add(1, Ordering::Relaxed);
                        }
                    }
                    CanId::Standard(_) => {
                        CAN_OTHER_STD.fetch_add(1, Ordering::Relaxed);
                    }
                    CanId::Extended(_) => {
                        CAN_EXTENDED.fetch_add(1, Ordering::Relaxed);
                    }
                },
                Event::Transmitted { outcome, .. } => {
                    if let Outcome::Sent(_) = outcome { &CAN_SENT } else { &CAN_FAILED }.fetch_add(1, Ordering::Relaxed);
                }
                Event::BusStateChanged(_) => {
                    CAN_STATE_CHANGES.fetch_add(1, Ordering::Relaxed);
                }
            }
        }
        while let Some(reply) = pending.front() {
            if ConfirmedTransmit::<Frame>::try_transmit(&mut can, reply).is_err() {
                break;
            }
            pending.pop_front();
        }
        let state = match can.bus_state() {
            Ok(BusState::ErrorActive) => 0,
            Ok(BusState::ErrorPassive) => 1,
            Ok(BusState::BusOff) => 2,
            _ => 3,
        };
        CAN_STATE.store(state, Ordering::Relaxed);
        if let Ok(counters) = can.error_counters() {
            CAN_TEC.store(u32::from(counters.transmit), Ordering::Relaxed);
            CAN_REC.store(u32::from(counters.receive), Ordering::Relaxed);
        }
    }
}

/// One echo connection at a time on port 7.
async fn tcp_echo(stack: Stack<'_>) -> ! {
    let mut rx = [0; 2048];
    let mut tx = [0; 2048];
    let listener = net::listen(stack, 7);
    loop {
        let Ok(mut socket) = net::accept(stack, &listener, &mut rx, &mut tx).await else { continue };
        ECHO_CONNECTS.fetch_add(1, Ordering::Relaxed);
        socket.set_timeout(Some(Duration::from_secs(10)));
        let mut buffer = [0; 1024];
        loop {
            match socket.read(&mut buffer).await {
                Ok(0) | Err(_) => break,
                Ok(n) => {
                    if socket.write_all(&buffer[..n]).await.is_err() {
                        break;
                    }
                    ECHO_BYTES.fetch_add(n, Ordering::Relaxed);
                    yield_now().await;
                }
            }
        }
        let _ = socket.flush().await;
        socket.close();
    }
}

/// One HTTP connection at a time from port 80's `listener`, Nagle off as in
/// `eth_http`.
async fn http<'d, P: picoserve::routing::PathRouter>(app: &picoserve::Router<P>, stack: Stack<'d>, listener: &net::SharedListener<'d>) -> ! {
    let mut rx = [0; 2048];
    let mut tx = [0; 8192];
    let mut buffer = [0; 2048];
    loop {
        let Ok(mut socket) = net::accept(stack, listener, &mut rx, &mut tx).await else { continue };
        HTTP_CONNECTS.fetch_add(1, Ordering::Relaxed);
        socket.set_nagle_enabled(false);
        socket.set_keep_alive(Some(Duration::from_secs(30)));
        socket.set_timeout(Some(Duration::from_secs(45)));
        let _ = picoserve::Server::new(app, &CONFIG, &mut buffer).serve(socket).await;
    }
}

/// `/status`: the report line.
fn status(iface: Iface<'static>) -> impl IntoResponse {
    let mut text = heapless::String::<1024>::new();
    let _ = writeln!(text, "{}", Report(Some(iface)));
    text
}

/// The soak's counters on one line.
struct Report(Option<Iface<'static>>);

impl core::fmt::Display for Report {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        let load = |a: &AtomicU32| a.load(Ordering::Relaxed);
        write!(f, "up {} s", Instant::now().as_secs())?;
        for (name, usb) in [("fs", &FS), ("hs", &HS)] {
            write!(
                f,
                " | {name} conn {} bytes {} zlp {} reset {} config {} susp {} res {}",
                load(&usb.connects),
                usb.bytes.load(Ordering::Relaxed),
                load(&usb.zlps),
                load(&usb.resets),
                load(&usb.configs),
                load(&usb.suspends),
                load(&usb.resumes)
            )?;
        }
        // The full-speed controller's FSM state, STATUS (speed, line state),
        // INTFLAG, INTEN, CTRLB and address, and endpoint 0's STATUS and flags
        // (as `usb_echo` logs them), to see the state a stuck port is in.
        // SAFETY: USB's registers (0x4502_A000), read only.
        let r8 = |offset: usize| unsafe { core::ptr::read_volatile((0x4502_A000 + offset) as *const u8) };
        // SAFETY: as above.
        let r16 = |offset: usize| unsafe { core::ptr::read_volatile((0x4502_A000 + offset) as *const u16) };
        write!(
            f,
            " | fs regs FSM {:#04x} STATUS {:#04x} INTFLAG {:#06x} INTEN {:#06x} CTRLB {:#06x} DADD {:#04x} EP0 STATUS {:#04x} FLAG {:#04x}",
            r8(0x0D),
            r8(0x0C),
            r16(0x1C),
            r16(0x18),
            r16(0x08),
            r8(0x0A),
            r8(0x106),
            r8(0x107)
        )?;
        write!(
            f,
            " | fs reattach {} failed {} last {} ms max {} ms | late max {} us worst {} us",
            load(&REATTACHES),
            load(&REATTACH_FAILED),
            load(&REATTACH_LAST_MS),
            load(&REATTACH_MAX_MS),
            load(&LATE_MAX_US),
            load(&LATE_WORST_US)
        )?;
        if let Some(iface) = self.0 {
            write!(
                f,
                " | eth link {} v4 {:?} echo conn {} bytes {} http conn {}",
                if iface.is_link_up() { "up" } else { "down" },
                net::v4(iface).map(|cidr| cidr.address()),
                load(&ECHO_CONNECTS),
                ECHO_BYTES.load(Ordering::Relaxed),
                load(&HTTP_CONNECTS)
            )?;
            let [frames, fcs, resource, overrun] = eth_stats();
            write!(f, " rx frames {frames} fcs {fcs} no-buffer {resource} overrun {overrun}")?;
        } else {
            write!(f, " | eth none")?;
        }
        if CAN_UP.load(Ordering::Relaxed) {
            write!(
                f,
                " | can test {} sent {} failed {} dropped {} other {} ext {} state {} changes {} tec {} rec {}",
                load(&CAN_TEST),
                load(&CAN_SENT),
                load(&CAN_FAILED),
                load(&CAN_DROPPED),
                load(&CAN_OTHER_STD),
                load(&CAN_EXTENDED),
                ["active", "passive", "bus-off", "?"][load(&CAN_STATE) as usize],
                load(&CAN_STATE_CHANGES),
                load(&CAN_TEC),
                load(&CAN_REC)
            )?;
        } else {
            write!(f, " | can none")?;
        }
        Ok(())
    }
}

#[embassy_executor::main]
async fn main(spawner: Spawner) {
    let p = pic32ck_curiosity_ultra::init();
    time::init(cortex_m::Peripherals::take().unwrap());
    let mut log = Uart::init(p.SERCOM5, p.PA24, p.PA25);
    let mut led = Output::new(p.PD20, Level::High);
    let _ = writeln!(log, "\npic32ck-curiosity-ultra soak: reset cause {:#06x}", ResetCause::read().0);

    // CAN0 first: its pins and clock don't wait on anything.
    match can0::open(p.CAN0, can0::CLASSIC_RATE, Mode::Normal, p.PB16, p.PB17) {
        Ok(can) => {
            CAN_UP.store(true, Ordering::Relaxed);
            spawner.spawn(can_task(can).unwrap());
        }
        Err(e) => {
            let _ = writeln!(log, "can: {e:?}");
        }
    }

    // USB full speed on J203.
    static FS_DESCRIPTORS: StaticCell<([u8; 256], [u8; 256], [u8; 64])> = StaticCell::new();
    static FS_STATE: StaticCell<State<'static>> = StaticCell::new();
    static FS_EVENTS: StaticCell<Events> = StaticCell::new();
    let (config_descriptor, bos_descriptor, control_buf) = FS_DESCRIPTORS.init(([0; 256], [0; 256], [0; 64]));
    let driver = usb::Driver::new(p.USB, Irqs, p.PD04, p.PD03, clocks::GEN_48);
    let mut builder = Builder::new(driver, usb_config(0x000A, "PIC32CK soak FS", "pic32ck-soak-fs"), config_descriptor, bos_descriptor, &mut [], control_buf);
    builder.handler(FS_EVENTS.init(Events(&FS)));
    let class = CdcAcmClass::new(&mut builder, FS_STATE.init(State::new()), cdc_acm::Config::new());
    spawner.spawn(fs_device(builder.build()).unwrap());
    spawner.spawn(fs_echo(class).unwrap());
    spawner.spawn(lateness().unwrap());
    spawner.spawn(fs_reattach().unwrap());

    // USB high speed on J202.
    static HS_DESCRIPTORS: StaticCell<([u8; 256], [u8; 256], [u8; 64])> = StaticCell::new();
    static HS_STATE: StaticCell<State<'static>> = StaticCell::new();
    static HS_EVENTS: StaticCell<Events> = StaticCell::new();
    let (config_descriptor, bos_descriptor, control_buf) = HS_DESCRIPTORS.init(([0; 256], [0; 256], [0; 64]));
    let driver = usbhs::Driver::new(p.USBHS, Irqs, usbhs::Config::default());
    let mut config = usb_config(0x000B, "PIC32CK soak HS", "pic32ck-soak-hs");
    config.max_speed = UsbDeviceSpeed::High;
    let mut builder = Builder::new(driver, config, config_descriptor, bos_descriptor, &mut [], control_buf);
    builder.handler(HS_EVENTS.init(Events(&HS)));
    let class = CdcAcmClass::new(&mut builder, HS_STATE.init(State::new()), cdc_acm::Config::new());
    spawner.spawn(hs_device(builder.build()).unwrap());
    spawner.spawn(hs_echo(class).unwrap());

    // Ethernet: the servers run in `main` (the router isn't a nameable type).
    let id = uid::unique_id();
    let mac = [0x02, id[1], id[2], id[3], id[4], id[5]];
    let pins = Pins {
        ref_clk: p.PC00,
        mdc: p.PC03,
        mdio: p.PC04,
        crs_dv: p.PC10,
        rx_er: p.PC09,
        rxd0: p.PC07,
        rxd1: p.PC06,
        tx_en: p.PC11,
        txd0: p.PC12,
        txd1: p.PC13,
    };
    let Ok(ethernet) = Ethernet::new(p.ETH, Irqs, pins, p.PD21, QUEUE.init(PacketQueue::new()), mac, clocks::GEN_TIMER).await else {
        let _ = writeln!(log, "eth: no PHY");
        loop {
            Timer::after_secs(REPORT_SECS).await;
            let _ = writeln!(log, "{}", Report(None));
        }
    };
    let seed = u64::from_le_bytes([id[8], id[9], id[10], id[11], id[12], id[13], id[14], id[15]]);
    let (stack, runner) = Stack::new(STACK.init(StackStorage::new()), &POOL, seed);
    let iface = stack.add_iface_borrowed(ETHERNET.init(ethernet)).unwrap();
    iface.set_dhcpv4(Some(DhcpConfig::default())).unwrap();
    iface.set_slaac(Some(SlaacConfig::default())).unwrap();
    spawner.spawn(net_task(runner).unwrap());
    let _ = with_timeout(Duration::from_secs(30), iface.wait_config_up()).await;
    let _ = writeln!(log, "IPv4 {:?}; IPv6 {:?}; link-local {:?}", net::v4(iface), net::v6(iface), net::link_local(iface));

    let app = picoserve::Router::new()
        .route("/status", get(move || async move { status(iface) }))
        .route(
            "/fs-reattach",
            get(|| async {
                REATTACH_REQUEST.store(true, Ordering::Relaxed);
                "fs re-attach requested\n"
            }),
        )
        .route("/blob", get_service(picoserve::response::File::with_content_type("application/octet-stream", &BLOB)));
    let listener = net::listen(stack, 80);
    let server0 = http(&app, stack, &listener);
    let server1 = http(&app, stack, &listener);
    let report = async {
        let mut text = heapless::String::<1024>::new();
        loop {
            led.toggle();
            Timer::after_secs(REPORT_SECS).await;
            text.clear();
            let _ = write!(text, "{}", Report(Some(iface)));
            LATE_MAX_US.store(0, Ordering::Relaxed);
            log_line(&text).await;
        }
    };
    #[expect(clippy::large_futures, reason = "main's future lives in the executor's static task storage, not on a stack")]
    join4(tcp_echo(stack), server0, server1, report).await;
}
