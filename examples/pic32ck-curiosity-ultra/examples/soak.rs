/// Full speed's re-attach (`GET /fs-reattach`): asked for, done, done but
/// not configured by the host before the next, and how long the latest
/// and the slowest took from attach to configured.
static REATTACH_REQUEST: AtomicBool = AtomicBool::new(false);
static REATTACHES: AtomicU32 = AtomicU32::new(0);
static REATTACH_FAILED: AtomicU32 = AtomicU32::new(0);
static REATTACH_PENDING: AtomicBool = AtomicBool::new(false);
static REATTACH_AT_MS: AtomicU32 = AtomicU32::new(0);
static REATTACH_LAST_MS: AtomicU32 = AtomicU32::new(0);
static REATTACH_MAX_MS: AtomicU32 = AtomicU32::new(0);
/// How late a 1 ms timer fires (the executor's latency): since the last
/// counter line, and since start-up.
static LATE_MAX_US: AtomicU32 = AtomicU32::new(0);
static LATE_WORST_US: AtomicU32 = AtomicU32::new(0);

/// The Ethernet controller's receive statistics (DS60001795 32.7.2), which
/// clear on a read, added up here: frames received, FCS errors, resource
/// errors (no free receive buffer) and overruns.
static ETH_STATS: [AtomicU32; 4] = [const { AtomicU32::new(0) }; 4];
const ETH_STAT_OFFSETS: [usize; 4] = [0x1158, 0x1190, 0x11A0, 0x11A4];

fn eth_stats() -> [u32; 4] {
    let mut totals = [0; 4];
    for (i, offset) in ETH_STAT_OFFSETS.iter().enumerate() {
        // SAFETY: an ETH statistics register (base 0x4502_2000), whose read
        // only clears it.
        let count = unsafe { core::ptr::read_volatile((0x4502_2000 + offset) as *const u32) };
        totals[i] = ETH_STATS[i].fetch_add(count, Ordering::Relaxed).wrapping_add(count);
    }
    totals
}

#[expect(clippy::cast_possible_truncation, reason = "milliseconds since boot, wrapping")]
fn now_ms() -> u32 {
    Instant::now().as_millis() as u32
}

