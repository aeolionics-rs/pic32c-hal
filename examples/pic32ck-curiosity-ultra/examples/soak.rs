/// The pattern `/blob` serves: bytes 0 to 255, 256 times.
static BLOB: [u8; 65_536] = {
    let mut blob = [0; 65_536];
    let mut i = 0;
    while i < blob.len() {
        #[expect(clippy::cast_possible_truncation, reason = "the low byte")]
        let byte = i as u8;
        blob[i] = byte;
        i += 1;
    }
    blob
};

/// A USB port's bus events, counted.
struct Events(&'static UsbCounts);

impl Handler for Events {
    fn reset(&mut self) {
        self.0.resets.fetch_add(1, Ordering::Relaxed);
    }

    fn suspended(&mut self, suspended: bool) {
        if suspended { &self.0.suspends } else { &self.0.resumes }.fetch_add(1, Ordering::Relaxed);
    }

    fn configured(&mut self, configured: bool) {
        if !configured {
            return;
        }
        self.0.configs.fetch_add(1, Ordering::Relaxed);
        if core::ptr::eq(self.0, &raw const FS) && REATTACH_PENDING.swap(false, Ordering::Relaxed) {
            let ms = now_ms().wrapping_sub(REATTACH_AT_MS.load(Ordering::Relaxed));
            REATTACH_LAST_MS.store(ms, Ordering::Relaxed);
            REATTACH_MAX_MS.fetch_max(ms, Ordering::Relaxed);
        }
    }
}

/// Detaches full speed for 100 ms when `GET /fs-reattach` asks, as an
/// unplug would, so the host enumerates it again under whatever load the
/// soak has on.
#[embassy_executor::task]
async fn fs_reattach() -> ! {
    const CTRLB: *mut u16 = 0x4502_A008 as *mut u16;
    loop {
        Timer::after_millis(100).await;
        if !REATTACH_REQUEST.swap(false, Ordering::Relaxed) {
            continue;
        }
        if REATTACH_PENDING.swap(true, Ordering::Relaxed) {
            REATTACH_FAILED.fetch_add(1, Ordering::Relaxed);
        }
        REATTACHES.fetch_add(1, Ordering::Relaxed);
        // SAFETY: USB's CTRLB; DETACH is bit 0, nothing else here writes it.
        unsafe { core::ptr::write_volatile(CTRLB, core::ptr::read_volatile(CTRLB) | 1) };
        Timer::after_millis(100).await;
        // SAFETY: as above.
        unsafe { core::ptr::write_volatile(CTRLB, core::ptr::read_volatile(CTRLB) & !1) };
        REATTACH_AT_MS.store(now_ms(), Ordering::Relaxed);
    }
}

/// How late a 1 ms timer fires, the executor's latency.
#[embassy_executor::task]
async fn lateness() -> ! {
    loop {
        let start = Instant::now();
        Timer::after_millis(1).await;
        #[expect(clippy::cast_possible_truncation, reason = "microseconds, far below 2^32")]
        let late = start.elapsed().as_micros().saturating_sub(1000) as u32;
        LATE_MAX_US.fetch_max(late, Ordering::Relaxed);
        LATE_WORST_US.fetch_max(late, Ordering::Relaxed);
    }
}

/// One line to the log, giving way while the UART has no room: at 115200
/// baud a counter line takes about 50 ms, which `writeln!` would spend
/// with every other task waiting.
async fn log_line(text: &str) {
    let mut log = Uart;
    for byte in text.bytes().chain(*b"\r\n") {
        while !log.try_write_byte(byte) {
            yield_now().await;
        }
    }
}

