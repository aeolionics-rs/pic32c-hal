//! A soak test: every driver the other bench programs exercise one at a
//! time, at once, for as long as the host keeps them busy.
//!
//! - USB full speed (`usb`, J203): a CDC-ACM echo, as `usb_echo`.
//! - USB high speed (`usbhs`, J202): a CDC-ACM echo in 512-byte packets that
//!   ends a transfer after a full packet with a zero-length one when no more
//!   data follows within 200 µs, as `usbhs_echo`.
//! - Ethernet (`eth`, embassy-net): DHCP and SLAAC, a TCP echo on port 7,
//!   and picoserve on port 80, two connections at a time: `/status` the
//!   soak's counters as text, `/blob` 64 KiB of a known pattern, and
//!   `/fs-reattach`, which detaches full speed for 100 ms, as an unplug
//!   would, to see the host enumerate it again under load.
//! - CAN0 at 250 kbit/s (`can`), normal mode: every classic frame with a
//!   standard identifier whose bit 10 is clear is sent back with bit 10 set;
//!   frames with bit 10 set (echoes) and extended frames are only counted,
//!   so on a shared bus it answers nothing but its own test traffic.
//!
//! Each echo gives way to the other tasks after every packet: under a
//! stream the next packet is ready at once, and a task that never waits
//! never lets the executor run another.
//!
//! The reset cause goes to the virtual COM port at start-up, then a line of
//! counters every 10 s, so a reset shows as the uptime starting again and a
//! stuck driver as its counters standing still. The line also has full
//! speed's controller registers, how late a 1 ms timer fires (the
//! executor's latency) and the Ethernet controller's receive errors; it
//! goes out a byte at a time as the UART has room, since at 115200 baud it
//! takes about 50 ms. `tools/host/soak.py` drives
//! the USB ports and the network; something on the CAN bus has to send the
//! frames to echo.

