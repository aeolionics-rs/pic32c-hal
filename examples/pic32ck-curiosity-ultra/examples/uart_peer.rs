//! The far end for `uart_flow`, `uart_ring` and `uart_lines`: an echo that
//! drains slowly, on a second Curiosity Ultra (SG01 or GC01). SERCOM2 on the
//! EXT2 header (J501; I/O set 2: TX PC15 pin 16, RX PC16 pin 18, RTS PC17
//! pin 17, CTS PC18 pin 6), at `UART_PEER_BAUD` (decimal, read when
//! building; 1,000,000 by default), 8N1, RTS/CTS on. Wire it to the board
//! under test's EXT2 crossed (TX to RX, RTS to CTS, both ways) with GND, and
//! start it first.
//!
//! Each round waits for a byte, then gathers up to 512 bytes for at most
//! 20 ms, writes them back, and pauses 10 ms: about 50 KB/s at 1 Mbaud, half
//! the line's rate. So a burst from the far end fills its 2 KiB receive ring,
//! and the full ring leaves bytes in the SERCOM, whose RTS then holds the far
//! end; and its own transmitter stops while the far end's RTS holds it. A
//! byte on its own comes back after the 20 ms wait.
//!
//! Receive errors (the tests' controls overrun it on purpose, and send at
//! the wrong rate or parity) are counted and the echo carries on. Every 10 s
//! it logs the bytes echoed and the errors over the virtual COM port; LED0
//! blinks slowly.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;
use core::sync::atomic::{AtomicU32, Ordering};

use embassy_executor::Spawner;
use embassy_futures::join::join3;
use embassy_futures::select::{Either, select};
use embassy_time::{Duration, Instant, Timer};
use panic_halt as _;
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::uart::{self, BufferedUart, BufferedUartRx, BufferedUartTx};
use pic32c_hal::{bind_interrupts, peripherals};
use pic32ck_curiosity_ultra::time;
use pic32ck_curiosity_ultra::uart::Uart as Log;

pic32ck_curiosity_ultra::boot!();

const BAUD: u32 = match option_env!("UART_PEER_BAUD") {
    Some(text) => match u32::from_str_radix(text, 10) {
        Ok(baud) => baud,
        Err(_) => panic!("UART_PEER_BAUD must be decimal"),
    },
    None => 1_000_000,
};
/// The most taken in one round.
const CHUNK: usize = 512;
/// How long a round gathers after its first byte.
const GATHER: Duration = Duration::from_millis(20);
/// The pause after each round, which sets the drain rate.
const PAUSE: Duration = Duration::from_millis(10);

static ECHOED: AtomicU32 = AtomicU32::new(0);
static ERRORS: AtomicU32 = AtomicU32::new(0);

bind_interrupts!(struct Irqs {
    SERCOM2_0 => uart::InterruptHandler<peripherals::SERCOM2>;
    SERCOM2_1 => uart::InterruptHandler<peripherals::SERCOM2>;
    SERCOM2_2 => uart::InterruptHandler<peripherals::SERCOM2>;
    SERCOM2_56 => uart::InterruptHandler<peripherals::SERCOM2>;
});

/// Waits for a byte, then takes what comes within `GATHER`, up to `CHUNK`:
/// how many bytes. A receive error is counted and ends the round.
async fn gather(rx: &mut BufferedUartRx<'_>, buffer: &mut [u8; CHUNK]) -> usize {
    let Ok(mut n) = rx.read(buffer).await else {
        ERRORS.fetch_add(1, Ordering::Relaxed);
        return 0;
    };
    let deadline = Instant::now() + GATHER;
    while n < CHUNK {
        // `read` takes bytes only when it returns, so dropping it at the
        // deadline loses nothing.
        match select(rx.read(&mut buffer[n..]), Timer::at(deadline)).await {
            Either::First(Ok(more)) => n += more,
            Either::First(Err(_)) => {
                ERRORS.fetch_add(1, Ordering::Relaxed);
                break;
            }
            Either::Second(()) => break,
        }
    }
    n
}

async fn echo(mut tx: BufferedUartTx<'_>, mut rx: BufferedUartRx<'_>) -> ! {
    let mut buffer = [0u8; CHUNK];
    loop {
        let n = gather(&mut rx, &mut buffer).await;
        if n > 0 && tx.write_all(&buffer[..n]).await.is_ok() {
            #[expect(clippy::cast_possible_truncation, reason = "n is at most CHUNK")]
            ECHOED.fetch_add(n as u32, Ordering::Relaxed);
        }
        Timer::after(PAUSE).await;
    }
}

async fn report(log: &mut Log) -> ! {
    loop {
        Timer::after(Duration::from_secs(10)).await;
        let _ = writeln!(log, "uart_peer: {} bytes echoed, {} receive errors", ECHOED.load(Ordering::Relaxed), ERRORS.load(Ordering::Relaxed));
    }
}

async fn blink(led: &mut Output<'_>) -> ! {
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(500)).await;
    }
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32ck_curiosity_ultra::init();
    time::init(cortex_m::Peripherals::take().unwrap());
    let mut log = Log::init(p.SERCOM5, p.PA24, p.PA25);
    let mut led = Output::new(p.PD20, Level::High);
    let _ = writeln!(
        log,
        "\npic32ck-curiosity-ultra uart_peer at {BAUD} baud: up to {CHUNK} bytes a round, gathered for {} ms, then {} ms paused",
        GATHER.as_millis(),
        PAUSE.as_millis()
    );
    let mut config = uart::Config::default();
    config.baudrate = BAUD;
    let (mut tx_ring, mut rx_ring) = ([0u8; 1024], [0u8; 2048]);
    let link = match BufferedUart::new_with_rtscts(p.SERCOM2, p.PC15, p.PC16, p.PC17, p.PC18, Irqs, &mut tx_ring[..], &mut rx_ring[..], config) {
        Ok(link) => link,
        Err(e) => {
            let _ = writeln!(log, "uart_peer: can't set up: {e:?}");
            loop {
                led.toggle();
                Timer::after(Duration::from_millis(100)).await;
            }
        }
    };
    let (tx, rx) = link.split();
    let _ = join3(echo(tx, rx), report(&mut log), blink(&mut led)).await;
}
