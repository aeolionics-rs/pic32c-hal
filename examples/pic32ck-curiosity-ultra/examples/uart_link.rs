//! A UART link to another device: SERCOM2 on the EXT2 header (J501; I/O
//! set 2: TX PC15 pin 16, RX PC16 pin 18, RTS PC17 pin 17, CTS PC18 pin 6;
//! hardware flow control on), at `UART_LINK_BAUD` (decimal, read
//! when building; 1,000,000 by default). The far end either echoes (`uart_peer` on a
//! second board) or runs this program too, crossed. PC15-PC17 are also the
//! mikroBUS SPI's: don't run `spi` on a board wired this way.
//!
//! It sends a sync byte (0x7E) and a 1 KiB block of a pattern that never
//! contains it, every 100 ms, and reads what comes back (its own, echoed, or
//! the other board's): it waits for the sync byte, then reads the block. Two
//! phases of 20 blocks: a `BufferedUart` (256-byte rings, on the interrupts),
//! then a `Uart` with DMA, whose writes and block reads go by DMA. A block that comes in wrong, or not within a second, fails;
//! the first of each phase may be cut short and doesn't count. Then it
//! reports and starts again. The FIFO is on unless `UART_LINK_FIFO=0`
//! (both phases pass either way). Over the virtual COM
//! port; LED0 blinks slowly while all pass, fast after a failure.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;
use core::sync::atomic::{AtomicBool, Ordering};

use embassy_executor::Spawner;
use embassy_futures::join::join;
use embassy_futures::select::{Either, select};
use embassy_time::{Duration, Timer};
use panic_halt as _;
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::uart::{self, BufferedUart, BufferedUartRx, BufferedUartTx, Uart, UartRx, UartTx};
use pic32c_hal::{bind_interrupts, mode::Async, peripherals};
use pic32ck_curiosity_ultra::time;
use pic32ck_curiosity_ultra::uart::Uart as Log;

pic32ck_curiosity_ultra::boot!();

const BAUD: u32 = match option_env!("UART_LINK_BAUD") {
    Some(text) => match u32::from_str_radix(text, 10) {
        Ok(baud) => baud,
        Err(_) => panic!("UART_LINK_BAUD must be decimal"),
    },
    None => 1_000_000,
};
/// The SERCOM's FIFO, unless `UART_LINK_FIFO=0` when building.
const FIFO: bool = match option_env!("UART_LINK_FIFO") {
    Some(value) => !matches!(value.as_bytes(), [b'0']),
    None => true,
};
const SYNC: u8 = 0x7E;
const BLOCK: usize = 1024;

static FAILED: AtomicBool = AtomicBool::new(false);

bind_interrupts!(struct Irqs {
    SERCOM2_0 => uart::InterruptHandler<peripherals::SERCOM2>;
    SERCOM2_1 => uart::InterruptHandler<peripherals::SERCOM2>;
    SERCOM2_2 => uart::InterruptHandler<peripherals::SERCOM2>;
    SERCOM2_56 => uart::InterruptHandler<peripherals::SERCOM2>;
});

/// Byte `i` of the pattern: never `SYNC`.
fn pattern(i: usize) -> u8 {
    #[expect(clippy::cast_possible_truncation, reason = "a pattern")]
    let b = ((i * 7 + i / 128) % 0x7E) as u8;
    b
}

/// What the test needs of a UART's halves, the DMA one's or the buffered one's.
trait LinkTx {
    async fn send(&mut self, bytes: &[u8]);
}

trait LinkRx {
    async fn byte(&mut self) -> Result<u8, uart::Error>;
    async fn block(&mut self, block: &mut [u8]) -> Result<(), uart::Error>;
}

impl LinkTx for UartTx<'_, Async> {
    async fn send(&mut self, bytes: &[u8]) {
        let _ = self.write(bytes).await;
        self.flush().await;
    }
}

impl LinkRx for UartRx<'_, Async> {
    async fn byte(&mut self) -> Result<u8, uart::Error> {
        self.read_byte().await
    }
    async fn block(&mut self, block: &mut [u8]) -> Result<(), uart::Error> {
        // By DMA, the whole block.
        self.read(block).await
    }
}

impl LinkTx for BufferedUartTx<'_> {
    async fn send(&mut self, bytes: &[u8]) {
        let _ = self.write_all(bytes).await;
        let _ = self.flush().await;
    }
}

impl LinkRx for BufferedUartRx<'_> {
    async fn byte(&mut self) -> Result<u8, uart::Error> {
        let mut b = [0u8; 1];
        self.read_exact(&mut b).await.map(|()| b[0])
    }
    async fn block(&mut self, block: &mut [u8]) -> Result<(), uart::Error> {
        self.read_exact(block).await
    }
}

async fn sender(tx: &mut impl LinkTx) -> ! {
    let mut block = [0u8; BLOCK + 1];
    block[0] = SYNC;
    for (i, b) in block[1..].iter_mut().enumerate() {
        *b = pattern(i);
    }
    loop {
        tx.send(&block).await;
        Timer::after(Duration::from_millis(100)).await;
    }
}

/// Reads the block after a sync byte.
async fn read_block(rx: &mut impl LinkRx, block: &mut [u8; BLOCK]) -> Result<(), &'static str> {
    loop {
        match rx.byte().await {
            Ok(SYNC) => break,
            Ok(_) => {}
            Err(_) => return Err("receive error before the sync byte"),
        }
    }
    rx.block(block).await.map_err(|_| "receive error")
}

/// Reads `blocks` blocks, logging the bad ones: how many were good and bad.
async fn receiver(rx: &mut impl LinkRx, how: &str, blocks: u32, log: &mut Log) -> (u32, u32) {
    let mut block = [0u8; BLOCK];
    let (mut good, mut bad) = (0u32, 0u32);
    for n in 0..blocks {
        block.fill(0xFF);
        let start = time::micros();
        let result = match select(read_block(rx, &mut block), Timer::after(Duration::from_secs(1))).await {
            Either::First(r) => r,
            Either::Second(()) => Err("nothing within a second"),
        };
        let us = time::micros() - start;
        let wrong = block.iter().enumerate().filter(|&(i, &b)| b != pattern(i)).count();
        if result.is_ok() && wrong == 0 {
            good += 1;
        } else if n == 0 {
            // It may have started mid-block.
            let _ = writeln!(log, "first block by {how}: skipped ({result:?}, {wrong} wrong)");
        } else {
            bad += 1;
            FAILED.store(true, Ordering::Relaxed);
            let mut expected = [0u8; 8];
            for (i, e) in expected.iter_mut().enumerate() {
                *e = pattern(i);
            }
            let _ = writeln!(log, "block by {how}: FAILED ({result:?}, {wrong} wrong of {BLOCK}) in {us} us; got {:02x?} expected {expected:02x?}", &block[..8]);
        }
    }
    (good, bad)
}

/// 20 blocks received while the sender runs.
async fn receive_while_sending(rx: &mut impl LinkRx, tx: &mut impl LinkTx, how: &str, log: &mut Log) -> (u32, u32) {
    match select(receiver(rx, how, 20, log), sender(tx)).await {
        Either::First(counts) => counts,
        Either::Second(never) => never,
    }
}

fn report(log: &mut Log, how: &str, (good, bad): (u32, u32)) {
    let _ = writeln!(log, "uart_link by {how} at {BAUD} baud: {good} blocks good, {bad} bad");
    if bad == 0 && good > 0 {
        let _ = writeln!(log, "uart_link by {how}: all passed");
    }
}

async fn fail_setup(log: &mut Log, how: &str, e: uart::ConfigError) {
    let _ = writeln!(log, "uart_link by {how}: can't set up: {e:?}");
    FAILED.store(true, Ordering::Relaxed);
    Timer::after(Duration::from_secs(1)).await;
}

async fn blink(led: &mut Output<'_>) -> ! {
    loop {
        led.toggle();
        let period = if FAILED.load(Ordering::Relaxed) { 100 } else { 500 };
        Timer::after(Duration::from_millis(period)).await;
    }
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32ck_curiosity_ultra::init();
    time::init(cortex_m::Peripherals::take().unwrap());
    let mut log = Log::init(p.SERCOM5, p.PA24, p.PA25);
    let mut led = Output::new(p.PD20, Level::High);
    let _ = writeln!(log, "\npic32ck-curiosity-ultra uart_link at {BAUD} baud, FIFO {FIFO}");
    let mut config = uart::Config::default();
    config.baudrate = BAUD;
    config.fifo = FIFO;
    let (mut sercom, mut tx_pin, mut rx_pin, mut rts, mut cts) = (p.SERCOM2, p.PC15, p.PC16, p.PC17, p.PC18);
    let (mut tx_dma, mut rx_dma) = (p.DMA0_CH1, p.DMA0_CH0);
    let (mut tx_ring, mut rx_ring) = ([0u8; 256], [0u8; 256]);
    let blink = blink(&mut led);
    let run = async {
        loop {
            {
                let how = "a buffered UART";
                match BufferedUart::new_with_rtscts(sercom.reborrow(), tx_pin.reborrow(), rx_pin.reborrow(), rts.reborrow(), cts.reborrow(), Irqs, &mut tx_ring[..], &mut rx_ring[..], config) {
                    Ok(link) => {
                        let (mut tx, mut rx) = link.split();
                        let counts = receive_while_sending(&mut rx, &mut tx, how, &mut log).await;
                        report(&mut log, how, counts);
                    }
                    Err(e) => fail_setup(&mut log, how, e).await,
                }
            }
            {
                let how = "DMA";
                match Uart::new_with_rtscts(sercom.reborrow(), tx_pin.reborrow(), rx_pin.reborrow(), rts.reborrow(), cts.reborrow(), Irqs, tx_dma.reborrow(), rx_dma.reborrow(), config) {
                    Ok(link) => {
                        let (mut tx, mut rx) = link.split();
                        let counts = receive_while_sending(&mut rx, &mut tx, how, &mut log).await;
                        report(&mut log, how, counts);
                    }
                    Err(e) => fail_setup(&mut log, how, e).await,
                }
            }
        }
    };
    let _ = join(run, blink).await;
}
