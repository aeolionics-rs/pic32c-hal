//! `pic32c-hal`'s async `flash` (`Flash::new`, `embedded-storage-async`) on
//! `flash`'s scratch areas: the top 16 KiB of panel 2 (offset `0x1F_C000`,
//! which the program doesn't run from) and the top page of panel 1
//! (`0x0F_F000`, which it does).
//!
//! A ticker task counts 100 µs timer ticks beside each operation, to show
//! whether the executor ran meanwhile: it should, all through a panel-2
//! erase (up to 20 ms); in panel 1 the CPU stalls on any fetch the cache
//! misses. Then: rows from SRAM and flash words from a pattern in flash,
//! written and read back; and an erase whose future is dropped 1 ms in, after
//! which the page must read erased and the next operation work. Over the
//! virtual COM port; LED0 blinks slowly when all passed, fast on a failure.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;
use core::sync::atomic::{AtomicU32, Ordering};

use embassy_executor::Spawner;
use embassy_futures::select::{Either, select};
use embassy_time::{Duration, Timer};
use embedded_storage_async::nor_flash::{NorFlash, ReadNorFlash};
use panic_halt as _;
use pic32c_hal::bind_interrupts;
use pic32c_hal::flash::{self, Async, Flash, PAGE_SIZE, ROW_SIZE};
use pic32c_hal::gpio::{Level, Output};
use pic32ck_curiosity_ultra::time;
use pic32ck_curiosity_ultra::uart::Uart;

pic32ck_curiosity_ultra::boot!();

bind_interrupts!(struct Irqs {
    FCW => flash::InterruptHandler;
});

const PANEL2: u32 = 0x1F_C000;
const PANEL1: u32 = 0x0F_F000;
/// [`PAGE_SIZE`] and [`ROW_SIZE`] as the flash API's offsets.
const PAGE: u32 = 4096;
const ROW: u32 = 1024;
const _: () = assert!(PAGE as usize == PAGE_SIZE && ROW as usize == ROW_SIZE);

/// 100 µs ticks taken by the ticker task.
static TICKS: AtomicU32 = AtomicU32::new(0);

/// A pattern held in flash, for flash-word writes.
static PATTERN: [u8; 256] = {
    let mut p = [0; 256];
    let mut i = 0;
    while i < 256 {
        #[expect(clippy::cast_possible_truncation, reason = "the low byte")]
        let b = (i * 7 + 3) as u8;
        p[i] = b;
        i += 1;
    }
    p
};

#[repr(C, align(4))]
struct Row([u8; ROW_SIZE]);

async fn ticker() -> ! {
    loop {
        Timer::after(Duration::from_micros(100)).await;
        TICKS.fetch_add(1, Ordering::Relaxed);
    }
}

/// Runs `operation`, returning its result, its time in µs and the ticks the
/// ticker took meanwhile.
async fn timed<R>(operation: impl Future<Output = R>) -> (R, u64, u32) {
    let ticks = TICKS.load(Ordering::Relaxed);
    let start = time::micros();
    let result = operation.await;
    (result, time::micros() - start, TICKS.load(Ordering::Relaxed) - ticks)
}

/// Whether `length` bytes at `offset` all read `0xFF`.
async fn erased(flash: &mut Flash<'_, Async>, offset: u32, length: usize) -> bool {
    let mut buffer = [0u8; 256];
    let mut done = 0;
    while done < length {
        let n = buffer.len().min(length - done);
        #[expect(clippy::cast_possible_truncation, reason = "within a page")]
        let at = offset + done as u32;
        if flash.read(at, &mut buffer[..n]).await.is_err() || buffer[..n].iter().any(|&b| b != 0xFF) {
            return false;
        }
        done += n;
    }
    true
}

async fn tests(flash: &mut Flash<'_, Async>, log: &mut Uart) -> u32 {
    let mut failures = 0;
    let mut check = |name: &str, good: bool, detail: core::fmt::Arguments<'_>| {
        let _ = writeln!(log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        failures += u32::from(!good);
    };

    // An erase in each panel, with the ticker's count meanwhile.
    let (result, us, ticks) = timed(flash.erase(PANEL2, PANEL2 + PAGE)).await;
    let ok = result.is_ok() && erased(flash, PANEL2, PAGE_SIZE).await;
    check("erase a panel-2 page", ok && ticks > 0, format_args!("in {us} us, ticker ran {ticks} times ({result:?})"));
    let (result, us, ticks) = timed(flash.erase(PANEL1, PANEL1 + PAGE)).await;
    let ok = result.is_ok() && erased(flash, PANEL1, PAGE_SIZE).await;
    check("erase the panel-1 page", ok, format_args!("in {us} us, ticker ran {ticks} times ({result:?}; the CPU may stall here)"));

    // Rows from SRAM.
    let mut row = Row([0; ROW_SIZE]);
    for (i, b) in row.0.iter_mut().enumerate() {
        #[expect(clippy::cast_possible_truncation, reason = "the low byte")]
        let v = (i ^ 0x5A) as u8;
        *b = v;
    }
    let (result, us, ticks) = timed(flash.write(PANEL2, &row.0)).await;
    let mut back = [0u8; ROW_SIZE];
    let _ = flash.read(PANEL2, &mut back).await;
    check("row write from SRAM", result.is_ok() && back == row.0, format_args!("1 KiB in {us} us, ticker {ticks} ({result:?})"));

    // Flash words from a pattern in flash (no row writes from flash).
    let at = PANEL2 + ROW;
    let (result, us, ticks) = timed(flash.write(at, &PATTERN)).await;
    let mut back = [0u8; 256];
    let _ = flash.read(at, &mut back).await;
    check("flash-word writes from flash", result.is_ok() && back == PATTERN, format_args!("256 B in {us} us, ticker {ticks} ({result:?})"));

    // Misaligned and out-of-range writes are refused.
    let refused = matches!(flash.write(PANEL2 + 16, &PATTERN[..32]).await, Err(flash::Error::NotAligned)) && matches!(flash.erase(0x1F_F000, 0x20_1000).await, Err(flash::Error::OutOfBounds));
    check("misaligned and out-of-range refused", refused, format_args!(""));

    // A dropped erase: the page must still end erased, and the flash work.
    let page = PANEL2 + PAGE;
    let _ = flash.write(page, &PATTERN).await;
    let dropped = match select(flash.erase(page, page + PAGE), Timer::after(Duration::from_millis(1))).await {
        Either::First(_) => "finished within 1 ms",
        Either::Second(()) => "dropped after 1 ms",
    };
    let ok = erased(flash, page, PAGE_SIZE).await;
    let after = flash.write(page, &PATTERN[..64]).await;
    let mut back = [0u8; 64];
    let _ = flash.read(page, &mut back).await;
    check("an erase dropped part way", ok && after.is_ok() && back == PATTERN[..64], format_args!("({dropped}; erased {ok}, then a write {after:?})"));

    // Clean up.
    let _ = flash.erase(PANEL2, PANEL2 + 4 * PAGE).await;
    let _ = flash.erase(PANEL1, PANEL1 + PAGE).await;
    failures
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32ck_curiosity_ultra::init();
    time::init(cortex_m::Peripherals::take().unwrap());
    let mut log = Uart::init(p.SERCOM5, p.PA24, p.PA25);
    let mut led = Output::new(p.PD20, Level::High);
    let _ = writeln!(log, "\npic32ck-curiosity-ultra flash_async");
    let mut flash = Flash::new(p.FCW, Irqs);

    let failures = match select(tests(&mut flash, &mut log), ticker()).await {
        Either::First(failures) => failures,
        Either::Second(never) => never,
    };
    let _ = if failures == 0 { writeln!(log, "flash_async: all passed") } else { writeln!(log, "flash_async: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
