/// A handshake peaks at under 6 KB (measured), so this holds both
/// connections' at once with room to spare.
const HEAP_SIZE: usize = 32 * 1024;
static HEAP: TlsfHeap = TlsfHeap::empty();
static USED: AtomicUsize = AtomicUsize::new(0);
static PEAK: AtomicUsize = AtomicUsize::new(0);

/// The TLSF heap, counting what's allocated and its peak.
struct Counting;

// SAFETY: passes every call to the TLSF heap unchanged.
unsafe impl GlobalAlloc for Counting {
    unsafe fn alloc(&self, layout: Layout) -> *mut u8 {
        // SAFETY: as the caller promises.
        let ptr = unsafe { HEAP.alloc(layout) };
        if !ptr.is_null() {
            let used = USED.fetch_add(layout.size(), Ordering::Relaxed) + layout.size();
            PEAK.fetch_max(used, Ordering::Relaxed);
        }
        ptr
    }

    unsafe fn dealloc(&self, ptr: *mut u8, layout: Layout) {
        USED.fetch_sub(layout.size(), Ordering::Relaxed);
        // SAFETY: as the caller promises.
        unsafe { HEAP.dealloc(ptr, layout) }
    }
}

#[global_allocator]
static ALLOCATOR: Counting = Counting;

/// Bytes allocated now (requested sizes; not `TlsfHeap::used`, which in
/// embedded-alloc 0.7.0 borrows the heap's `RefCell` twice and panics).
fn heap_used() -> usize {
    USED.load(Ordering::Relaxed)
}

fn heap_peak() -> usize {
    PEAK.load(Ordering::Relaxed)
}

static CERT: &[u8] = include_bytes!("../certs/cert.der");
static KEY: &[u8] = include_bytes!("../certs/key.der");

/// getrandom's custom backend: embassy-crypto's random number driver, which
/// pic32c-hal's `embassy-crypto-rng` serves from the TRNG.
///
/// # Safety
/// getrandom passes a writable buffer of `len` bytes.
#[unsafe(no_mangle)]
#[expect(clippy::unnecessary_wraps, reason = "getrandom's signature for a custom backend")]
unsafe extern "Rust" fn __getrandom_v03_custom(dest: *mut u8, len: usize) -> Result<(), getrandom::Error> {
    // SAFETY: as getrandom promises.
    let buf = unsafe { core::slice::from_raw_parts_mut(dest, len) };
    embassy_crypto::rng_fill_bytes(buf);
    Ok(())
}

/// The SNTP clock; `None` (clockless) before the first sync, which a
/// server that issues no tickets and asks for no client certificate never
/// needs.
#[derive(Debug)]
struct Clock;

impl rustls::time_provider::TimeProvider for Clock {
    fn current_time(&self) -> Option<UnixTime> {
        sntp::now_us().map(|us| UnixTime::since_unix_epoch(core::time::Duration::from_micros(us)))
    }
}

static QUEUE: StaticCell<PacketQueue<4, 8>> = StaticCell::new();
static ETHERNET: StaticCell<Ethernet<'static>> = StaticCell::new();
/// The stack's own state; its socket tables are sized by xarxa's features
/// (two HTTPS sockets and a listener; SNTP's, mDNS's and the DNS client's
/// UDP sockets).
static STACK: StaticCell<StackStorage<'static>> = StaticCell::new();
/// The stack's packets: the MAC's receive ring holds eight, its transmit
/// ring up to four, and the rest are the stack's. (TCP's data is in the
/// sockets' own buffers; UDP's datagrams wait here.)
static POOL: ConstStaticCell<StaticPool<{ eth::BUFFER_SIZE }, 16, { eth::BUFFER_ALIGN }>> = ConstStaticCell::new(StaticPool::new());
static CONFIG: picoserve::Config = picoserve::Config::new(picoserve::Timeouts {
    start_read_request: Duration::from_secs(5),
    persistent_start_read_request: Duration::from_secs(2),
    read_request: Duration::from_secs(2),
    write: Duration::from_secs(5),
})
.keep_connection_alive();

/// The pattern `/blob` serves: bytes 0 to 255, 256 times.
static BLOB: [u8; 65_536] = {
    let mut blob = [0; 65_536];
    let mut i = 0;
    while i < blob.len() {
        #[expect(clippy::cast_possible_truncation, reason = "the low byte")]
        let byte = i as u8;
        blob[i] = byte;
        i += 1;
    }
    blob
};

#[embassy_executor::task]
async fn net(mut runner: Runner<'static>) -> ! {
    runner.run().await
}

fn status(iface: Iface<'_>) -> impl IntoResponse {
    let mut text = heapless::String::<640>::new();
    let _ = write!(
        text,
        "up {} s\nUnix time {:?}\nlast sync {:?}\nlink {}\nIPv4 {:?}\nIPv6 {:?}\nheap used {}, peak {}, of {}\n",
        Instant::now().as_secs(),
        sntp::now_us().map(|us| us / 1_000_000),
        sntp::last_sync(),
        if iface.is_link_up() { "up" } else { "down" },
        net::v4(iface),
        net::v6(iface),
        heap_used(),
        heap_peak(),
        HEAP_SIZE
    );
    text
}

/// One HTTPS connection at a time from port 443's `listener`, which the
/// tasks serving it share.
async fn https<'d, P: picoserve::routing::PathRouter>(app: &picoserve::Router<P>, stack: Stack<'d>, listener: &net::SharedListener<'d>, config: Arc<ServerConfig>, name: &str) -> ! {
    let mut tcp_rx = [0; 4096];
    let mut tcp_tx = [0; 4096];
    // A whole record from the peer (16,384 bytes of payload, plus header,
    // padding and tag), one decrypted record, and outgoing records.
    #[expect(clippy::large_stack_arrays, reason = "in the task's future, in static storage, not on a stack")]
    let mut rx = [0; 16_384 + 325];
    let mut plain = [0; 16_384];
    let mut tx = [0; 4096];
    // Plaintext gathered into one record (what fits `tx` with a record's overhead).
    let mut out = [0; 4096 - tls::OVERHEAD];
    let mut buffer = [0; 2048];
    let mut log = Uart;
    loop {
        let Ok(mut socket) = net::accept(stack, listener, &mut tcp_rx, &mut tcp_tx).await else { continue };
        let _ = writeln!(log, "{name}: connection from {:?}", socket.remote_addr());
        socket.set_nagle_enabled(false);
        socket.set_keep_alive(Some(Duration::from_secs(30)));
        socket.set_timeout(Some(Duration::from_secs(45)));
        let start = Instant::now();
        let heap_before = heap_used();
        match with_timeout(Duration::from_secs(10), tls::accept(socket, config.clone(), &mut rx, &mut plain, &mut tx, &mut out)).await {
            Ok(Ok(connection)) => {
                let _ = writeln!(log, "{name}: handshake {} ms, heap {} -> {} (peak {})", start.elapsed().as_millis(), heap_before, heap_used(), heap_peak());
                let result = picoserve::Server::new(app, &CONFIG, &mut buffer).serve(connection).await;
                match result {
                    Ok(info) => {
                        let _ = writeln!(log, "{name}: closed after {} requests", info.handled_requests_count);
                    }
                    Err(e) => {
                        let _ = writeln!(log, "{name}: {e:?}");
                    }
                }
            }
            Ok(Err(e)) => {
                let _ = writeln!(log, "{name}: handshake failed: {e}");
            }
            Err(_) => {
                let _ = writeln!(log, "{name}: handshake timed out");
            }
        }
    }
}

#[embassy_executor::main]
async fn main(spawner: Spawner) {
    let p = pic32ck_curiosity_ultra::init();
    let mut log = Uart::init(p.SERCOM5, p.PA24, p.PA25);
    let mut led = Output::new(p.PD20, Level::High);
    let _ = writeln!(log, "\npic32ck-curiosity-ultra eth_https (RNG {})", trng::CONSTRUCTION);

    static mut HEAP_MEMORY: [MaybeUninit<u8>; HEAP_SIZE] = [MaybeUninit::uninit(); HEAP_SIZE];
    // SAFETY: once, before anything allocates; the memory is ours alone.
    unsafe { HEAP.init((&raw mut HEAP_MEMORY) as usize, HEAP_SIZE) };

    let start = Instant::now();
    let mut provider = tls::provider();
    // ChaCha20-Poly1305 first (the provider's order), and the server's order
    // wins: in software on the M33 it moves 1.4 MB/s, AES-128-GCM 0.38.
    // `TLS_PREFER` at build time changes it: `aes128`, or `client` (the
    // client's order).
    let prefer = match option_env!("TLS_PREFER") {
        Some("client") => None,
        Some("aes128") => Some(rustls_rustcrypto::TLS13_AES_128_GCM_SHA256),
        _ => Some(rustls_rustcrypto::TLS13_CHACHA20_POLY1305_SHA256),
    };
    if let Some(first) = prefer {
        provider.cipher_suites.retain(|suite| suite.suite() != first.suite());
        provider.cipher_suites.insert(0, first);
    }
    let provider = Arc::new(provider);
    let config = ServerConfig::builder_with_details(provider, Arc::new(Clock))
        .with_safe_default_protocol_versions()
        .and_then(|builder| builder.with_no_client_auth().with_single_cert(vec![CertificateDer::from(CERT)], PrivateKeyDer::Pkcs8(PrivatePkcs8KeyDer::from(KEY))));
    let mut config = match config {
        Ok(config) => config,
        Err(e) => {
            let _ = writeln!(log, "TLS config: {e}");
            loop {
                led.toggle();
                Timer::after(Duration::from_millis(100)).await;
            }
        }
    };
    config.send_tls13_tickets = 0;
    config.ignore_client_order = prefer.is_some();
    let config = Arc::new(config);
    let _ = writeln!(log, "TLS config in {} ms, heap {} of {}; preferring {:?}", start.elapsed().as_millis(), heap_used(), HEAP_SIZE, prefer.map(|s| s.suite()));

    let id = uid::unique_id();
    let mac = [0x02, id[1], id[2], id[3], id[4], id[5]];
    let pins = Pins {
        ref_clk: p.PC00,
        mdc: p.PC03,
        mdio: p.PC04,
        crs_dv: p.PC10,
        rx_er: p.PC09,
        rxd0: p.PC07,
        rxd1: p.PC06,
        tx_en: p.PC11,
        txd0: p.PC12,
        txd1: p.PC13,
    };
    let Ok(ethernet) = Ethernet::new(p.ETH, Irqs, pins, p.PD21, QUEUE.init(PacketQueue::new()), mac, clocks::GEN_TIMER).await else {
        let _ = writeln!(log, "eth: no PHY");
        loop {
            led.toggle();
            Timer::after(Duration::from_millis(100)).await;
        }
    };
    let seed = u64::from_le_bytes([id[8], id[9], id[10], id[11], id[12], id[13], id[14], id[15]]);
    let (stack, runner) = Stack::new(STACK.init(StackStorage::new()), POOL.take(), seed);
    let iface = stack.add_iface_borrowed(ETHERNET.init(ethernet)).unwrap();
    iface.set_dhcpv4(Some(DhcpConfig::default())).unwrap();
    iface.set_slaac(Some(SlaacConfig::default())).unwrap();
    spawner.spawn(net(runner).unwrap());
    let _ = with_timeout(Duration::from_secs(30), iface.wait_config_up()).await;
    let _ = writeln!(log, "IPv4 {:?}; IPv6 {:?}; link-local {:?}", net::v4(iface), net::v6(iface), net::link_local(iface));

    let app = picoserve::Router::new()
        .route(
            "/",
            get_service(picoserve::response::File::html(
                "<!doctype html><title>PIC32CK</title><h1>Hello over TLS from the PIC32CK</h1><p>pic32c-hal, embassy-net, rustls and picoserve.</p>\n",
            )),
        )
        .route("/status", get(move || async move { status(iface) }))
        .route("/blob", get_service(picoserve::response::File::with_content_type("application/octet-stream", &BLOB)));

    let blink = async {
        let mut log = Uart;
        let mut ticks = 0u32;
        loop {
            led.toggle();
            Timer::after(Duration::from_millis(500)).await;
            ticks += 1;
            // A heartbeat, so a log shows when the program stopped.
            if ticks.is_multiple_of(60) {
                let _ = writeln!(log, "[{} s] alive, heap {} (peak {})", Instant::now().as_secs(), heap_used(), heap_peak());
            }
        }
    };
    let name = mdns::host_name(iface);
    let listener = net::listen(stack, 443);
    let advert = mdns::Advert {
        service: "_https",
        protocol: "_tcp",
        port: 443,
    };
    #[expect(clippy::large_futures, reason = "main's future lives in the executor's static task storage, not on a stack")]
    join5(
        https(&app, stack, &listener, config.clone(), "https0"),
        https(&app, stack, &listener, config, "https1"),
        sntp::run(iface),
        mdns::run(iface, &name, advert, seed),
        blink,
    )
    .await;
}
