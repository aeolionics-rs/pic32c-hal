//! HTTPS (spike): `eth_http`'s routes over TLS on port 443, two connections
//! at a time, with rustls (unbuffered API, `RustCrypto`) and the board's
//! `tls` adapter. Software crypto only, so it runs on the GC01 (no HSM).
//!
//! - Certificate: `certs/cert.der`, a self-signed P-256 one for the bench
//!   (both boards' mDNS names in its SAN), key `certs/key.der`. TEST ONLY.
//! - Randomness: the TRNG, as embassy-crypto's random number driver
//!   (pic32c-hal's `embassy-crypto-rng`, health-checked, and by default an
//!   `HMAC_DRBG` per call), through getrandom's custom backend (rustls-
//!   rustcrypto draws its key shares and signature nonces from getrandom).
//! - Time: `common/sntp.rs` (the DHCP gateway, then the pool);
//!   clockless until the first sync, which this server never needs (no
//!   tickets, no client certificates).
//! - Name: `pic32ck-<the MAC's last 3 bytes>.local` by mDNS, with `_https._tcp`
//!   on 443 (the board crate's `mdns`).
//! - Heap: 32 KiB (TLSF) for rustls; a handshake peaks under 6 KB.
//! - Cipher suite: ChaCha20-Poly1305 preferred (fastest in software here).
//!
//! Each handshake's time and the heap's use go out over the virtual COM
//! port.

