//! `pic32c-hal`'s `dma`: copies of bytes, halfwords and words of awkward
//! lengths and alignments from SRAM and from flash, checked and timed
//! against the CPU's own copy; a ticker task counting meanwhile, to show the
//! executor runs through a transfer; a copy dropped part way, after which
//! the channel must work again; channels on both controllers at once; and a
//! message written to the VCOM by DMA, SERCOM5 pacing it with its transmit
//! request. Over the virtual COM port; LED0 blinks slowly when all passed,
//! fast on a failure.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;
use core::sync::atomic::{AtomicU32, Ordering};

use embassy_executor::Spawner;
use embassy_futures::join::join;
use embassy_futures::select::{Either, select};
use embassy_time::{Duration, Timer};
use panic_halt as _;
use pic32c_hal::dma::{self, Request, Transfer, Word};
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::{Peri, peripherals};
use pic32ck_curiosity_ultra::time;
use pic32ck_curiosity_ultra::uart::Uart;
use static_cell::ConstStaticCell;

pic32ck_curiosity_ultra::boot!();

/// 100 µs ticks taken by the ticker task.
static TICKS: AtomicU32 = AtomicU32::new(0);

/// SERCOM5's DATA register, where the log goes.
const SERCOM5_DATA: usize = 0x4500_2000 + 0x28;

/// A pattern in flash.
static PATTERN: [u8; 4096] = {
    let mut p = [0; 4096];
    let mut i = 0;
    while i < p.len() {
        #[expect(clippy::cast_possible_truncation, reason = "the low byte")]
        let b = (i * 31 + 7) as u8;
        p[i] = b;
        i += 1;
    }
    p
};

/// Buffers in SRAM, word-aligned (`u8` views of `u32`s).
static SOURCE: ConstStaticCell<[u32; 16_384]> = ConstStaticCell::new([0; 16_384]);
static DESTINATION: ConstStaticCell<[u32; 16_384]> = ConstStaticCell::new([0; 16_384]);
static SECOND: ConstStaticCell<[u32; 1024]> = ConstStaticCell::new([0; 1024]);

async fn ticker() -> ! {
    loop {
        Timer::after(Duration::from_micros(100)).await;
        TICKS.fetch_add(1, Ordering::Relaxed);
    }
}

/// The channels the tests use.
#[expect(non_snake_case, reason = "named as the peripherals")]
struct Channels {
    DMA0_CH0: Peri<'static, peripherals::DMA0_CH0>,
    DMA0_CH1: Peri<'static, peripherals::DMA0_CH1>,
    DMA0_CH2: Peri<'static, peripherals::DMA0_CH2>,
    DMA0_CH3: Peri<'static, peripherals::DMA0_CH3>,
    DMA0_CH4: Peri<'static, peripherals::DMA0_CH4>,
    DMA0_CH5: Peri<'static, peripherals::DMA0_CH5>,
    DMA0_CH6: Peri<'static, peripherals::DMA0_CH6>,
    DMA1_CH0: Peri<'static, peripherals::DMA1_CH0>,
    DMA1_CH1: Peri<'static, peripherals::DMA1_CH1>,
}

struct Tests<'a> {
    log: &'a mut Uart,
    failures: u32,
}

impl Tests<'_> {
    fn check(&mut self, name: &str, good: bool, detail: core::fmt::Arguments<'_>) {
        let _ = writeln!(self.log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        self.failures += u32::from(!good);
    }
}

/// Copies `source` into `destination` by DMA, returning the result, the
/// microseconds it took and the ticker's ticks meanwhile.
async fn timed_copy<W: Word>(channel: Peri<'_, impl dma::Channel>, source: &[W], destination: &mut [W]) -> (Result<(), dma::Error>, u64, u32) {
    let ticks = TICKS.load(Ordering::Relaxed);
    let start = time::micros();
    let result = Transfer::new_copy(channel, source, destination).await;
    (result, time::micros() - start, TICKS.load(Ordering::Relaxed) - ticks)
}

async fn tests(p: &mut Channels, t: &mut Tests<'_>) {
    let (source, destination, second) = (SOURCE.take(), DESTINATION.take(), SECOND.take());
    for (i, w) in source.iter_mut().enumerate() {
        #[expect(clippy::cast_possible_truncation, reason = "a pattern")]
        let v = (i as u32).wrapping_mul(0x9E37_79B9);
        *w = v;
    }
    let source_bytes: &[u8] = bytemuck(source);

    // Bytes of awkward lengths and offsets, SRAM to SRAM.
    for (offset, length) in [(0, 1), (1, 3), (3, 1023), (1, 1024), (2, 1025), (0, 4096)] {
        destination.fill(0);
        let destination_bytes = bytemuck_mut(destination);
        let (result, us, _) = timed_copy(p.DMA0_CH0.reborrow(), &source_bytes[offset..offset + length], &mut destination_bytes[offset + 1..offset + 1 + length]).await;
        let good = result.is_ok() && destination_bytes[offset + 1..offset + 1 + length] == source_bytes[offset..offset + length] && destination_bytes[offset] == 0 && destination_bytes[offset + 1 + length] == 0;
        t.check("bytes", good, format_args!("{length} from +{offset} to +{} in {us} us ({result:?})", offset + 1));
    }

    // Halfwords and words.
    {
        let halves: &[u16] = bytemuck(&source[..512]);
        destination.fill(0);
        let out: &mut [u16] = bytemuck_mut(&mut destination[..512]);
        let (result, us, _) = timed_copy(p.DMA0_CH1.reborrow(), &halves[1..1000], &mut out[1..1000]).await;
        t.check("halfwords", result.is_ok() && out[1..1000] == halves[1..1000] && out[0] == 0 && out[1000] == 0, format_args!("999 in {us} us ({result:?})"));
    }
    destination.fill(0);
    let (result, us, ticks) = timed_copy(p.DMA0_CH2.reborrow(), &source[..], &mut destination[..]).await;
    let dma_us = us;
    t.check(
        "64 KiB of words",
        result.is_ok() && destination[..] == source[..],
        format_args!("in {us} us, {} MB/s, ticker ran {ticks} times ({result:?})", 65_536 / us.max(1)),
    );
    // The CPU's copy, for comparison.
    destination.fill(0);
    let start = time::micros();
    destination.copy_from_slice(source);
    let cpu_us = time::micros() - start;
    t.check("CPU copy of 64 KiB", destination[..] == source[..], format_args!("in {cpu_us} us (DMA {dma_us} us)"));

    // From flash.
    destination.fill(0);
    let out = &mut bytemuck_mut(destination)[..PATTERN.len()];
    let (result, us, _) = timed_copy(p.DMA1_CH0.reborrow(), &PATTERN, out).await;
    t.check("flash to SRAM on DMA1", result.is_ok() && out[..] == PATTERN[..], format_args!("4 KiB in {us} us ({result:?})"));

    // Both controllers at once.
    destination.fill(0);
    second.fill(0);
    let (a, b) = join(
        Transfer::new_copy(p.DMA0_CH3.reborrow(), &source[..8192], &mut destination[..8192]),
        Transfer::new_copy(p.DMA1_CH1.reborrow(), &source[8192..9216], &mut second[..]),
    )
    .await;
    t.check("two controllers", a.is_ok() && b.is_ok() && destination[..8192] == source[..8192] && second[..] == source[8192..9216], format_args!("({a:?}, {b:?})"));

    // A copy dropped part way: the channel must stop, and work again.
    destination.fill(0);
    let dropped = {
        let transfer = Transfer::new_copy(p.DMA0_CH4.reborrow(), &source[..], &mut destination[..]);
        // A few microseconds into 64 KiB.
        let deadline = time::micros() + 20;
        while time::micros() < deadline {}
        let running = transfer.is_running();
        let remaining = transfer.remaining();
        drop(transfer);
        (running, remaining)
    };
    let copied = destination.iter().zip(source.iter()).take_while(|(d, s)| d == s).count();
    let untouched = destination[copied..].iter().all(|&w| w == 0);
    t.check(
        "dropped part way",
        dropped.0 && untouched && copied < source.len(),
        format_args!("running {}, {} bytes left, {} words copied, rest untouched {untouched}", dropped.0, dropped.1, copied),
    );
    destination.fill(0);
    let (result, _, _) = timed_copy(p.DMA0_CH4.reborrow(), &source[..256], &mut destination[..256]).await;
    t.check("the same channel again", result.is_ok() && destination[..256] == source[..256], format_args!("({result:?})"));

    // A transfer dropped before its first trigger: nothing moves.
    second.fill(0);
    let outcome = select(
        // SAFETY: SERCOM5's DATA; but RX requests never come with nothing
        // sent to the board, so this never moves a byte.
        unsafe { Transfer::new_read(p.DMA0_CH5.reborrow(), Request::sercom_rx(5), SERCOM5_DATA as *const u8, &mut bytemuck_mut(second)[..16]) },
        Timer::after(Duration::from_millis(5)),
    )
    .await;
    t.check("a read with no data", matches!(outcome, Either::Second(())) && second.iter().all(|&w| w == 0), format_args!("timed out, nothing written"));

    // The VCOM, written by DMA, paced by SERCOM5's transmit request.
    t.log.flush();
    let message = b"dma: this line went out by DMA, paced by SERCOM5\r\n";
    let start = time::micros();
    // SAFETY: SERCOM5's DATA, which takes a byte per transmit request; the
    // log is idle meanwhile (flushed, and nothing else writes to it).
    let result = unsafe { Transfer::new_write(p.DMA0_CH6.reborrow(), Request::sercom_tx(5), message, SERCOM5_DATA as *mut u8) }.await;
    let us = time::micros() - start;
    t.log.flush();
    // 50 bytes at 115,200 baud is 4.3 ms, less the 8 the FIFO takes at
    // once: anything much faster wasn't paced.
    t.check("UART TX by DMA", result.is_ok() && us > 3_000, format_args!("{} bytes in {us} us ({result:?})", message.len()));
}

/// A slice of `u32`s as the smaller words in it.
fn bytemuck<W: Word>(words: &[u32]) -> &[W] {
    // SAFETY: u8 and u16 have weaker alignment than u32 and no invalid bit
    // patterns; the length is in bytes divided by the word's size.
    unsafe { core::slice::from_raw_parts(words.as_ptr().cast(), core::mem::size_of_val(words) / size_of::<W>()) }
}

fn bytemuck_mut<W: Word>(words: &mut [u32]) -> &mut [W] {
    // SAFETY: as `bytemuck`.
    unsafe { core::slice::from_raw_parts_mut(words.as_mut_ptr().cast(), core::mem::size_of_val(words) / size_of::<W>()) }
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32ck_curiosity_ultra::init();
    time::init(cortex_m::Peripherals::take().unwrap());
    let mut log = Uart::init(p.SERCOM5, p.PA24, p.PA25);
    let mut led = Output::new(p.PD20, Level::High);
    let mut channels = Channels {
        DMA0_CH0: p.DMA0_CH0,
        DMA0_CH1: p.DMA0_CH1,
        DMA0_CH2: p.DMA0_CH2,
        DMA0_CH3: p.DMA0_CH3,
        DMA0_CH4: p.DMA0_CH4,
        DMA0_CH5: p.DMA0_CH5,
        DMA0_CH6: p.DMA0_CH6,
        DMA1_CH0: p.DMA1_CH0,
        DMA1_CH1: p.DMA1_CH1,
    };
    let _ = writeln!(log, "\npic32ck-curiosity-ultra dma");

    let mut t = Tests { log: &mut log, failures: 0 };
    match select(tests(&mut channels, &mut t), ticker()).await {
        Either::First(()) | Either::Second(_) => {}
    }
    let failures = t.failures;
    let _ = if failures == 0 { writeln!(log, "dma: all passed") } else { writeln!(log, "dma: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
