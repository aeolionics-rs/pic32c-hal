//! `pic32c-hal`'s `usb` with embassy-usb: a CDC-ACM serial port on the board's
//! full-speed USB connector (J203, the Micro-AB marked USB1) that echoes
//! everything it receives. The 48 MHz USB clock is generator 3, from the
//! crystal through PLL0. Progress goes out over the virtual COM port.

#![no_std]
#![no_main]
// Embassy's main macro passes `_spawner` on to the task it generates, where
// an attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;

use embassy_executor::Spawner;
use embassy_usb::class::cdc_acm::device::{self as cdc_acm, CdcAcmClass, State};
use embassy_usb::driver::EndpointError;
use embassy_usb::{Builder, Config};
use panic_halt as _;
use pic32c_hal::{bind_interrupts, usb};
use pic32ck_curiosity_ultra::uart::Uart;
use pic32ck_curiosity_ultra::{clocks, time};

pic32ck_curiosity_ultra::boot!();

bind_interrupts!(struct Irqs {
    USB_OTHER => usb::InterruptHandler;
    USB_SOF => usb::InterruptHandler;
    USB_TRCPT0 => usb::InterruptHandler;
    USB_TRCPT1 => usb::InterruptHandler;
});

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let peripherals = pic32ck_curiosity_ultra::init();
    time::init(cortex_m::Peripherals::take().unwrap());
    let mut log = Uart::init(peripherals.SERCOM5, peripherals.PA24, peripherals.PA25);
    let _ = writeln!(log, "\npic32ck-curiosity-ultra usb_echo: CPU {} Hz", pic32c_hal::clocks::generator_hz(0).unwrap_or(0));
    let driver = usb::Driver::new(peripherals.USB, Irqs, peripherals.PD04, peripherals.PD03, clocks::GEN_48);
    // A test VID/PID (pid.codes' test range).
    let mut config = Config::new(0x1209, 0x000A);
    config.manufacturer = Some("Aeolionics");
    config.product = Some("PIC32CK USB echo");
    config.serial_number = Some("pic32ck-curiosity-ultra");
    config.max_power = 100;
    config.max_packet_size_0 = 64;

    let mut config_descriptor = [0; 256];
    let mut bos_descriptor = [0; 256];
    let mut control_buf = [0; 64];
    let mut state = State::new();
    let mut builder = Builder::new(driver, config, &mut config_descriptor, &mut bos_descriptor, &mut [], &mut control_buf);
    let mut class = CdcAcmClass::new(&mut builder, &mut state, cdc_acm::Config::new());
    let mut usb = builder.build();
    let _ = writeln!(log, "USB device built; attaching");

    let echo = async {
        loop {
            class.wait_connection().await;
            let _ = writeln!(log, "connected");
            let mut echoed = 0usize;
            let mut buf = [0; 64];
            loop {
                match class.read_packet(&mut buf).await {
                    Ok(n) => {
                        if class.write_packet(&buf[..n]).await.is_err() {
                            break;
                        }
                        echoed += n;
                    }
                    Err(EndpointError::BufferOverflow) => {}
                    Err(_) => break,
                }
            }
            let _ = writeln!(log, "disconnected after echoing {echoed} bytes");
        }
    };
    // Once a second: the controller's FSM state, line state and speed,
    // interrupt flags and enables, address, and endpoint 0's status and
    // flags.
    let watch = async {
        let mut log = Uart;
        let mut next = time::micros();
        loop {
            while time::micros() < next {
                embassy_futures::yield_now().await;
            }
            next += 1_000_000;
            let r8 = |offset: usize| unsafe { core::ptr::read_volatile((0x4502_A000 + offset) as *const u8) };
            let r16 = |offset: usize| unsafe { core::ptr::read_volatile((0x4502_A000 + offset) as *const u16) };
            let _ = writeln!(
                log,
                "usb: CTRLA {:#04x} CTRLB {:#06x} FSM {:#04x} STATUS {:#04x} INTFLAG {:#06x} INTEN {:#06x} DADD {:#04x} EP0 CFG {:#04x} STATUS {:#04x} FLAG {:#04x} EN {:#04x} PADCAL {:#06x}",
                r8(0),
                r16(8),
                r8(0x0D),
                r8(0x0C),
                r16(0x1C),
                r16(0x18),
                r8(0x0A),
                r8(0x100),
                r8(0x106),
                r8(0x107),
                r8(0x109),
                r16(0x28)
            );
        }
    };
    embassy_futures::join::join3(usb.run(), echo, watch).await;
}
