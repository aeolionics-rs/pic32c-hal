//! `pic32c-hal`'s `BufferedUart` read by line, as a line-based serial protocol is,
//! against `uart_peer` on a second board's EXT2 header (SERCOM2, TX PC15, RX PC16,
//! RTS PC17, CTS PC18, 1 Mbaud, RTS/CTS on):
//!
//! - lines: 300 sentences of 20 to 82 characters sent while
//!   reading them back through `fill_buf` and `consume` from a 128-byte
//!   ring, so lines straddle its wrap: every one back, in order;
//! - `available`: one 10-byte line, left unread for 50 ms, counts 10;
//! - `set_baudrate`: a line at 1 Mbaud comes back; at 115200 (`uart_peer` stays
//!   at 1 Mbaud) it doesn't; back at 1 Mbaud it does again;
//! - `set_config` (through embassy-embedded-hal's `SetConfig`): the same
//!   with even parity for the wrong setting (`uart_peer` stays at 8N1);
//! - the blocking `embedded_io` traits: a line written and read back.
//!
//! Over the virtual COM port; LED0 blinks slowly when all passed, fast on a
//! failure.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;

use embassy_embedded_hal::SetConfig;
use embassy_executor::Spawner;
use embassy_futures::join::join;
use embassy_futures::select::{Either, select};
use embassy_time::{Duration, Timer};
use panic_halt as _;
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::uart::{self, BufferedUart, BufferedUartRx};
use pic32c_hal::{bind_interrupts, peripherals};
use pic32ck_curiosity_ultra::time;
use pic32ck_curiosity_ultra::uart::Uart as Log;
use static_cell::ConstStaticCell;

pic32ck_curiosity_ultra::boot!();

bind_interrupts!(struct Irqs {
    SERCOM2_0 => uart::InterruptHandler<peripherals::SERCOM2>;
    SERCOM2_1 => uart::InterruptHandler<peripherals::SERCOM2>;
    SERCOM2_2 => uart::InterruptHandler<peripherals::SERCOM2>;
    SERCOM2_56 => uart::InterruptHandler<peripherals::SERCOM2>;
});

const LINES: usize = 300;
const BAUD: u32 = 1_000_000;

static TX_RING: ConstStaticCell<[u8; 512]> = ConstStaticCell::new([0; 512]);
static RX_RING: ConstStaticCell<[u8; 128]> = ConstStaticCell::new([0; 128]);

struct Tests<'a> {
    log: &'a mut Log,
    failures: u32,
}

impl Tests<'_> {
    fn check(&mut self, name: &str, good: bool, detail: core::fmt::Arguments<'_>) {
        let _ = writeln!(self.log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        self.failures += u32::from(!good);
    }
}

/// Sentence `i`: `$PAEOL,<i>,<padding>*hh\r\n`, 20 to 82 characters, with
/// an XOR checksum of the characters between `$` and `*`.
fn sentence(i: usize, out: &mut heapless::String<82>) {
    out.clear();
    let pad = (i * 37) % 52;
    let _ = write!(out, "$PAEOL,{i:05},");
    for k in 0..pad {
        #[expect(clippy::cast_possible_truncation, reason = "A to Z")]
        let c = (b'A' + ((i + k) % 26) as u8) as char;
        let _ = out.push(c);
    }
    let sum = out.bytes().skip(1).fold(0u8, |a, b| a ^ b);
    let _ = write!(out, "*{sum:02X}\r\n");
}

/// Reads one line (up to and including `\n`) into `line` by `fill_buf` and
/// `consume`: its length, or `None` after 500 ms with nothing.
async fn read_line(rx: &mut BufferedUartRx<'_>, line: &mut heapless::Vec<u8, 128>) -> Option<usize> {
    line.clear();
    loop {
        let chunk = match select(rx.fill_buf(), Timer::after(Duration::from_millis(500))).await {
            Either::First(Ok(chunk)) => chunk,
            Either::First(Err(_)) => continue,
            Either::Second(()) => return None,
        };
        let (take, done) = match chunk.iter().position(|&b| b == b'\n') {
            Some(at) => (at + 1, true),
            None => (chunk.len(), false),
        };
        let _ = line.extend_from_slice(&chunk[..take.min(line.capacity() - line.len())]);
        rx.consume(take);
        if done {
            return Some(line.len());
        }
    }
}

/// Reads whatever comes until 30 ms pass with nothing.
async fn drain(rx: &mut BufferedUartRx<'_>) {
    let mut scratch = [0u8; 64];
    while matches!(select(rx.read(&mut scratch), Timer::after(Duration::from_millis(30))).await, Either::First(_)) {}
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32ck_curiosity_ultra::init();
    time::init(cortex_m::Peripherals::take().unwrap());
    let mut log = Log::init(p.SERCOM5, p.PA24, p.PA25);
    let mut led = Output::new(p.PD20, Level::High);
    let _ = writeln!(log, "\npic32ck-curiosity-ultra uart_lines");
    let mut config = uart::Config::default();
    config.baudrate = BAUD;
    let uart = BufferedUart::new_with_rtscts(p.SERCOM2, p.PC15, p.PC16, p.PC17, p.PC18, Irqs, TX_RING.take(), RX_RING.take(), config).unwrap();
    let (mut tx, mut rx) = uart.split();
    let mut t = Tests { log: &mut log, failures: 0 };
    drain(&mut rx).await;

    // Lines through fill_buf and consume.
    let start = time::micros();
    let mut wrong = 0usize;
    let mut got = 0usize;
    let mut bytes = 0usize;
    let send = async {
        let mut s = heapless::String::<82>::new();
        for i in 0..LINES {
            sentence(i, &mut s);
            let _ = tx.write_all(s.as_bytes()).await;
        }
        let _ = tx.flush().await;
    };
    let receive = async {
        let mut line = heapless::Vec::<u8, 128>::new();
        let mut expected = heapless::String::<82>::new();
        for i in 0..LINES {
            let Some(n) = read_line(&mut rx, &mut line).await else { break };
            sentence(i, &mut expected);
            got += 1;
            bytes += n;
            if line[..] != *expected.as_bytes() {
                wrong += 1;
            }
        }
    };
    join(send, receive).await;
    let us = time::micros() - start;
    t.check("lines", got == LINES && wrong == 0, format_args!("{got} of {LINES} lines ({bytes} bytes) in {us} us, {wrong} wrong"));

    // available: one 10-byte line, unread.
    drain(&mut rx).await;
    let _ = tx.write_all(b"$PAEOL,1\r\n").await;
    let _ = tx.flush().await;
    Timer::after(Duration::from_millis(50)).await;
    let waiting = rx.available();
    t.check("available", waiting == 10, format_args!("{waiting} bytes waiting (the ring holds 128)"));
    drain(&mut rx).await;

    // set_baudrate: right, wrong, right again.
    let mut results = [false; 3];
    for (k, baud) in [BAUD, 115_200, BAUD].into_iter().enumerate() {
        tx.set_baudrate(baud).unwrap();
        drain(&mut rx).await;
        let _ = tx.write_all(b"$PAEOL,BAUD*00\r\n").await;
        let _ = tx.flush().await;
        let mut line = heapless::Vec::<u8, 128>::new();
        let back = read_line(&mut rx, &mut line).await;
        results[k] = back.is_some() && line[..] == *b"$PAEOL,BAUD*00\r\n";
        drain(&mut rx).await;
    }
    let rate = rx.baudrate();
    t.check(
        "set_baudrate",
        results == [true, false, true],
        format_args!("line back at 1 Mbaud {}, at 115200 {}, at 1 Mbaud again {} (now {rate} baud)", results[0], results[1], results[2]),
    );

    // set_config: 8N1, then even parity (`uart_peer` stays at 8N1), then 8N1.
    let mut results = [false; 3];
    for (k, parity) in [uart::Parity::None, uart::Parity::Even, uart::Parity::None].into_iter().enumerate() {
        let mut config = uart::Config::default();
        config.baudrate = BAUD;
        config.parity = parity;
        SetConfig::set_config(&mut tx, &config).unwrap();
        drain(&mut rx).await;
        let _ = tx.write_all(b"$PAEOL,PARITY*00\r\n").await;
        let _ = tx.flush().await;
        let mut line = heapless::Vec::<u8, 128>::new();
        let back = read_line(&mut rx, &mut line).await;
        results[k] = back.is_some() && line[..] == *b"$PAEOL,PARITY*00\r\n";
        drain(&mut rx).await;
    }
    let rate = rx.baudrate();
    t.check(
        "set_config",
        results == [true, false, true],
        format_args!("line back with no parity {}, with even parity {}, with none again {} (now {rate} baud)", results[0], results[1], results[2]),
    );

    // The blocking embedded_io traits.
    drain(&mut rx).await;
    embedded_io::Write::write_all(&mut tx, b"$PAEOL,BLOCKING\r\n").unwrap();
    embedded_io::Write::flush(&mut tx).unwrap();
    let mut back = [0u8; 17];
    let mut at = 0;
    let start = time::micros();
    while at < back.len() && time::micros() - start < 500_000 {
        at += embedded_io::Read::read(&mut rx, &mut back[at..]).unwrap_or(0);
    }
    t.check("blocking", back[..at] == *b"$PAEOL,BLOCKING\r\n", format_args!("{at} bytes back"));

    let failures = t.failures;
    let _ = if failures == 0 { writeln!(log, "uart_lines: all passed") } else { writeln!(log, "uart_lines: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
