//! `pic32c-hal`'s `usbhs` as a network interface: embassy-usb's CDC-NCM
//! class in 512-byte packets on the board's high-speed USB connector
//! (J202), under embassy-net. The host sees a USB Ethernet adapter; the
//! board answers on static link-local addresses (IPv6 `fe80::/64` from its
//! MAC, IPv4 169.254.x.y from its last two bytes):
//! - ping, both families;
//! - TCP echo on port 7, discard on port 9 and chargen (a fixed pattern,
//!   until the host closes) on port 19, one connection each at a time.
//!
//! The NCM class sends its connection and speed notifications on the
//! interrupt IN endpoint and switches the data interface's alternate
//! setting, so this also runs those parts of the driver. Addresses and
//! progress go out over the virtual COM port, and once a second the bytes
//! each service has moved.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;
use core::net::{Ipv4Addr, Ipv6Addr};
use core::sync::atomic::{AtomicUsize, Ordering};

use embassy_executor::Spawner;
use embassy_futures::join::join4;
use embassy_net::tcp::TcpSocket;
use embassy_net::{ConfigV4, Ipv4Cidr, Ipv6Cidr, Stack, StackResources, StaticConfigV4, StaticConfigV6};
use embassy_time::{Duration, Timer};
use embassy_usb::class::cdc_ncm::{self, CdcNcmClass};
use embassy_usb::{Builder, UsbDevice};
use embedded_io_async::Write as _;
use panic_halt as _;
use pic32c_hal::{bind_interrupts, uid, usbhs};
use pic32ck_curiosity_ultra::uart::Uart;
use static_cell::StaticCell;

pic32ck_curiosity_ultra::boot!();

bind_interrupts!(struct Irqs {
    USBHS => usbhs::InterruptHandler;
});

const MTU: usize = 1514;
/// The bulk endpoints' packet size at high speed.
const PACKET: u16 = 512;
type Driver = usbhs::Driver<'static>;
type NetDevice = cdc_ncm::embassy_net::Device<'static, MTU>;

static CONFIG_DESCRIPTOR: StaticCell<[u8; 256]> = StaticCell::new();
static BOS_DESCRIPTOR: StaticCell<[u8; 256]> = StaticCell::new();
static CONTROL_BUF: StaticCell<[u8; 128]> = StaticCell::new();
static NCM_STATE: StaticCell<cdc_ncm::State<'static>> = StaticCell::new();
static NET_STATE: StaticCell<cdc_ncm::embassy_net::State<MTU, 4, 4>> = StaticCell::new();
static RESOURCES: StaticCell<StackResources<6>> = StaticCell::new();

static ECHOED: AtomicUsize = AtomicUsize::new(0);
static DISCARDED: AtomicUsize = AtomicUsize::new(0);
static GENERATED: AtomicUsize = AtomicUsize::new(0);

#[embassy_executor::task]
async fn usb_task(mut device: UsbDevice<'static, Driver>) -> ! {
    device.run().await
}

#[embassy_executor::task]
async fn ncm_task(runner: cdc_ncm::embassy_net::Runner<'static, Driver, MTU>) -> ! {
    runner.run().await
}

#[embassy_executor::task]
async fn net_task(mut runner: embassy_net::Runner<'static, NetDevice>) -> ! {
    runner.run().await
}

/// `fe80::/64` with `mac` as modified EUI-64.
fn link_local(mac: [u8; 6]) -> Ipv6Addr {
    Ipv6Addr::from([0xfe, 0x80, 0, 0, 0, 0, 0, 0, mac[0] ^ 0x02, mac[1], mac[2], 0xff, 0xfe, mac[3], mac[4], mac[5]])
}

/// 169.254.x.y from the last two bytes of `mac` (x kept off 0 and 255).
fn link_local_v4(mac: [u8; 6]) -> Ipv4Addr {
    Ipv4Addr::new(169, 254, 1 + mac[4] % 254, mac[5])
}

/// One connection at a time on `port`, running `serve` on it.
async fn service<F: AsyncFnMut(&mut TcpSocket<'_>)>(stack: Stack<'static>, port: u16, mut serve: F) -> ! {
    let mut rx = [0; 8192];
    let mut tx = [0; 8192];
    loop {
        let mut socket = TcpSocket::new(stack, &mut rx, &mut tx);
        socket.set_timeout(Some(Duration::from_secs(10)));
        if socket.accept(port).await.is_err() {
            continue;
        }
        serve(&mut socket).await;
        // The FIN out and acknowledged before the socket goes: dropped
        // straight after `close`, it never sends it.
        socket.close();
        let _ = socket.flush().await;
    }
}

#[embassy_executor::main]
async fn main(spawner: Spawner) {
    let p = pic32ck_curiosity_ultra::init();
    let mut log = Uart::init(p.SERCOM5, p.PA24, p.PA25);
    let _ = writeln!(log, "\npic32ck-curiosity-ultra usbhs_ncm");

    let id = uid::unique_id();
    let mac = [0x02, id[1], id[2], id[3], id[4], id[5]];
    let host_mac = [0x06, id[1], id[2], id[3], id[4], id[5]];
    let address = link_local(mac);
    let address_v4 = link_local_v4(mac);

    let mut config = embassy_usb::Config::new(0x1209, 0x000B);
    config.manufacturer = Some("Aeolionics");
    config.product = Some("PIC32CK USB HS NCM");
    config.serial_number = Some("pic32ck-curiosity-ultra-ncm");
    config.max_power = 100;
    config.max_packet_size_0 = 64;

    let driver = usbhs::Driver::new(p.USBHS, Irqs, usbhs::Config::default());
    let mut builder = Builder::new(driver, config, CONFIG_DESCRIPTOR.init([0; 256]), BOS_DESCRIPTOR.init([0; 256]), &mut [], CONTROL_BUF.init([0; 128]));
    let ncm = CdcNcmClass::new(&mut builder, NCM_STATE.init(cdc_ncm::State::new()), host_mac, PACKET);
    let (ncm_runner, device) = ncm.into_embassy_net_device::<MTU, 4, 4>(NET_STATE.init(cdc_ncm::embassy_net::State::new()), mac);
    spawner.spawn(usb_task(builder.build()).unwrap());
    spawner.spawn(ncm_task(ncm_runner).unwrap());

    let mut net_config = embassy_net::Config::ipv6_static(StaticConfigV6 { address: Ipv6Cidr::new(address, 64), gateway: None, dns_servers: heapless::Vec::new() });
    net_config.ipv4 = ConfigV4::Static(StaticConfigV4 { address: Ipv4Cidr::new(address_v4, 16), gateway: None, dns_servers: heapless::Vec::new() });
    let seed = u64::from_le_bytes([id[8], id[9], id[10], id[11], id[12], id[13], id[14], id[15]]);
    let (stack, runner) = embassy_net::new(device, net_config, RESOURCES.init(StackResources::new()), seed);
    spawner.spawn(net_task(runner).unwrap());
    let _ = writeln!(log, "MAC {mac:02x?}; IPv6 {address}; IPv4 {address_v4}");

    let echo = service(stack, 7, async |socket| {
        let mut buffer = [0; 4096];
        loop {
            match socket.read(&mut buffer).await {
                Ok(0) | Err(_) => break,
                Ok(n) => {
                    if socket.write_all(&buffer[..n]).await.is_err() {
                        break;
                    }
                    ECHOED.fetch_add(n, Ordering::Relaxed);
                }
            }
        }
    });
    let discard = service(stack, 9, async |socket| {
        let mut buffer = [0; 4096];
        while let Ok(n @ 1..) = socket.read(&mut buffer).await {
            DISCARDED.fetch_add(n, Ordering::Relaxed);
        }
    });
    let chargen = service(stack, 19, async |socket| {
        let mut pattern = [0; 4096];
        for (i, byte) in pattern.iter_mut().enumerate() {
            #[expect(clippy::cast_possible_truncation, reason = "the low byte")]
            let low = i as u8;
            *byte = low;
        }
        // The pattern runs on across partial writes.
        let mut offset = 0;
        while let Ok(n @ 1..) = socket.write(&pattern[offset..]).await {
            offset = (offset + n) % pattern.len();
            GENERATED.fetch_add(n, Ordering::Relaxed);
        }
    });
    let watch = async {
        let mut log = Uart;
        let mut up = false;
        loop {
            Timer::after_secs(1).await;
            if stack.is_link_up() != up {
                up = stack.is_link_up();
                let _ = writeln!(log, "link {}, high speed: {}", if up { "up" } else { "down" }, usbhs::is_high_speed());
            }
            let _ = writeln!(
                log,
                "echoed {} discarded {} generated {}",
                ECHOED.load(Ordering::Relaxed),
                DISCARDED.load(Ordering::Relaxed),
                GENERATED.load(Ordering::Relaxed)
            );
        }
    };
    #[expect(clippy::large_futures, reason = "main's future lives in the executor's static task storage, not on a stack")]
    join4(echo, discard, chargen, watch).await;
}
