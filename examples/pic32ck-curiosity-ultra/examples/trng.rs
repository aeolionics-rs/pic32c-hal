//! `pic32c-hal`'s `trng`: the TRNG's bus clock as reset leaves it (MCLK
//! CLKMSK3 bit 16), the time per word blocking and waiting on the
//! interrupt, and sanity statistics over 2 Mbit (65,536 words): the share
//! of ones, a chi-square over byte values (255 degrees of freedom), the
//! longest run of equal bits, and repeated consecutive words. These catch
//! a stuck or biased source, not a subtly weak one. The first words go out
//! too, to compare boards and boots. Over the virtual COM port.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;
use core::ptr::read_volatile;

use pic32ck_curiosity_ultra::time;
use pic32ck_curiosity_ultra::uart::Uart;
use embassy_executor::Spawner;
use panic_halt as _;
use pic32c_hal::bind_interrupts;
use pic32c_hal::trng::{self, Trng};

pic32ck_curiosity_ultra::boot!();

bind_interrupts!(struct Irqs {
    TRNG => trng::InterruptHandler;
});

const CLKMSK3: usize = 0x4401_2000 + 0x3C + 3 * 4;
const WORDS: u32 = 65_536;

/// Running statistics over the words as they come.
struct Stats {
    ones: u64,
    bytes: [u32; 256],
    run: u32,
    longest: u32,
    last_bit: bool,
    last_word: Option<u32>,
    repeats: u32,
}

impl Stats {
    const fn new() -> Self {
        Self { ones: 0, bytes: [0; 256], run: 0, longest: 0, last_bit: false, last_word: None, repeats: 0 }
    }

    fn add(&mut self, word: u32) {
        self.ones += u64::from(word.count_ones());
        for byte in word.to_le_bytes() {
            self.bytes[usize::from(byte)] += 1;
        }
        for i in 0..32 {
            let bit = word >> i & 1 != 0;
            if bit == self.last_bit {
                self.run += 1;
            } else {
                self.run = 1;
                self.last_bit = bit;
            }
            self.longest = self.longest.max(self.run);
        }
        if self.last_word == Some(word) {
            self.repeats += 1;
        }
        self.last_word = Some(word);
    }

    /// Chi-square of the byte counts against a uniform spread.
    fn chi_square(&self) -> f32 {
        #[expect(clippy::cast_precision_loss, reason = "counts up to 2^18, exact in f32")]
        let expected = (WORDS * 4) as f32 / 256.0;
        self.bytes
            .iter()
            .map(|&n| {
                #[expect(clippy::cast_precision_loss, reason = "as above")]
                let d = n as f32 - expected;
                d * d / expected
            })
            .sum()
    }
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let mut p = pic32ck_curiosity_ultra::init();
    time::init(cortex_m::Peripherals::take().unwrap());
    let mut log = Uart::init(p.SERCOM5, p.PA24, p.PA25);
    let _ = writeln!(log, "\npic32ck-curiosity-ultra trng");
    let mut failures = 0u32;

    // SAFETY: a read of an MCLK register.
    let mask = unsafe { read_volatile(CLKMSK3 as *const u32) };
    let _ = writeln!(log, "MCLK CLKMSK3 {mask:#010x}: TRNG bus clock bit {}", mask >> 16 & 1);

    let mut rng = Trng::new(p.TRNG.reborrow(), Irqs);
    let first: [u32; 4] = core::array::from_fn(|_| rng.next_u32_blocking());
    let _ = writeln!(log, "first words {:08x} {:08x} {:08x} {:08x}", first[0], first[1], first[2], first[3]);

    let start = time::cycles();
    for _ in 0..1000 {
        let _ = rng.next_u32_blocking();
    }
    let blocking = (time::cycles() - start) / 1000;
    let start = time::cycles();
    for _ in 0..1000 {
        let _ = rng.next_u32().await;
    }
    let waiting = (time::cycles() - start) / 1000;
    let _ = writeln!(log, "per word: {blocking} CPU cycles blocking, {waiting} waiting on the interrupt");

    let mut buffer = [0u8; 4099];
    let start = time::micros();
    rng.fill(&mut buffer).await;
    let filled = time::micros() - start;
    #[expect(clippy::naive_bytecount, reason = "4 KiB once; not worth a crate")]
    let zeros = buffer.iter().filter(|&&b| b == 0).count();
    let _ = writeln!(log, "fill 4,099 bytes: {filled} us ({zeros} zero bytes)");

    let mut stats = Stats::new();
    for _ in 0..WORDS {
        stats.add(rng.next_u32_blocking());
    }
    let bits = u64::from(WORDS) * 32;
    #[expect(clippy::cast_precision_loss, reason = "2^21 bits, exact in f32")]
    let share = stats.ones as f32 / bits as f32;
    let chi = stats.chi_square();
    // Bounds well past chance for a good source: the share's sd is 0.00035,
    // the chi-square's 99.9th percentile is ~330, a run past 40 in 2^21
    // bits is under one in a million, and a repeat one in 2^32 per word.
    let checks = [
        ("share of ones", (0.497..0.503).contains(&share)),
        ("byte chi-square", chi < 330.0),
        ("longest run", stats.longest <= 40),
        ("repeated words", stats.repeats == 0),
    ];
    let _ = writeln!(log, "2 Mbit: ones {share:.5}, chi-square {chi:.1}, longest run {}, repeated words {}", stats.longest, stats.repeats);
    for (name, good) in checks {
        if !good {
            let _ = writeln!(log, "{name}: FAILED");
            failures += 1;
        }
    }

    drop(rng);
    let mut rng = Trng::new(p.TRNG, Irqs);
    let again = rng.next_u32().await;
    let _ = writeln!(log, "after a drop and new: {again:08x}");

    if failures == 0 {
        let _ = writeln!(log, "trng: all passed");
    } else {
        let _ = writeln!(log, "trng: {failures} failures");
    }
    loop {
        cortex_m::asm::wfi();
    }
}
