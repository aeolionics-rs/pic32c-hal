//! `pic32c-hal`'s `trng`: the TRNG's bus clock as reset leaves it (MCLK
//! CLKMSK3 bit 16), the time per word blocking and waiting on the
//! interrupt, and sanity statistics over 2 Mbit (65,536 words; see
//! `common/rng_stats.rs`). The first words go out too, to compare boards and
//! boots. Over the virtual COM port. Built without `tls`, which gives the
//! TRNG to embassy-crypto (`crypto_rng` checks that side).

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;
use core::ptr::read_volatile;

use embassy_executor::Spawner;
use panic_halt as _;
use pic32c_hal::bind_interrupts;
use pic32c_hal::trng::{self, Trng};
use pic32ck_curiosity_ultra::time;
use pic32ck_curiosity_ultra::uart::Uart;

pic32ck_curiosity_ultra::boot!();

#[path = "common/rng_stats.rs"]
mod rng_stats;
use rng_stats::{Stats, WORDS};

bind_interrupts!(struct Irqs {
    TRNG => trng::InterruptHandler;
});

const CLKMSK3: usize = 0x4401_2000 + 0x3C + 3 * 4;

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let mut p = pic32ck_curiosity_ultra::init();
    time::init(cortex_m::Peripherals::take().unwrap());
    let mut log = Uart::init(p.SERCOM5, p.PA24, p.PA25);
    let _ = writeln!(log, "\npic32ck-curiosity-ultra trng");
    let mut failures = 0u32;

    // SAFETY: a read of an MCLK register.
    let mask = unsafe { read_volatile(CLKMSK3 as *const u32) };
    let _ = writeln!(log, "MCLK CLKMSK3 {mask:#010x}: TRNG bus clock bit {}", mask >> 16 & 1);

    let mut rng = Trng::new(p.TRNG.reborrow(), Irqs);
    let first: [u32; 4] = core::array::from_fn(|_| rng.next_u32_blocking());
    let _ = writeln!(log, "first words {:08x} {:08x} {:08x} {:08x}", first[0], first[1], first[2], first[3]);

    let start = time::cycles();
    for _ in 0..1000 {
        let _ = rng.next_u32_blocking();
    }
    let blocking = (time::cycles() - start) / 1000;
    let start = time::cycles();
    for _ in 0..1000 {
        let _ = rng.next_u32().await;
    }
    let waiting = (time::cycles() - start) / 1000;
    let _ = writeln!(log, "per word: {blocking} CPU cycles blocking, {waiting} waiting on the interrupt");

    let mut buffer = [0u8; 4099];
    let start = time::micros();
    rng.fill(&mut buffer).await;
    let filled = time::micros() - start;
    #[expect(clippy::naive_bytecount, reason = "4 KiB once; not worth a crate")]
    let zeros = buffer.iter().filter(|&&b| b == 0).count();
    let _ = writeln!(log, "fill 4,099 bytes: {filled} us ({zeros} zero bytes)");

    let mut stats = Stats::new();
    for _ in 0..WORDS {
        stats.add(rng.next_u32_blocking());
    }
    failures += stats.report(&mut log);

    drop(rng);
    let mut rng = Trng::new(p.TRNG, Irqs);
    let again = rng.next_u32().await;
    let _ = writeln!(log, "after a drop and new: {again:08x}");

    if failures == 0 {
        let _ = writeln!(log, "trng: all passed");
    } else {
        let _ = writeln!(log, "trng: {failures} failures");
    }
    loop {
        cortex_m::asm::wfi();
    }
}
