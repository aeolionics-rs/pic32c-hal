//! `pic32c-hal`'s async `flash` (`Flash::new`, `embedded-storage-async`,
//! the NVMCTRL's READY interrupt bound) on `flash`'s scratch areas: the top
//! 1 KiB of flash (offset `0x7C00`) and a row at `0x6000`.
//!
//! A ticker task counts 100 µs timer ticks beside each operation. Flash is
//! one array and the program runs from it, so the CPU stalls through every
//! erase and write and the ticker barely runs: this checks the
//! interrupt-driven path works, not that anything runs meanwhile. Then:
//! words from SRAM and from a pattern in flash, written and read back; and
//! an erase whose future is dropped 1 ms in (in practice after the stall),
//! after which the row must read erased and the next operation work. Over
//! the virtual COM port; the LED blinks slowly when all passed, fast on a
//! failure.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;
use core::sync::atomic::{AtomicU32, Ordering};

use embassy_executor::Spawner;
use embassy_futures::select::{Either, select};
use embassy_time::{Duration, Timer};
use embedded_storage_async::nor_flash::{NorFlash, ReadNorFlash};
use panic_halt as _;
use pic32c_hal::bind_interrupts;
use pic32c_hal::flash::{self, Async, Flash, ROW_SIZE};
use pic32c_hal::gpio::{Level, Output};
use pic32cm_gv_curiosity_nano::{Log, micros};

bind_interrupts!(struct Irqs {
    NVMCTRL => flash::InterruptHandler;
});

const TOP: u32 = 0x7C00;
const MIDDLE: u32 = 0x6000;
/// [`ROW_SIZE`], the erase unit, as the flash API's offsets.
const ROW: u32 = 256;
const _: () = assert!(ROW as usize == ROW_SIZE);
/// The erase unit, as the other chips' examples name it.
const PAGE: u32 = ROW;
const PAGE_SIZE: usize = ROW_SIZE;

/// 100 µs ticks taken by the ticker task.
static TICKS: AtomicU32 = AtomicU32::new(0);

/// A pattern held in flash, for flash-word writes.
static PATTERN: [u8; 256] = {
    let mut p = [0; 256];
    let mut i = 0;
    while i < 256 {
        #[expect(clippy::cast_possible_truncation, reason = "the low byte")]
        let b = (i * 7 + 3) as u8;
        p[i] = b;
        i += 1;
    }
    p
};

#[repr(C, align(4))]
struct Row([u8; ROW_SIZE]);

async fn ticker() -> ! {
    loop {
        Timer::after(Duration::from_micros(100)).await;
        // No read-modify-write atomics on the M0+; only this task writes.
        TICKS.store(TICKS.load(Ordering::Relaxed) + 1, Ordering::Relaxed);
    }
}

/// Runs `operation`, returning its result, its time in µs and the ticks the
/// ticker took meanwhile.
async fn timed<R>(operation: impl Future<Output = R>) -> (R, u64, u32) {
    let ticks = TICKS.load(Ordering::Relaxed);
    let start = micros();
    let result = operation.await;
    (result, micros() - start, TICKS.load(Ordering::Relaxed) - ticks)
}

/// Whether `length` bytes at `offset` all read `0xFF`.
async fn erased(flash: &mut Flash<'_, Async>, offset: u32, length: usize) -> bool {
    let mut buffer = [0u8; 256];
    let mut done = 0;
    while done < length {
        let n = buffer.len().min(length - done);
        #[expect(clippy::cast_possible_truncation, reason = "within a page")]
        let at = offset + done as u32;
        if flash.read(at, &mut buffer[..n]).await.is_err() || buffer[..n].iter().any(|&b| b != 0xFF) {
            return false;
        }
        done += n;
    }
    true
}

async fn tests(flash: &mut Flash<'_, Async>, log: &mut Log) -> u32 {
    let mut failures = 0;
    let mut check = |name: &str, good: bool, detail: core::fmt::Arguments<'_>| {
        let _ = writeln!(log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        failures += u32::from(!good);
    };

    // An erase in each area, with the ticker's count meanwhile.
    let (result, us, ticks) = timed(flash.erase(TOP, TOP + PAGE)).await;
    let ok = result.is_ok() && erased(flash, TOP, PAGE_SIZE).await;
    check("erase a top row", ok, format_args!("in {us} us, ticker ran {ticks} times ({result:?}; the CPU stalls)"));
    let (result, us, ticks) = timed(flash.erase(MIDDLE, MIDDLE + PAGE)).await;
    let ok = result.is_ok() && erased(flash, MIDDLE, PAGE_SIZE).await;
    check("erase the middle row", ok, format_args!("in {us} us, ticker ran {ticks} times ({result:?})"));

    // Rows from SRAM.
    let mut row = Row([0; ROW_SIZE]);
    for (i, b) in row.0.iter_mut().enumerate() {
        #[expect(clippy::cast_possible_truncation, reason = "the low byte")]
        let v = (i ^ 0x5A) as u8;
        *b = v;
    }
    let (result, us, ticks) = timed(flash.write(TOP, &row.0)).await;
    let mut back = [0u8; ROW_SIZE];
    let _ = flash.read(TOP, &mut back).await;
    check("words from SRAM", result.is_ok() && back == row.0, format_args!("256 B in {us} us, ticker {ticks} ({result:?})"));

    // Words from a pattern in flash.
    let at = TOP + ROW;
    let (result, us, ticks) = timed(flash.write(at, &PATTERN)).await;
    let mut back = [0u8; 256];
    let _ = flash.read(at, &mut back).await;
    check("words from flash", result.is_ok() && back == PATTERN, format_args!("256 B in {us} us, ticker {ticks} ({result:?})"));

    // Misaligned and out-of-range writes are refused.
    let refused = matches!(flash.write(TOP + 2, &PATTERN[..32]).await, Err(flash::Error::NotAligned)) && matches!(flash.erase(0x7F00, 0x8100).await, Err(flash::Error::OutOfBounds));
    check("misaligned and out-of-range refused", refused, format_args!(""));

    // A dropped erase: the row must still end erased, and the flash work.
    let page = TOP + PAGE;
    let _ = flash.write(page, &PATTERN).await;
    let dropped = match select(flash.erase(page, page + PAGE), Timer::after(Duration::from_millis(1))).await {
        Either::First(_) => "finished within 1 ms",
        Either::Second(()) => "dropped after 1 ms",
    };
    let ok = erased(flash, page, PAGE_SIZE).await;
    let after = flash.write(page, &PATTERN[..64]).await;
    let mut back = [0u8; 64];
    let _ = flash.read(page, &mut back).await;
    check("an erase dropped part way", ok && after.is_ok() && back == PATTERN[..64], format_args!("({dropped}; erased {ok}, then a write {after:?})"));

    // Clean up.
    let _ = flash.erase(TOP, TOP + 4 * PAGE).await;
    let _ = flash.erase(MIDDLE, MIDDLE + PAGE).await;
    failures
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32cm_gv_curiosity_nano::init();
    let mut log = Log::init(p.SERCOM2, p.PA12, p.PA13);
    let mut led = Output::new(p.PA24, Level::Low);
    let _ = writeln!(log, "\npic32cm-gv-curiosity-nano flash_async");
    let mut flash = Flash::new(p.NVMCTRL, Irqs);

    let failures = match select(tests(&mut flash, &mut log), ticker()).await {
        Either::First(failures) => failures,
        Either::Second(never) => never,
    };
    let _ = if failures == 0 { writeln!(log, "flash_async: all passed") } else { writeln!(log, "flash_async: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
