//! `pic32c-hal`'s `spi` on the board's SPI pins (SERCOM5, function D: MOSI
//! PB02, pad 0; SCK PB03, pad 1; MISO PB00, pad 2), with nothing wired to
//! them, so in loopback: the receiver reads the MOSI pad, through the pin.
//! The CPU at 47.97 MHz from the DFLL48M on the crystal, so SCK reaches the
//! GV00's rated 8 MHz. Blocking only (the GV00 has no DMA): rates from
//! 1 MHz to 8 MHz, the four modes and LSB first, transfers of unequal
//! lengths and in place, timed; then a full-duplex SPI with MISO on PB00,
//! which reads whatever the open pin gives. Over the virtual COM port; the
//! LED blinks slowly when all passed, fast on a failure.

#![no_std]
#![no_main]
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;

use embassy_executor::Spawner;
use embassy_time::{Duration, Timer};
use embedded_hal::spi::{MODE_0, MODE_1, MODE_2, MODE_3};
use panic_halt as _;
use pic32c_hal::clocks;
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::spi::{BitOrder, Config, Spi};
use pic32cm_gv_curiosity_nano::{Log, micros};

struct Tests<'a> {
    log: &'a mut Log,
    failures: u32,
}

impl Tests<'_> {
    fn check(&mut self, name: &str, good: bool, detail: core::fmt::Arguments<'_>) {
        let _ = writeln!(self.log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        self.failures += u32::from(!good);
    }
}

fn pattern(buffer: &mut [u8], seed: u8) {
    for (i, b) in buffer.iter_mut().enumerate() {
        #[expect(clippy::cast_possible_truncation, reason = "a pattern")]
        let v = (i as u8).wrapping_mul(37).wrapping_add(seed);
        *b = v;
    }
}

fn config(frequency: u32) -> Config {
    let mut config = Config::default();
    config.frequency = frequency;
    config.loopback = true;
    config
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let mut p = pic32c_hal::init(pic32c_hal::Config::new(clocks::Config::dfll48m_from_xosc32k()));
    let mut log = Log::init(p.SERCOM2, p.PA12, p.PA13);
    let mut led = Output::new(p.PA24, Level::Low);
    let _ = writeln!(log, "\npic32cm-gv-curiosity-nano spi, CPU {} Hz", clocks::frequencies().map_or(0, |f| f.cpu()));
    let mut t = Tests { log: &mut log, failures: 0 };

    // 256 bytes each, of the 4 KB of SRAM.
    let mut out = [0u8; 256];
    let mut back = [0u8; 256];
    pattern(&mut out, 5);

    // At several rates, the last the most SCK may run.
    for frequency in [1_000_000, 2_000_000, 4_000_000, 8_000_000, 24_000_000] {
        let mut spi = Spi::new_blocking_txonly(p.SERCOM5.reborrow(), p.PB03.reborrow(), p.PB02.reborrow(), config(frequency)).unwrap();
        back.fill(0);
        let start = micros();
        let result = spi.blocking_transfer(&mut back, &out);
        let us = micros() - start;
        t.check(
            "rate",
            result.is_ok() && back == out && spi.frequency() <= 8_000_000,
            format_args!("asked {frequency} Hz, got {} Hz: 256 bytes in {us} us ({result:?})", spi.frequency()),
        );
    }

    // The four modes and LSB first: one bus, moved between them by
    // `set_config`.
    let mut spi = Spi::new_blocking_txonly(p.SERCOM5.reborrow(), p.PB03.reborrow(), p.PB02.reborrow(), config(1_000_000)).unwrap();
    for (name, mode) in [("mode 0", MODE_0), ("mode 1", MODE_1), ("mode 2", MODE_2), ("mode 3", MODE_3)] {
        for bit_order in [BitOrder::MsbFirst, BitOrder::LsbFirst] {
            let mut config = config(4_000_000);
            config.mode = mode;
            config.bit_order = bit_order;
            spi.set_config(&config).unwrap();
            back.fill(0);
            let result = spi.blocking_transfer(&mut back[..64], &out[..64]);
            t.check(name, result.is_ok() && back[..64] == out[..64], format_args!("{bit_order:?} at {} Hz ({result:?})", spi.frequency()));
        }
    }
    drop(spi);

    // Unequal lengths and in place.
    {
        let mut spi = Spi::new_blocking_txonly(p.SERCOM5.reborrow(), p.PB03.reborrow(), p.PB02.reborrow(), config(8_000_000)).unwrap();
        back.fill(0xEE);
        let result = spi.blocking_transfer(&mut back[..40], &out[..32]);
        t.check("read longer", result.is_ok() && back[..32] == out[..32] && back[32..40].iter().all(|&b| b == 0) && back[40] == 0xEE, format_args!("({result:?})"));
        back.fill(0xEE);
        let result = spi.blocking_transfer(&mut back[..20], &out[..60]);
        t.check("write longer", result.is_ok() && back[..20] == out[..20] && back[20] == 0xEE, format_args!("({result:?})"));
        let mut words = [0u8; 100];
        pattern(&mut words, 9);
        let sent = words;
        let result = spi.blocking_transfer_in_place(&mut words);
        t.check("in place", result.is_ok() && words == sent, format_args!("({result:?})"));
        let result = embedded_hal::spi::SpiBus::write(&mut spi, &out);
        t.check("write alone (SpiBus)", result.is_ok(), format_args!("({result:?})"));
    }

    // Full duplex with MISO on PB00, open: it runs, whatever it reads.
    {
        let mut config = Config::default();
        config.frequency = 8_000_000;
        let mut spi = Spi::new_blocking(p.SERCOM5.reborrow(), p.PB03.reborrow(), p.PB02.reborrow(), p.PB00.reborrow(), config).unwrap();
        let result = spi.blocking_transfer(&mut back, &out);
        let ones = back.iter().fold(0, |n, &b| n + usize::from(b == 0xFF));
        t.check("full duplex, MISO on PB00", result.is_ok(), format_args!("{ones} of 256 bytes read 0xFF ({result:?})"));
    }

    let failures = t.failures;
    let _ = if failures == 0 { writeln!(log, "spi: all passed") } else { writeln!(log, "spi: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
