//! `pic32c-hal`'s `spi` on the board's SPI pins (SERCOM5, function D: MOSI
//! PB02, pad 0; SCK PB03, pad 1; MISO PB00, pad 2), with nothing wired to
//! them, so in loopback: the receiver reads the MOSI pad, through the pin.
//! The CPU at 47.97 MHz from the DFLL48M on the crystal, so SCK reaches the
//! GV00's rated 8 MHz. Blocking: rates from 1 MHz to 8 MHz, the four modes
//! and LSB first, transfers of unequal lengths and in place, timed. Then
//! async, the SERCOM's interrupt moving the bytes (the GV00 has no DMA),
//! with a ticker task counting 100 µs ticks meanwhile: the same transfers,
//! the embedded-hal-async trait, and a transfer dropped part way, after
//! which the bus must work. Then full duplex with MISO on PB00, which reads
//! whatever the open pin gives. Over the virtual COM port; the LED blinks
//! slowly when all passed, fast on a failure.

#![no_std]
#![no_main]
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;
use core::sync::atomic::{AtomicU32, Ordering};

use embassy_executor::Spawner;
use embassy_futures::select::{Either, select};
use embassy_time::{Duration, Timer};
use embedded_hal::spi::{MODE_0, MODE_1, MODE_2, MODE_3};
use panic_halt as _;
use pic32c_hal::clocks;
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::spi::{self, BitOrder, Config, Spi};
use pic32c_hal::{bind_interrupts, peripherals};
use pic32cm_gv_curiosity_nano::{Log, micros};

bind_interrupts!(struct Irqs {
    SERCOM5 => spi::InterruptHandler<peripherals::SERCOM5>;
});

/// 100 µs ticks taken by the ticker task.
static TICKS: AtomicU32 = AtomicU32::new(0);

async fn ticker() -> ! {
    loop {
        Timer::after(Duration::from_micros(100)).await;
        // No read-modify-write atomics on the M0+; only this task writes.
        TICKS.store(TICKS.load(Ordering::Relaxed) + 1, Ordering::Relaxed);
    }
}

struct Tests<'a> {
    log: &'a mut Log,
    failures: u32,
}

impl Tests<'_> {
    fn check(&mut self, name: &str, good: bool, detail: core::fmt::Arguments<'_>) {
        let _ = writeln!(self.log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        self.failures += u32::from(!good);
    }
}

fn pattern(buffer: &mut [u8], seed: u8) {
    for (i, b) in buffer.iter_mut().enumerate() {
        #[expect(clippy::cast_possible_truncation, reason = "a pattern")]
        let v = (i as u8).wrapping_mul(37).wrapping_add(seed);
        *b = v;
    }
}

fn config(frequency: u32) -> Config {
    let mut config = Config::default();
    config.frequency = frequency;
    config.loopback = true;
    config
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let mut p = pic32c_hal::init(pic32c_hal::Config::new(clocks::Config::dfll48m_from_xosc32k()));
    let mut log = Log::init(p.SERCOM2, p.PA12, p.PA13);
    let mut led = Output::new(p.PA24, Level::Low);
    let _ = writeln!(log, "\npic32cm-gv-curiosity-nano spi, CPU {} Hz", clocks::frequencies().map_or(0, |f| f.cpu()));
    let mut t = Tests { log: &mut log, failures: 0 };

    // 256 bytes each, of the 4 KB of SRAM.
    let mut out = [0u8; 256];
    let mut back = [0u8; 256];
    pattern(&mut out, 5);

    // At several rates, the last the most SCK may run.
    for frequency in [1_000_000, 2_000_000, 4_000_000, 8_000_000, 24_000_000] {
        let mut spi = Spi::new_blocking_txonly(p.SERCOM5.reborrow(), p.PB03.reborrow(), p.PB02.reborrow(), config(frequency)).unwrap();
        back.fill(0);
        let start = micros();
        let result = spi.blocking_transfer(&mut back, &out);
        let us = micros() - start;
        t.check(
            "rate",
            result.is_ok() && back == out && spi.frequency() <= 8_000_000,
            format_args!("asked {frequency} Hz, got {} Hz: 256 bytes in {us} us ({result:?})", spi.frequency()),
        );
    }

    // The four modes and LSB first: one bus, moved between them by
    // `set_config`.
    let mut spi = Spi::new_blocking_txonly(p.SERCOM5.reborrow(), p.PB03.reborrow(), p.PB02.reborrow(), config(1_000_000)).unwrap();
    for (name, mode) in [("mode 0", MODE_0), ("mode 1", MODE_1), ("mode 2", MODE_2), ("mode 3", MODE_3)] {
        for bit_order in [BitOrder::MsbFirst, BitOrder::LsbFirst] {
            let mut config = config(4_000_000);
            config.mode = mode;
            config.bit_order = bit_order;
            spi.set_config(&config).unwrap();
            back.fill(0);
            let result = spi.blocking_transfer(&mut back[..64], &out[..64]);
            t.check(name, result.is_ok() && back[..64] == out[..64], format_args!("{bit_order:?} at {} Hz ({result:?})", spi.frequency()));
        }
    }
    drop(spi);

    // Unequal lengths and in place.
    {
        let mut spi = Spi::new_blocking_txonly(p.SERCOM5.reborrow(), p.PB03.reborrow(), p.PB02.reborrow(), config(8_000_000)).unwrap();
        back.fill(0xEE);
        let result = spi.blocking_transfer(&mut back[..40], &out[..32]);
        t.check("read longer", result.is_ok() && back[..32] == out[..32] && back[32..40].iter().all(|&b| b == 0) && back[40] == 0xEE, format_args!("({result:?})"));
        back.fill(0xEE);
        let result = spi.blocking_transfer(&mut back[..20], &out[..60]);
        t.check("write longer", result.is_ok() && back[..20] == out[..20] && back[20] == 0xEE, format_args!("({result:?})"));
        let mut words = [0u8; 100];
        pattern(&mut words, 9);
        let sent = words;
        let result = spi.blocking_transfer_in_place(&mut words);
        t.check("in place", result.is_ok() && words == sent, format_args!("({result:?})"));
        let result = embedded_hal::spi::SpiBus::write(&mut spi, &out);
        t.check("write alone (SpiBus)", result.is_ok(), format_args!("({result:?})"));
    }

    // Async, on the interrupt, beside a ticker task.
    let async_tests = async {
        for frequency in [1_000_000, 4_000_000, 8_000_000] {
            let mut spi = Spi::new_txonly(p.SERCOM5.reborrow(), p.PB03.reborrow(), p.PB02.reborrow(), Irqs, config(frequency)).unwrap();
            back.fill(0);
            let ticks = TICKS.load(Ordering::Relaxed);
            let start = micros();
            let result = spi.transfer(&mut back, &out).await;
            let us = micros() - start;
            let ticks = TICKS.load(Ordering::Relaxed) - ticks;
            t.check("async rate", result.is_ok() && back == out, format_args!("256 bytes at {} Hz in {us} us, ticker ran {ticks} times ({result:?})", spi.frequency()));
        }
        let mut spi = Spi::new_txonly(p.SERCOM5.reborrow(), p.PB03.reborrow(), p.PB02.reborrow(), Irqs, config(8_000_000)).unwrap();
        back.fill(0xEE);
        let result = spi.transfer(&mut back[..40], &out[..32]).await;
        t.check(
            "async, read longer",
            result.is_ok() && back[..32] == out[..32] && back[32..40].iter().all(|&b| b == 0) && back[40] == 0xEE,
            format_args!("({result:?})"),
        );
        back.fill(0xEE);
        let result = spi.transfer(&mut back[..20], &out[..60]).await;
        t.check("async, write longer", result.is_ok() && back[..20] == out[..20] && back[20] == 0xEE, format_args!("({result:?})"));
        let mut words = [0u8; 100];
        pattern(&mut words, 9);
        let sent = words;
        let result = spi.transfer_in_place(&mut words).await;
        t.check("async, in place", result.is_ok() && words == sent, format_args!("({result:?})"));
        back.fill(0xEE);
        let result = spi.read(&mut back[..64]).await;
        t.check("async read alone", result.is_ok() && back[..64].iter().all(|&b| b == 0), format_args!("zeros sent and read back ({result:?})"));
        let result = embedded_hal_async::spi::SpiBus::write(&mut spi, &out).await;
        t.check("async write alone (SpiBus)", result.is_ok(), format_args!("({result:?})"));

        // A transfer dropped part way (256 bytes at 1 MHz take about 2 ms),
        // then the bus again.
        spi.set_config(&config(1_000_000)).unwrap();
        back.fill(0);
        let dropped = match select(spi.transfer(&mut back, &out), Timer::after(Duration::from_micros(500))).await {
            Either::First(_) => "finished",
            Either::Second(()) => "dropped",
        };
        let moved = back.iter().zip(out.iter()).take_while(|(a, b)| a == b).count();
        back.fill(0);
        let after = spi.transfer(&mut back[..64], &out[..64]).await;
        t.check(
            "async, dropped part way",
            dropped == "dropped" && after.is_ok() && back[..64] == out[..64],
            format_args!("{dropped} after 500 us with {moved} bytes moved; then 64 bytes {after:?}"),
        );
        // The blocking calls on the async SPI.
        back.fill(0);
        let result = spi.blocking_transfer(&mut back[..16], &out[..16]);
        t.check("blocking on the async SPI", result.is_ok() && back[..16] == out[..16], format_args!("({result:?})"));
        drop(spi);

        // Full duplex with MISO on PB00, open: it runs, whatever it reads.
        let mut config = Config::default();
        config.frequency = 8_000_000;
        let mut spi = Spi::new(p.SERCOM5.reborrow(), p.PB03.reborrow(), p.PB02.reborrow(), p.PB00.reborrow(), Irqs, config).unwrap();
        let result = spi.transfer(&mut back, &out).await;
        let ones = back.iter().fold(0, |n, &b| n + usize::from(b == 0xFF));
        t.check("full duplex, MISO on PB00 (async)", result.is_ok(), format_args!("{ones} of 256 bytes read 0xFF ({result:?})"));
    };
    match select(async_tests, ticker()).await {
        Either::First(()) | Either::Second(_) => {}
    }

    let failures = t.failures;
    let _ = if failures == 0 { writeln!(log, "spi: all passed") } else { writeln!(log, "spi: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
