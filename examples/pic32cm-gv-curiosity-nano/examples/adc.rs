//! `pic32c-hal`'s `adc` on the GV00's ADC (the SAM D20's), on its inputs
//! inside the chip:
//!
//! - AVDD from the 1.1 V bandgap read at the default full scale (half AVDD
//!   at half gain, so AVDD): 3.3 V on the board within 8 % (the bandgap's
//!   typical value is all the data sheet gives);
//! - VDDIO/4 against the internal 1.0 V reference at unity gain: VDD within
//!   5 %; and at the default full scale, a quarter of it;
//! - the same at 10 and 8 bits: on the 12-bit scale with the low 2 and 4
//!   bits zero, within a step of the 12-bit reading;
//! - the temperature sensor against 1.0 V, by the data sheet's typical
//!   figures (±10 °C): 5 to 50 °C on the bench;
//! - a read's time, short and long sample times, blocking and async (the
//!   async reads on `ADC`).
//!
//! Over the virtual COM port; the LED blinks slowly when all passed, fast
//! on a failure.

#![no_std]
#![no_main]
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;

use embassy_executor::Spawner;
use embassy_time::{Duration, Timer};
use panic_halt as _;
use pic32c_hal::adc::{self, Adc, Gain, Reference, Resolution, SampleTime, Temperature, Vddio, VrefInt};
use pic32c_hal::bind_interrupts;
use pic32c_hal::gpio::{Level, Output};
use pic32cm_gv_curiosity_nano::{Log, micros};

bind_interrupts!(struct Irqs {
    ADC => adc::InterruptHandler;
});

/// The board's VDD, set by its debugger (3.32 V measured).
const VDD_MV: u32 = 3300;

struct Tests<'a> {
    log: &'a mut Log,
    failures: u32,
}

impl Tests<'_> {
    fn check(&mut self, name: &str, good: bool, detail: core::fmt::Arguments<'_>) {
        let _ = writeln!(self.log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        self.failures += u32::from(!good);
    }
}

fn spread(n: u32, mut read: impl FnMut() -> u16) -> (u16, u32, u16) {
    let (mut least, mut most, mut sum) = (u16::MAX, 0, 0u32);
    for _ in 0..n {
        let v = read();
        least = least.min(v);
        most = most.max(v);
        sum += u32::from(v);
    }
    (least, sum / n, most)
}

/// The internal 1.0 V at unity gain: full scale 1,000 mV.
fn internal(resolution: Resolution) -> adc::Config {
    let mut config = adc::Config::default();
    config.reference = Reference::Internal1V0;
    config.gain = Gain::X1;
    config.resolution = resolution;
    config
}

#[expect(clippy::cast_possible_truncation, reason = "a 12-bit mean")]
const fn mean16(mean: u32) -> u16 {
    mean as u16
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let mut p = pic32cm_gv_curiosity_nano::init();
    let mut log = Log::init(p.SERCOM2, p.PA12, p.PA13);
    let mut led = Output::new(p.PA24, Level::Low);
    let _ = writeln!(log, "\npic32cm-gv-curiosity-nano adc");
    let mut t = Tests { log: &mut log, failures: 0 };

    // AVDD from the bandgap, at the default full scale (AVDD).
    {
        let start = micros();
        let mut adc = Adc::new_blocking(p.ADC.reborrow(), adc::Config::default()).unwrap();
        let us = micros() - start;
        let mut bandgap = adc.enable_vrefint();
        let (least, mean, most) = spread(64, || adc.blocking_read(&mut bandgap, SampleTime::LONG));
        let avdd = VrefInt::full_scale_mv(mean16(mean));
        t.check(
            "AVDD from the bandgap",
            most - least <= 16 && avdd.abs_diff(VDD_MV) <= VDD_MV * 8 / 100,
            format_args!("{avdd} mV: bandgap {least}..{most}, mean {mean} (set up in {us} us, CLK_ADC {} Hz)", adc.clock_hz()),
        );
        let mut vddio = adc.enable_vddio();
        let (_, mean, _) = spread(64, || adc.blocking_read(&mut vddio, SampleTime::LONG));
        t.check("VDDIO/4 at full scale AVDD", mean.abs_diff(1024) <= 30, format_args!("reads {mean} of 4096, a quarter is 1024"));
    }

    // VDD from VDDIO/4 against 1.0 V.
    let at_12 = {
        let mut adc = Adc::new_blocking(p.ADC.reborrow(), internal(Resolution::Bits12)).unwrap();
        let mut vddio = adc.enable_vddio();
        let (least, mean, most) = spread(64, || adc.blocking_read(&mut vddio, SampleTime::LONG));
        let vdd = Vddio::millivolts(mean16(mean), 1000);
        t.check("VDD", most - least <= 16 && vdd.abs_diff(VDD_MV) <= VDD_MV / 20, format_args!("{vdd} mV from VDDIO/4 against 1.0 V: {least}..{most}, mean {mean}"));
        mean
    };

    // Resolutions.
    for (resolution, shift) in [(Resolution::Bits10, 2), (Resolution::Bits8, 4)] {
        let mut adc = Adc::new_blocking(p.ADC.reborrow(), internal(resolution)).unwrap();
        let mut vddio = adc.enable_vddio();
        let mut low = 0u16;
        let (_, mean, _) = spread(64, || {
            let v = adc.blocking_read(&mut vddio, SampleTime::LONG);
            low |= v & ((1 << shift) - 1);
            v
        });
        let step = 1u32 << shift;
        t.check(
            "resolution",
            low == 0 && mean.abs_diff(at_12) <= step,
            format_args!("{} bits: VDDIO/4 mean {mean}, low {shift} bits {low:#x}, 12 bits' {at_12}", resolution.bits()),
        );
    }

    // Temperature, and read times, against 1.0 V.
    {
        let mut adc = Adc::new_blocking(p.ADC.reborrow(), internal(Resolution::Bits12)).unwrap();
        let mut temperature = adc.enable_temperature();
        let _ = adc.blocking_read(&mut temperature, SampleTime::LONG);
        let (least, mean, most) = spread(64, || adc.blocking_read(&mut temperature, SampleTime::LONG));
        let mv = mean * 1000 / 4096;
        let tenths = Temperature::typical_celsius(mv);
        t.check(
            "temperature",
            (50..=500).contains(&tenths),
            format_args!("{}.{} C (typical figures) from {mv} mV: {least}..{most}, mean {mean}", tenths / 10, (tenths % 10).abs()),
        );

        let mut vddio = adc.enable_vddio();
        let mut time_read = |sample: SampleTime| {
            let start = micros();
            for _ in 0..100 {
                let _ = adc.blocking_read(&mut vddio, sample);
            }
            micros() - start
        };
        let short = time_read(SampleTime::SHORT);
        let long = time_read(SampleTime::LONG);
        let _ = writeln!(t.log, "100 reads: {short} us with SHORT, {long} us with LONG (CLK_ADC {} Hz)", adc.clock_hz());
    }

    // Async.
    let mut adc = Adc::new(p.ADC.reborrow(), Irqs, internal(Resolution::Bits12)).unwrap();
    let mut vddio = adc.enable_vddio();
    let start = micros();
    let mut sum = 0u32;
    for _ in 0..64 {
        sum += u32::from(adc.read(&mut vddio, SampleTime::LONG).await);
    }
    let us = micros() - start;
    let mean = sum / 64;
    t.check("async", mean.abs_diff(at_12) <= 4, format_args!("VDDIO/4 mean {mean} over 64 reads in {us} us"));

    let failures = t.failures;
    let _ = if failures == 0 { writeln!(log, "adc: all passed") } else { writeln!(log, "adc: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
