//! `pic32c-hal`'s `rtc` on the GV00, from the board's 32.768 kHz crystal
//! (connected out of the box) through generator 4 at 1.024 kHz:
//!
//! - set up afresh at power-on, or found running;
//! - its seconds timed against the time driver's clock (OSC8M, the internal
//!   8 MHz oscillator) over 10 s, in ppm, within OSC8M's percent or so;
//! - the calendar through 29 February and a new year;
//! - an alarm 3 s ahead, timed;
//! - a system reset request: only a power-on reset resets the GV00's RTC,
//!   its generator and the crystal, so after it the driver must find the
//!   RTC running, the marker time set before kept (plus the seconds the
//!   reset took);
//! - then OSCULP32K as the source: set up afresh, its rate reported.
//!
//! Over the virtual COM port; the LED blinks slowly when all passed, fast
//! on a failure.

#![no_std]
#![no_main]
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;

use embassy_executor::Spawner;
use embassy_time::{Duration, Timer};
use panic_halt as _;
use pic32c_hal::bind_interrupts;
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::rtc::{self, DateTime, Rtc};
use pic32cm_gv_curiosity_nano::{Log, micros};

bind_interrupts!(struct Irqs {
    RTC => rtc::InterruptHandler;
});

/// A word of SRAM a system reset keeps: in `.uninit`, which start-up
/// leaves alone.
#[unsafe(link_section = ".uninit.STAGE")]
static mut STAGE: core::mem::MaybeUninit<u32> = core::mem::MaybeUninit::uninit();
/// At [`STAGE`] across the reset this program asks for.
const RESET_ASKED: u32 = 0x5254_4352;

fn stage() -> u32 {
    // SAFETY: only `main` touches it; any bit pattern is a u32.
    unsafe { core::ptr::addr_of!(STAGE).cast::<u32>().read_volatile() }
}

fn set_stage(value: u32) {
    // SAFETY: as above.
    unsafe { core::ptr::addr_of_mut!(STAGE).cast::<u32>().write_volatile(value) }
}

/// The time set before the reset.
const MARKER: DateTime = match DateTime::new(2030, 6, 15, 12, 0, 0) {
    Ok(t) => t,
    Err(_) => panic!("a valid marker"),
};

struct Tests<'a> {
    log: &'a mut Log,
    failures: u32,
}

impl Tests<'_> {
    fn check(&mut self, name: &str, good: bool, detail: core::fmt::Arguments<'_>) {
        let _ = writeln!(self.log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        self.failures += u32::from(!good);
    }
}

/// Waits for the seconds to change, by polling: the microsecond it did.
fn next_second(rtc: &Rtc<'_>) -> u64 {
    let start = rtc.now();
    while rtc.now() == start {}
    micros()
}

/// The RTC's rate against the time driver's over `seconds` s, in ppm.
fn rate(rtc: &Rtc<'_>, seconds: u32) -> (u64, i64) {
    let first = next_second(rtc);
    let mut last = first;
    for _ in 0..seconds {
        last = next_second(rtc);
    }
    let elapsed = last - first;
    let nominal = u64::from(seconds) * 1_000_000;
    #[expect(clippy::cast_possible_wrap, reason = "seconds in microseconds")]
    let ppm = (elapsed as i64 - nominal as i64) * 1_000_000 / nominal as i64;
    (elapsed, ppm)
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32cm_gv_curiosity_nano::init();
    let mut log = Log::init(p.SERCOM2, p.PA12, p.PA13);
    let mut led = Output::new(p.PA24, Level::Low);
    let _ = writeln!(log, "\npic32cm-gv-curiosity-nano rtc");
    let after_reset = stage() == RESET_ASKED;
    set_stage(0);
    let mut t = Tests { log: &mut log, failures: 0 };
    let mut rtc_peripheral = p.RTC;
    let start = micros();
    let made = Rtc::new(rtc_peripheral.reborrow(), Irqs, rtc::Config::default());
    let us = micros() - start;
    let Ok(mut rtc) = made else {
        t.check("RTC from the crystal", false, format_args!("not set up ({:?})", made.err()));
        loop {
            Timer::after(Duration::from_secs(1)).await;
        }
    };
    let now = rtc.now();

    if after_reset {
        // The reset asked for: the RTC kept, the marker time and the
        // seconds since.
        let kept = rtc.was_running() && (MARKER.to_unix() + 1..=MARKER.to_unix() + 5).contains(&now.to_unix());
        t.check(
            "after a system reset",
            kept,
            format_args!("RTC {} in {us} us at {now} (the marker was {MARKER}, 1.5 s before the reset)", if rtc.was_running() { "found running" } else { "set up afresh" }),
        );

        // Then OSCULP32K: a new source, so set up afresh.
        let mut config = rtc::Config::default();
        config.source = rtc::Source::UltraLowPower;
        match Rtc::new(rtc_peripheral.reborrow(), Irqs, config) {
            Ok(ulp) => {
                let (elapsed, ppm) = rate(&ulp, 5);
                t.check(
                    "OSCULP32K",
                    !ulp.was_running() && ppm.abs() < 200_000,
                    format_args!("set up {}; 5 s in {elapsed} us: {ppm} ppm against OSC8M", if ulp.was_running() { "NOT afresh" } else { "afresh" }),
                );
            }
            Err(e) => t.check("OSCULP32K", false, format_args!("{e:?}")),
        }
    } else {
        let _ = writeln!(t.log, "RTC {} in {us} us, at {now}", if rtc.was_running() { "found running" } else { "set up afresh" });

        // The seconds against OSC8M over 10 s.
        let (elapsed, ppm) = rate(&rtc, 10);
        t.check("rate", ppm.abs() < 50_000, format_args!("10 s in {elapsed} us: {ppm} ppm against OSC8M"));

        // The calendar through 29 February and a new year.
        for (set, expected) in [
            (DateTime::new(2024, 2, 28, 23, 59, 58), DateTime::new(2024, 2, 29, 0, 0, 0)),
            (DateTime::new(2025, 12, 31, 23, 59, 58), DateTime::new(2026, 1, 1, 0, 0, 0)),
        ] {
            let (set, expected) = (set.unwrap(), expected.unwrap());
            rtc.set(set);
            let back = rtc.now();
            Timer::after(Duration::from_millis(2500)).await;
            let later = rtc.now();
            t.check("calendar", back == set && later >= expected && later.to_unix() <= expected.to_unix() + 1, format_args!("set {set}, read {back}, 2.5 s later {later}"));
        }

        // An alarm 3 s ahead.
        let at = DateTime::from_unix(rtc.now().to_unix() + 3).unwrap();
        let start = micros();
        rtc.wait_until(at).await;
        let us = micros() - start;
        t.check("alarm", (2_000_000..=3_100_000).contains(&us) && rtc.now() >= at, format_args!("{at} came after {us} us"));

        // The reset: the marker, then the chip reset by software.
        if t.failures == 0 {
            rtc.set(MARKER);
            let _ = writeln!(t.log, "marker {MARKER} set; resetting");
            Timer::after(Duration::from_millis(1500)).await;
            set_stage(RESET_ASKED);
            cortex_m::peripheral::SCB::sys_reset();
        }
    }

    let failures = t.failures;
    let _ = if failures == 0 { writeln!(log, "rtc: all passed") } else { writeln!(log, "rtc: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
