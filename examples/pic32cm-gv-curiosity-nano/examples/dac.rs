//! `pic32c-hal`'s `dac` on the GV00, read back by its own ADC, with nothing
//! wired: the DAC drives VOUT (PA02, also the ADC's AIN0) and the inside
//! of the chip, so each code is read both ways.
//!
//! - against AVDD on both (the DAC's AVDD reference; the ADC's default full
//!   scale, AVDD): codes 0 to 1023 by 32, each read inside the chip and on
//!   PA02, should read four counts a code; a straight-line fit of each over
//!   codes 32 to 992 (clear of the ends), with its worst deviation;
//! - against the internal 1.0 V on both: the same, a few codes;
//! - settling: a full-scale step read at once and 10 µs later;
//! - the internal output alone (`Dac::new_internal`): that path feeds only
//!   the comparators, so neither the ADC's DAC input nor the pin follows the
//!   DAC; reported, not checked.
//!
//! Over the virtual COM port; the LED blinks slowly when all passed, fast
//! on a failure.

#![no_std]
#![no_main]
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;

use embassy_executor::Spawner;
use embassy_time::{Duration, Timer, block_for};
use panic_halt as _;
use pic32c_hal::adc::{self, Adc, Gain, SampleTime};
use pic32c_hal::dac::{self, Dac};
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::mode::Blocking;
use pic32cm_gv_curiosity_nano::Log;

struct Tests<'a> {
    log: &'a mut Log,
    failures: u32,
}

impl Tests<'_> {
    fn check(&mut self, name: &str, good: bool, detail: core::fmt::Arguments<'_>) {
        let _ = writeln!(self.log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        self.failures += u32::from(!good);
    }
}

/// A least-squares line through `points`: (offset, gain in thousandths of
/// a count per code, worst deviation in counts).
fn fit(points: &[(i64, i64)]) -> (i64, i64, i64) {
    #[expect(clippy::cast_possible_wrap, reason = "a few dozen points")]
    let n = points.len() as i64;
    let (sx, sy) = points.iter().fold((0, 0), |(sx, sy), &(x, y)| (sx + x, sy + y));
    let (sxx, sxy) = points.iter().fold((0, 0), |(a, b), &(x, y)| (a + x * x, b + x * y));
    let gain_milli = (n * sxy - sx * sy) * 1000 / (n * sxx - sx * sx);
    let offset = (sy * 1000 - gain_milli * sx) / (n * 1000);
    let worst = points.iter().map(|&(x, y)| y - (offset + gain_milli * x / 1000)).max_by_key(|d| d.abs()).unwrap_or(0);
    (offset, gain_milli, worst)
}

/// Mean of 8 reads.
fn mean(adc: &mut Adc<'_, Blocking>, channel: &mut impl adc::AdcChannel) -> i64 {
    let sum: u32 = (0..8).map(|_| u32::from(adc.blocking_read(channel, SampleTime::LONG))).sum();
    i64::from(sum / 8)
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let mut p = pic32cm_gv_curiosity_nano::init();
    let mut log = Log::init(p.SERCOM2, p.PA12, p.PA13);
    let mut led = Output::new(p.PA24, Level::Low);
    let _ = writeln!(log, "\npic32cm-gv-curiosity-nano dac");
    let mut t = Tests { log: &mut log, failures: 0 };

    // Against AVDD: the sweep.
    {
        let mut dac = Dac::new(p.DAC.reborrow(), p.PA02.reborrow(), dac::Config::default()).unwrap();
        let mut adc = Adc::new_blocking(p.ADC.reborrow(), adc::Config::default()).unwrap();
        let mut inside = adc.enable_dac_output();
        // SAFETY: PA02 is the DAC's VOUT and the ADC's AIN0 on the same
        // function, B; the ADC only reads it, setting that function again.
        let mut pa02 = unsafe { pic32c_hal::peripherals::PA02::steal() };
        let mut inside_points = [(0i64, 0i64); 31];
        let mut pin_points = [(0i64, 0i64); 31];
        for (i, code) in (32..=992u16).step_by(32).enumerate() {
            dac.set(code);
            block_for(Duration::from_micros(20));
            inside_points[i] = (i64::from(code), mean(&mut adc, &mut inside));
            pin_points[i] = (i64::from(code), mean(&mut adc, &mut pa02));
        }
        for (name, points) in [("inside", &inside_points), ("PA02", &pin_points)] {
            let (offset, gain, worst) = fit(points);
            t.check(
                "sweep against AVDD",
                (3800..=4200).contains(&gain) && offset.abs() <= 60 && worst.abs() <= 24,
                format_args!("{name}: {gain} thousandths of a count per code (4000 ideal), offset {offset}, worst deviation {worst} counts over codes 32-992"),
            );
        }
        let (code_0, code_max) = {
            dac.set(0);
            block_for(Duration::from_micros(20));
            let low = mean(&mut adc, &mut inside);
            dac.set(dac::MAX_CODE);
            block_for(Duration::from_micros(20));
            (low, mean(&mut adc, &mut inside))
        };
        let _ = writeln!(t.log, "ends: code 0 reads {code_0}, code 1023 reads {code_max} (of 4096)");

        // Settling: a full-scale step, read at once and 10 µs later.
        dac.set(0);
        block_for(Duration::from_micros(50));
        dac.set(dac::MAX_CODE);
        let at_once = adc.blocking_read(&mut inside, SampleTime::SHORT);
        block_for(Duration::from_micros(10));
        let later = adc.blocking_read(&mut inside, SampleTime::SHORT);
        t.check("settling", i64::from(later).abs_diff(code_max) <= 30, format_args!("0 to 1023: {at_once} at once, {later} 10 us later (settled {code_max})"));
    }

    // Against the internal 1.0 V on both.
    {
        let mut config = dac::Config::default();
        config.reference = dac::Reference::Internal1V0;
        let mut dac = Dac::new(p.DAC.reborrow(), p.PA02.reborrow(), config).unwrap();
        let mut adc_config = adc::Config::default();
        adc_config.reference = adc::Reference::Internal1V0;
        adc_config.gain = Gain::X1;
        let mut adc = Adc::new_blocking(p.ADC.reborrow(), adc_config).unwrap();
        let mut inside = adc.enable_dac_output();
        let mut points = [(0i64, 0i64); 7];
        for (i, code) in (128..=896u16).step_by(128).enumerate() {
            dac.set(code);
            block_for(Duration::from_micros(20));
            points[i] = (i64::from(code), mean(&mut adc, &mut inside));
        }
        let (offset, gain, worst) = fit(&points);
        t.check(
            "against 1.0 V",
            (3800..=4200).contains(&gain) && offset.abs() <= 60 && worst.abs() <= 24,
            format_args!("{gain} thousandths of a count per code, offset {offset}, worst {worst} counts"),
        );
    }

    // The internal output alone.
    {
        let mut dac = Dac::new_internal(p.DAC.reborrow(), dac::Config::default()).unwrap();
        let mut adc = Adc::new_blocking(p.ADC.reborrow(), adc::Config::default()).unwrap();
        let mut inside = adc.enable_dac_output();
        dac.set(512);
        block_for(Duration::from_micros(20));
        let reads = mean(&mut adc, &mut inside);
        let pin = mean(&mut adc, &mut p.PA02.reborrow());
        let _ = writeln!(t.log, "internal only (the comparators' path): code 512 reads {reads} at the ADC's DAC input, PA02 {pin} (not driven)");
    }

    let failures = t.failures;
    let _ = if failures == 0 { writeln!(log, "dac: all passed") } else { writeln!(log, "dac: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
