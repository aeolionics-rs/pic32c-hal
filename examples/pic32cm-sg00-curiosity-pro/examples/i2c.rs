//! `pic32c-hal`'s `i2c` on the board's I2C bus (SERCOM1: SDA PD01, SCL PD00,
//! I/O set 3, shared by EXT1, EXT2, the Arduino header and the mikroBUS
//! socket), which has no device of its own: wire one to EXT1 (11 SDA, 12
//! SCL, 19 GND, 20 3.3 V). Written against an `SHT4x` and a BMP280 or
//! BME280, such as on one sensor module carrying both, with the bus's
//! pull-ups.
//!
//! Blocking: a scan, a NACK from an empty address, the Bosch part's chip ID,
//! and its calibration read whole and as two reads in one transaction. On
//! interrupts: the same reads at 100 kHz, 400 kHz and 1 MHz, timed. Then,
//! at 400 kHz, each sensor the scan found that the CK board's
//! `common/sensors.rs` knows: the `SHT4x`'s CRC-checked serial number, the
//! Bosch part's chip ID, and a measurement from each within reason. Over
//! the virtual COM port; LED0 blinks slowly when all passed, fast on a
//! failure.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;

use embassy_executor::Spawner;
use embassy_time::{Duration, Timer};
use panic_halt as _;
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::i2c::{self, Config, Error, I2c};
use pic32c_hal::mode::Async;
use pic32c_hal::{Peri, bind_interrupts, peripherals};
use pic32cm_sg00_curiosity_pro::{Log, micros};
#[path = "../../pic32ck-curiosity-ultra/examples/common/sensors.rs"]
#[allow(dead_code, reason = "shared by several examples; each uses some of it")]
mod sensors;

use sensors::{BMX280, Bmx280, Centi, Reading, SHT4X};

pic32cm_sg00_curiosity_pro::boot!();

bind_interrupts!(struct Irqs {
    SERCOM1_0 => i2c::InterruptHandler<peripherals::SERCOM1>;
    SERCOM1_1 => i2c::InterruptHandler<peripherals::SERCOM1>;
});

/// The Bosch parts' registers: chip ID, and the start of the calibration.
const CHIP_ID: u8 = 0xD0;
const CALIBRATION: u8 = 0x88;

struct Tests<'a> {
    log: &'a mut Log,
    failures: u32,
}

impl Tests<'_> {
    fn check(&mut self, name: &str, good: bool, detail: core::fmt::Arguments<'_>) {
        let _ = writeln!(self.log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        self.failures += u32::from(!good);
    }
}

async fn tests(sercom: &mut Peri<'static, peripherals::SERCOM1>, sda: &mut Peri<'static, peripherals::PD01>, scl: &mut Peri<'static, peripherals::PD00>, t: &mut Tests<'_>) {
    let mut bus = I2c::new_blocking(sercom.reborrow(), sda.reborrow(), scl.reborrow(), Config::default()).unwrap();
    let _ = writeln!(t.log, "SCL {} Hz", bus.frequency());

    // A scan.
    let mut found = [0u8; 16];
    let mut n = 0;
    for address in 0x08..0x78u8 {
        match bus.blocking_write(address, &[]) {
            Ok(()) => {
                if n < found.len() {
                    found[n] = address;
                    n += 1;
                }
            }
            Err(Error::AddressNack) => {}
            Err(e) => {
                t.check("scan", false, format_args!("{address:#04x}: {e:?}"));
                return;
            }
        }
    }
    let found = &found[..n];
    let _ = writeln!(t.log, "found {found:02x?}");
    let Some(&bosch) = found.iter().find(|a| BMX280.contains(a)) else {
        t.check("a BMP280 or BME280", false, format_args!("nothing at 0x76 or 0x77"));
        return;
    };
    t.check("scan", true, format_args!("Bosch part at {bosch:#04x}"));

    // An empty address.
    let empty = (0x08..0x78u8).find(|a| !found.contains(a)).unwrap_or(0x08);
    let nack = bus.blocking_write(empty, &[0]);
    t.check("an empty address", nack == Err(Error::AddressNack), format_args!("{empty:#04x}: {nack:?}"));

    // The chip ID, and the calibration whole and in two reads.
    let mut id = [0u8];
    let result = bus.blocking_write_read(bosch, &[CHIP_ID], &mut id);
    t.check("chip ID", result.is_ok() && (id[0] == 0x58 || id[0] == 0x60), format_args!("{:#04x} ({result:?})", id[0]));
    let mut calibration = [0u8; 24];
    let result = bus.blocking_write_read(bosch, &[CALIBRATION], &mut calibration);
    t.check("calibration", result.is_ok() && calibration != [0; 24] && calibration != [0xFF; 24], format_args!("{calibration:02x?} ({result:?})"));
    let mut first = [0u8; 3];
    let mut rest = [0u8; 3];
    let result = bus.blocking_transaction(
        bosch,
        &mut [embedded_hal::i2c::Operation::Write(&[CALIBRATION]), embedded_hal::i2c::Operation::Read(&mut first), embedded_hal::i2c::Operation::Read(&mut rest)],
    );
    t.check("two reads in a row", result.is_ok() && first == calibration[..3] && rest == calibration[3..6], format_args!("({result:?})"));
    drop(bus);

    // On interrupts, at three rates: one bus, moved between them by
    // `set_config`.
    let mut bus = I2c::new(sercom.reborrow(), sda.reborrow(), scl.reborrow(), Irqs, Config::default()).unwrap();
    for frequency in [100_000, 400_000, 1_000_000] {
        let mut config = Config::default();
        config.frequency = frequency;
        bus.set_config(&config).unwrap();
        let start = micros();
        let mut again = [0u8; 24];
        let a = bus.write_read(bosch, &[CALIBRATION], &mut again).await;
        let mut id_again = [0u8];
        let b = bus.write_read(bosch, &[CHIP_ID], &mut id_again).await;
        let us = micros() - start;
        let nack = bus.write(empty, &[]).await;
        t.check(
            "async",
            a.is_ok() && b.is_ok() && again == calibration && id_again == id && nack == Err(Error::AddressNack),
            format_args!("at {} Hz: 25 bytes read in {us} us; empty address {nack:?}", bus.frequency()),
        );
    }

    sensors_found(&mut bus, found, t).await;
}

/// Tests each sensor in `found` that `sensors` knows, at 400 kHz.
async fn sensors_found(bus: &mut I2c<'_, Async>, found: &[u8], t: &mut Tests<'_>) {
    let mut config = Config::default();
    config.frequency = 400_000;
    bus.set_config(&config).unwrap();
    let mut tested = 0;
    for &address in found {
        if SHT4X.contains(&address) {
            tested += 1;
            let serial = sensors::sht4x_serial(bus, address).await;
            t.check("SHT4x serial", serial.is_ok(), format_args!("at {address:#04x}: {serial:08x?}"));
            let reading = sensors::sht4x_measure(bus, address).await;
            check_reading(t, "SHT4x", address, reading);
        } else if BMX280.contains(&address) {
            let Some(id) = sensors::bmx280_id(bus, address).await else {
                let _ = writeln!(t.log, "{address:#04x}: not a BMP280 or BME280 (chip ID), not tested");
                continue;
            };
            tested += 1;
            let name = if id == 0x60 { "BME280" } else { "BMP280" };
            let _ = writeln!(t.log, "{name} at {address:#04x}: chip ID {id:#04x}");
            let reading = match Bmx280::new(bus, address, id).await {
                Ok(part) => part.measure(bus).await,
                Err(e) => Err(e),
            };
            check_reading(t, name, address, reading);
        } else {
            let _ = writeln!(t.log, "{address:#04x}: not a known sensor, not tested");
        }
    }
    t.check("sensors tested", tested >= 2, format_args!("{tested}"));
}

/// A sensor's reading within reason: -10 to 60 C, 0 to 100 %RH, 300 to
/// 1100 hPa.
fn check_reading(t: &mut Tests<'_>, name: &str, address: u8, reading: Result<Reading, &'static str>) {
    match reading {
        Ok(r) => {
            let good = (-1000..=6000).contains(&r.centidegrees) && r.centi_rh.is_none_or(|rh| (0..=10_000).contains(&rh)) && r.pascals.is_none_or(|pa| (30_000..=110_000).contains(&pa));
            let _ = write!(t.log, "{name} at {address:#04x}: {} C", Centi(r.centidegrees));
            if let Some(rh) = r.centi_rh {
                let _ = write!(t.log, ", {} %RH", Centi(rh));
            }
            if let Some(pa) = r.pascals {
                let _ = write!(t.log, ", {} hPa", Centi(pa));
            }
            let _ = writeln!(t.log);
            t.check(name, good, format_args!("measurement within reason"));
        }
        Err(e) => t.check(name, false, format_args!("at {address:#04x}: {e}")),
    }
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32cm_sg00_curiosity_pro::init();
    let mut log = Log::init(p.SERCOM4, p.PD19, p.PD20);
    let mut led = Output::new(p.PA20, Level::High);
    let _ = writeln!(log, "\npic32cm-sg00-curiosity-pro i2c");
    let (mut sercom, mut sda, mut scl) = (p.SERCOM1, p.PD01, p.PD00);

    let mut t = Tests { log: &mut log, failures: 0 };
    tests(&mut sercom, &mut sda, &mut scl, &mut t).await;
    let failures = t.failures;
    let _ = if failures == 0 { writeln!(log, "i2c: all passed") } else { writeln!(log, "i2c: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
