//! Echoes the virtual COM port (SERCOM4, PD19/PD20, FIFO on) by DMA: a
//! `Uart` with DMA channels 0 (receive) and 1 (transmit) reads 256-byte
//! blocks, each a single DMA transfer paced by the SERCOM's receive request,
//! and writes each back as one transfer paced by its transmit request. Send
//! it a block at a time, each after the last one's echo: while it writes a
//! block it reads nothing, so a stream overruns the SERCOM's 16-byte FIFO
//! (`uart_ring` takes a stream): `tools/host/uart_dma_test.py`
//! does. LED0 toggles with each block. 115,200
//! baud unless `UART_BAUD` says otherwise when building.

#![no_std]
#![no_main]
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use embassy_executor::Spawner;
use panic_halt as _;
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::uart::{self, Uart};
use pic32c_hal::{bind_interrupts, peripherals};

pic32cm_sg00_curiosity_pro::boot!();

bind_interrupts!(struct Irqs {
    SERCOM4_0 => uart::InterruptHandler<peripherals::SERCOM4>;
    SERCOM4_1 => uart::InterruptHandler<peripherals::SERCOM4>;
    SERCOM4_2 => uart::InterruptHandler<peripherals::SERCOM4>;
    SERCOM4_6 => uart::InterruptHandler<peripherals::SERCOM4>;
});

const BLOCK: usize = 256;

/// `UART_BAUD` when building, else 115,200.
const BAUD: u32 = match option_env!("UART_BAUD") {
    Some(value) => parse(value.as_bytes()),
    None => 115_200,
};

const fn parse(digits: &[u8]) -> u32 {
    let mut value = 0;
    let mut i = 0;
    while i < digits.len() {
        assert!(digits[i].is_ascii_digit(), "UART_BAUD is a number");
        value = value * 10 + (digits[i] - b'0') as u32;
        i += 1;
    }
    value
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32cm_sg00_curiosity_pro::init();
    let mut led = Output::new(p.PA20, Level::High);
    let mut config = uart::Config::default();
    config.baudrate = BAUD;
    let mut uart = Uart::new(p.SERCOM4, p.PD19, p.PD20, Irqs, p.DMA_CH1, p.DMA_CH0, config).unwrap();
    let _ = uart.write(b"\r\npic32cm-sg00-curiosity-pro uart_dma\r\n").await;
    let mut block = [0u8; BLOCK];
    loop {
        // A receive error comes after the block, which is still echoed.
        let _ = uart.read(&mut block).await;
        let _ = uart.write(&block).await;
        led.toggle();
    }
}
