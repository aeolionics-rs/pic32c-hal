//! `pic32c-hal`'s `adc` on the SG00 (the CK's ADC IP, at another address,
//! with its pins AIN0-11 and the bandgap on input 14):
//!
//! - the factory's ADC trim (FCCFG65, into ADCCTRL);
//! - the 1.2 V bandgap, 64 reads: their spread, and AVDD worked out from the
//!   bandgap's nominal 1.2 V (3.3 V on the board, within 5 %; the SG00 has
//!   no factory reading of it);
//! - the same against the board's MCP1501 (3.3 V, 0.1 %, on VREFH, PA09):
//!   the bandgap in millivolts, 1.2 V within 5 %;
//! - the bandgap at 10 and 8 bits: on the 12-bit scale with the low 2 and
//!   4 bits zero, within a step of the 12-bit reading;
//! - a read's time, short and long sample times, blocking and async (the
//!   async reads on `ADC_REQ1`);
//! - the potentiometer (PB06, AIN11) read, then its range while it's turned
//!   for 10 s, if anyone does (not a failure).
//!
//! Over the virtual COM port; LED0 blinks slowly when all passed, fast on a
//! failure.

#![no_std]
#![no_main]
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;

use embassy_executor::Spawner;
use embassy_time::{Duration, Instant, Timer};
use panic_halt as _;
use pic32c_hal::adc::{self, Adc, AdcChannel, Resolution, SampleTime};
use pic32c_hal::bind_interrupts;
use pic32c_hal::gpio::{Level, Output};
use pic32cm_sg00_curiosity_pro::{Log, micros};

pic32cm_sg00_curiosity_pro::boot!();

bind_interrupts!(struct Irqs {
    ADC_REQ1 => adc::InterruptHandler;
});

/// The bandgap's nominal voltage, and the board's reference on VREFH.
const BANDGAP_MV: u32 = 1200;
const MCP1501_MV: u32 = 3300;

struct Tests<'a> {
    log: &'a mut Log,
    failures: u32,
}

impl Tests<'_> {
    fn check(&mut self, name: &str, good: bool, detail: core::fmt::Arguments<'_>) {
        let _ = writeln!(self.log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        self.failures += u32::from(!good);
    }
}

fn spread(n: u32, mut read: impl FnMut() -> u16) -> (u16, u32, u16) {
    let (mut least, mut most, mut sum) = (u16::MAX, 0, 0u32);
    for _ in 0..n {
        let v = read();
        least = least.min(v);
        most = most.max(v);
        sum += u32::from(v);
    }
    (least, sum / n, most)
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let mut p = pic32cm_sg00_curiosity_pro::init();
    let mut log = Log::init(p.SERCOM4, p.PD19, p.PD20);
    let mut led = Output::new(p.PA20, Level::High);
    let _ = writeln!(log, "\npic32cm-sg00-curiosity-pro adc");
    // SAFETY: the CAL OTP's FCCFG65, read only.
    let fccfg65 = unsafe { core::ptr::read_volatile(0x0A00_7184 as *const u32) };
    let _ = writeln!(log, "FCCFG65 (ADCCTRL trim) {fccfg65:#010x}");
    let mut t = Tests { log: &mut log, failures: 0 };

    let start = micros();
    let mut adc = match Adc::new_blocking(p.ADC.reborrow(), adc::Config::default()) {
        Ok(adc) => adc,
        Err(e) => {
            t.check("setup", false, format_args!("{e:?}"));
            loop {
                Timer::after(Duration::from_secs(1)).await;
            }
        }
    };
    let us = micros() - start;
    let _ = writeln!(t.log, "set up in {us} us");

    // The bandgap against AVDD, and AVDD from it.
    let mut vref = adc.enable_vrefint();
    let (least, bandgap, most) = spread(64, || adc.blocking_read(&mut vref, SampleTime::LONG));
    let avdd = BANDGAP_MV * 4096 / bandgap.max(1);
    t.check(
        "bandgap",
        most - least <= 12 && (3135..=3465).contains(&avdd),
        format_args!("{least}..{most}, mean {bandgap}: AVDD {avdd} mV from the nominal {BANDGAP_MV} mV"),
    );

    let mut time_read = |sample: SampleTime| {
        let start = micros();
        for _ in 0..100 {
            let _ = adc.blocking_read(&mut vref, sample);
        }
        micros() - start
    };
    let short = time_read(SampleTime::SHORT);
    let long = time_read(SampleTime::LONG);
    let _ = writeln!(t.log, "100 reads: {short} us with SHORT, {long} us with LONG");

    // The potentiometer.
    let mut pot = p.PB06.reborrow().degrade_adc();
    let (least, mean, most) = spread(16, || adc.blocking_read(&mut pot, SampleTime::SHORT));
    let _ = writeln!(t.log, "potentiometer AIN{}: {least}..{most}, mean {mean}", pot.channel());
    drop(adc);

    // Resolutions.
    for (resolution, shift) in [(Resolution::Bits10, 2), (Resolution::Bits8, 4)] {
        let mut config = adc::Config::default();
        config.resolution = resolution;
        let mut adc = Adc::new_blocking(p.ADC.reborrow(), config).unwrap();
        let mut vref = adc.enable_vrefint();
        let mut low = 0u16;
        let (_, mean, _) = spread(64, || {
            let v = adc.blocking_read(&mut vref, SampleTime::LONG);
            low |= v & ((1 << shift) - 1);
            v
        });
        let step = 1u32 << shift;
        t.check(
            "resolution",
            low == 0 && mean.abs_diff(bandgap) <= step,
            format_args!("{} bits: bandgap mean {mean}, low {shift} bits {low:#x}, 12 bits' {bandgap}", resolution.bits()),
        );
    }

    // Against the MCP1501 on VREFH.
    {
        pic32c_hal::gpio::set_as_function(p.PA09.reborrow(), pic32c_hal::gpio::Function::B);
        let mut config = adc::Config::default();
        config.reference = adc::Reference::External;
        let mut adc = Adc::new_blocking(p.ADC.reborrow(), config).unwrap();
        let mut vref = adc.enable_vrefint();
        let (_, counts, _) = spread(256, || adc.blocking_read(&mut vref, SampleTime::LONG));
        let mv = counts * MCP1501_MV / 4096;
        t.check("bandgap against the MCP1501", (1140..=1260).contains(&mv), format_args!("{counts} counts: {mv} mV"));
    }

    // Async.
    let mut adc = Adc::new(p.ADC.reborrow(), Irqs, adc::Config::default()).unwrap();
    let mut vref = adc.enable_vrefint();
    let start = micros();
    let mut sum = 0u32;
    for _ in 0..64 {
        sum += u32::from(adc.read(&mut vref, SampleTime::LONG).await);
    }
    let us = micros() - start;
    let mean = sum / 64;
    t.check("async", mean.abs_diff(bandgap) <= 4, format_args!("bandgap mean {mean} over 64 reads in {us} us"));

    // The potentiometer turned, if anyone's there.
    let _ = writeln!(t.log, "turn the potentiometer end to end within 10 s");
    let mut pot = p.PB06.reborrow().degrade_adc();
    let (mut least, mut most) = (u16::MAX, 0);
    let until = Instant::now() + Duration::from_secs(10);
    while Instant::now() < until {
        let v = adc.read(&mut pot, SampleTime::SHORT).await;
        least = least.min(v);
        most = most.max(v);
        Timer::after(Duration::from_millis(10)).await;
    }
    let turned = most - least > 3000;
    let _ = writeln!(t.log, "potentiometer: {least}..{most}{}", if turned { ", turned end to end" } else { " (not turned end to end; not a failure)" });

    let failures = t.failures;
    let _ = if failures == 0 { writeln!(log, "adc: all passed") } else { writeln!(log, "adc: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
