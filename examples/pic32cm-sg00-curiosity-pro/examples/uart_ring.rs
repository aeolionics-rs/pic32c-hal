//! `pic32c-hal`'s `RingBufferedUartRx` on the virtual COM port (SERCOM4,
//! PD19/PD20, FIFO on): the receive DMA channel fills a 2 KiB ring
//! continuously, its two halves linked to each other, and the transmit
//! channel writes the echo. The host drives it
//! (`tools/host/uart_ring_test.py`):
//!
//! 1. Overrun: it waits for a `G`, says `pause`, and reads nothing for
//!    500 ms, in which the host sends 4 KiB; the first read must say
//!    `Overrun`, and the next bytes sent must come through. It says
//!    `overrun: ok` or `overrun: FAILED`.
//! 2. Echo: every byte read goes back, in whatever chunks the ring gives,
//!    for the host to check: in order, through many laps of the ring. An
//!    echo at the line rate can only fall behind (each chunk waits for the
//!    one before to go out, and the two ends' baud rates differ a little),
//!    so the ring must hold the backlog: on the bench 100 KB built more
//!    than 256 bytes of it, less than 2 KiB.
//!
//! 115,200 baud unless `UART_BAUD` says otherwise when building. LED0
//! toggles with each chunk echoed.

#![no_std]
#![no_main]
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use embassy_executor::Spawner;
use embassy_futures::select::{Either, select};
use embassy_time::{Duration, Timer};
use panic_halt as _;
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::uart::{self, RingBufferedUartRx, Uart};
use pic32c_hal::{bind_interrupts, peripherals};
use static_cell::ConstStaticCell;

pic32cm_sg00_curiosity_pro::boot!();

bind_interrupts!(struct Irqs {
    SERCOM4_0 => uart::InterruptHandler<peripherals::SERCOM4>;
    SERCOM4_1 => uart::InterruptHandler<peripherals::SERCOM4>;
    SERCOM4_2 => uart::InterruptHandler<peripherals::SERCOM4>;
    SERCOM4_6 => uart::InterruptHandler<peripherals::SERCOM4>;
});

const RING: usize = 2048;

static RING_BUFFER: ConstStaticCell<[u8; RING]> = ConstStaticCell::new([0; RING]);

/// `UART_BAUD` when building, else 115,200.
const BAUD: u32 = match option_env!("UART_BAUD") {
    Some(value) => parse(value.as_bytes()),
    None => 115_200,
};

const fn parse(digits: &[u8]) -> u32 {
    let mut value = 0;
    let mut i = 0;
    while i < digits.len() {
        assert!(digits[i].is_ascii_digit(), "UART_BAUD is a number");
        value = value * 10 + (digits[i] - b'0') as u32;
        i += 1;
    }
    value
}

/// Reads whatever comes until 50 ms pass with nothing.
async fn drain(rx: &mut RingBufferedUartRx<'_>) {
    let mut scratch = [0u8; 64];
    while matches!(select(rx.read(&mut scratch), Timer::after(Duration::from_millis(50))).await, Either::First(_)) {}
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32cm_sg00_curiosity_pro::init();
    let mut led = Output::new(p.PA20, Level::High);
    let mut config = uart::Config::default();
    config.baudrate = BAUD;
    let uart = Uart::new(p.SERCOM4, p.PD19, p.PD20, Irqs, p.DMA_CH1, p.DMA_CH0, config).unwrap();
    let (mut tx, rx) = uart.split();
    let mut rx = rx.into_ring_buffered(RING_BUFFER.take());
    let _ = tx.write(b"\r\npic32cm-sg00-curiosity-pro uart_ring: send G\r\n").await;

    // Overrun.
    let mut chunk = [0u8; 512];
    loop {
        if let Ok(n) = rx.read(&mut chunk).await
            && chunk[..n].contains(&b'G')
        {
            break;
        }
    }
    let _ = tx.write(b"pause\r\n").await;
    Timer::after(Duration::from_millis(500)).await;
    let first = rx.read(&mut chunk).await;
    let overran = first == Err(uart::Error::Overrun);
    drain(&mut rx).await;
    let _ = tx.write(if overran { b"overrun: ok\r\n" } else { b"overrun: FAILED\r\n" }).await;

    // Echo.
    loop {
        if let Ok(n) = rx.read(&mut chunk).await {
            let _ = tx.write(&chunk[..n]).await;
            led.toggle();
        }
    }
}
