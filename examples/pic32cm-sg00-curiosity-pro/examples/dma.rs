//! `pic32c-hal`'s `dma` on the SG00's DMAC: copies of bytes, halfwords and
//! words of awkward lengths and alignments from SRAM and from flash,
//! checked and timed against the CPU's own copy; a ticker task counting
//! meanwhile, to show the executor runs through a transfer; a copy dropped
//! part way, after which the channel must work again; all eight channels at
//! once (4 to 7 share a vector); a read waiting for its first request, its
//! bytes still to move all of them; and a message written to the VCOM by
//! DMA, SERCOM4 pacing it with its transmit request. Over the virtual COM
//! port; LED0 blinks slowly when all passed, fast on a failure.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;
use core::sync::atomic::{AtomicU32, Ordering};

use embassy_executor::Spawner;
use embassy_futures::join::{join, join4};
use embassy_futures::select::{Either, select};
use embassy_time::{Duration, Timer};
use panic_halt as _;
use pic32c_hal::dma::{self, Request, Transfer, Word};
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::{Peri, peripherals};
use pic32cm_sg00_curiosity_pro::{Log, micros};
use static_cell::ConstStaticCell;

pic32cm_sg00_curiosity_pro::boot!();

/// 100 µs ticks taken by the ticker task.
static TICKS: AtomicU32 = AtomicU32::new(0);

/// SERCOM4's DATA register, where the log goes.
const SERCOM4_DATA: usize = 0x4482_0000 + 0x28;

/// Words in the big buffers: 16 KiB each.
const WORDS: usize = 4096;

/// A pattern in flash.
static PATTERN: [u8; 4096] = {
    let mut p = [0; 4096];
    let mut i = 0;
    while i < p.len() {
        #[expect(clippy::cast_possible_truncation, reason = "the low byte")]
        let b = (i * 31 + 7) as u8;
        p[i] = b;
        i += 1;
    }
    p
};

/// Buffers in SRAM, word-aligned (`u8` views of `u32`s).
static SOURCE: ConstStaticCell<[u32; WORDS]> = ConstStaticCell::new([0; WORDS]);
static DESTINATION: ConstStaticCell<[u32; WORDS]> = ConstStaticCell::new([0; WORDS]);
static SECOND: ConstStaticCell<[u32; 1024]> = ConstStaticCell::new([0; 1024]);

async fn ticker() -> ! {
    loop {
        Timer::after(Duration::from_micros(100)).await;
        TICKS.fetch_add(1, Ordering::Relaxed);
    }
}

/// The channels the tests use.
#[expect(non_snake_case, reason = "named as the peripherals")]
#[expect(clippy::struct_field_names, reason = "named as the peripherals")]
struct Channels {
    DMA_CH0: Peri<'static, peripherals::DMA_CH0>,
    DMA_CH1: Peri<'static, peripherals::DMA_CH1>,
    DMA_CH2: Peri<'static, peripherals::DMA_CH2>,
    DMA_CH3: Peri<'static, peripherals::DMA_CH3>,
    DMA_CH4: Peri<'static, peripherals::DMA_CH4>,
    DMA_CH5: Peri<'static, peripherals::DMA_CH5>,
    DMA_CH6: Peri<'static, peripherals::DMA_CH6>,
    DMA_CH7: Peri<'static, peripherals::DMA_CH7>,
}

struct Tests<'a> {
    log: &'a mut Log,
    failures: u32,
}

impl Tests<'_> {
    fn check(&mut self, name: &str, good: bool, detail: core::fmt::Arguments<'_>) {
        let _ = writeln!(self.log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        self.failures += u32::from(!good);
    }
}

/// Copies `source` into `destination` by DMA, returning the result, the
/// microseconds it took and the ticker's ticks meanwhile.
async fn timed_copy<W: Word>(channel: Peri<'_, impl dma::Channel>, source: &[W], destination: &mut [W]) -> (Result<(), dma::Error>, u64, u32) {
    let ticks = TICKS.load(Ordering::Relaxed);
    let start = micros();
    let result = Transfer::new_copy(channel, source, destination).await;
    (result, micros() - start, TICKS.load(Ordering::Relaxed) - ticks)
}

#[expect(clippy::too_many_lines, reason = "one test after another")]
async fn tests(p: &mut Channels, t: &mut Tests<'_>) {
    let (source, destination, second) = (SOURCE.take(), DESTINATION.take(), SECOND.take());
    for (i, w) in source.iter_mut().enumerate() {
        #[expect(clippy::cast_possible_truncation, reason = "a pattern")]
        let v = (i as u32).wrapping_mul(0x9E37_79B9);
        *w = v;
    }
    let source_bytes: &[u8] = bytemuck(source);

    // Bytes of awkward lengths and offsets, SRAM to SRAM.
    for (offset, length) in [(0, 1), (1, 3), (3, 1023), (1, 1024), (2, 1025), (0, 4096), (0, 4097)] {
        destination.fill(0);
        let destination_bytes = bytemuck_mut(destination);
        let (result, us, _) = timed_copy(p.DMA_CH0.reborrow(), &source_bytes[offset..offset + length], &mut destination_bytes[offset + 1..offset + 1 + length]).await;
        let good = result.is_ok() && destination_bytes[offset + 1..offset + 1 + length] == source_bytes[offset..offset + length] && destination_bytes[offset] == 0 && destination_bytes[offset + 1 + length] == 0;
        t.check("bytes", good, format_args!("{length} from +{offset} to +{} in {us} us ({result:?})", offset + 1));
    }

    // Halfwords, on halfword but not word boundaries, and words.
    {
        let halves: &[u16] = bytemuck(&source[..512]);
        destination.fill(0);
        let out: &mut [u16] = bytemuck_mut(&mut destination[..512]);
        let (result, us, _) = timed_copy(p.DMA_CH1.reborrow(), &halves[1..1000], &mut out[1..1000]).await;
        t.check("halfwords", result.is_ok() && out[1..1000] == halves[1..1000] && out[0] == 0 && out[1000] == 0, format_args!("999 in {us} us ({result:?})"));
    }
    destination.fill(0);
    let (result, us, ticks) = timed_copy(p.DMA_CH2.reborrow(), &source[..], &mut destination[..]).await;
    let dma_us = us;
    let bytes = WORDS * 4;
    t.check(
        "16 KiB of words",
        result.is_ok() && destination[..] == source[..],
        format_args!("in {us} us, {} MB/s, ticker ran {ticks} times ({result:?})", bytes as u64 / us.max(1)),
    );
    // The CPU's copy, for comparison.
    destination.fill(0);
    let start = micros();
    destination.copy_from_slice(source);
    let cpu_us = micros() - start;
    t.check("CPU copy of 16 KiB", destination[..] == source[..], format_args!("in {cpu_us} us (DMA {dma_us} us)"));

    // From flash.
    destination.fill(0);
    let out = &mut bytemuck_mut(destination)[..PATTERN.len()];
    let (result, us, _) = timed_copy(p.DMA_CH3.reborrow(), &PATTERN, out).await;
    t.check("flash to SRAM", result.is_ok() && out[..] == PATTERN[..], format_args!("4 KiB in {us} us ({result:?})"));

    // All eight channels at once: a 512-word slice each, 4 to 7 on the
    // shared vector.
    destination.fill(0);
    {
        let (to, _) = destination.as_chunks_mut::<512>();
        let (from, _) = source.as_chunks::<512>();
        let [to0, to1, to2, to3, to4, to5, to6, to7, ..] = to else { unreachable!("16 KiB is 8 slices") };
        let (first, second) = join(
            join4(
                Transfer::new_copy(p.DMA_CH0.reborrow(), &from[0][..], &mut to0[..]),
                Transfer::new_copy(p.DMA_CH1.reborrow(), &from[1][..], &mut to1[..]),
                Transfer::new_copy(p.DMA_CH2.reborrow(), &from[2][..], &mut to2[..]),
                Transfer::new_copy(p.DMA_CH3.reborrow(), &from[3][..], &mut to3[..]),
            ),
            join4(
                Transfer::new_copy(p.DMA_CH4.reborrow(), &from[4][..], &mut to4[..]),
                Transfer::new_copy(p.DMA_CH5.reborrow(), &from[5][..], &mut to5[..]),
                Transfer::new_copy(p.DMA_CH6.reborrow(), &from[6][..], &mut to6[..]),
                Transfer::new_copy(p.DMA_CH7.reborrow(), &from[7][..], &mut to7[..]),
            ),
        )
        .await;
        let all = [first.0, first.1, first.2, first.3, second.0, second.1, second.2, second.3];
        let good = all.iter().all(Result::is_ok) && destination[..512 * 8] == source[..512 * 8];
        t.check("eight channels", good, format_args!("2 KiB each ({all:?})"));
    }

    // A copy dropped part way: the channel must stop, and work again.
    destination.fill(0);
    let dropped = {
        let transfer = Transfer::new_copy(p.DMA_CH4.reborrow(), &source[..], &mut destination[..]);
        // A few microseconds into 16 KiB.
        let deadline = micros() + 20;
        while micros() < deadline {}
        let running = transfer.is_running();
        let remaining = transfer.remaining();
        drop(transfer);
        (running, remaining)
    };
    let copied = destination.iter().zip(source.iter()).take_while(|(d, s)| d == s).count();
    let untouched = destination[copied..].iter().all(|&w| w == 0);
    t.check(
        "dropped part way",
        dropped.0 && untouched && copied < source.len() && dropped.1 > 0 && dropped.1 < bytes,
        format_args!("running {}, {} bytes left, {} words copied, rest untouched {untouched}", dropped.0, dropped.1, copied),
    );
    destination.fill(0);
    let (result, _, _) = timed_copy(p.DMA_CH4.reborrow(), &source[..256], &mut destination[..256]).await;
    t.check("the same channel again", result.is_ok() && destination[..256] == source[..256], format_args!("({result:?})"));

    // A transfer before its first request: all to move, and dropped,
    // nothing moved.
    second.fill(0);
    {
        // SAFETY: SERCOM4's DATA; but RX requests never come with nothing
        // sent to the board, so this never moves a byte.
        let transfer = unsafe { Transfer::new_read(p.DMA_CH5.reborrow(), Request::sercom_rx(4), SERCOM4_DATA as *const u8, &mut bytemuck_mut(second)[..16]) };
        let remaining = transfer.remaining();
        let outcome = select(transfer, Timer::after(Duration::from_millis(5))).await;
        t.check(
            "a read with no data",
            matches!(outcome, Either::Second(())) && remaining == 16 && second.iter().all(|&w| w == 0),
            format_args!("{remaining} bytes to move, timed out, nothing written"),
        );
    }

    // The VCOM, written by DMA, paced by SERCOM4's transmit request.
    t.log.flush();
    let message = b"dma: this line went out by DMA, paced by SERCOM4\r\n";
    let start = micros();
    // SAFETY: SERCOM4's DATA, which takes a byte per transmit request; the
    // log is idle meanwhile (flushed, and nothing else writes to it).
    let result = unsafe { Transfer::new_write(p.DMA_CH6.reborrow(), Request::sercom_tx(4), message, SERCOM4_DATA as *mut u8) }.await;
    let us = micros() - start;
    t.log.flush();
    // 50 bytes at 115,200 baud is 4.3 ms, less the 17 the 16-byte FIFO and
    // the shift register take at once, 2.9 ms: anything much faster wasn't
    // paced.
    t.check("UART TX by DMA", result.is_ok() && us > 2_500, format_args!("{} bytes in {us} us ({result:?})", message.len()));
}

/// A slice of `u32`s as the smaller words in it.
fn bytemuck<W: Word>(words: &[u32]) -> &[W] {
    // SAFETY: u8 and u16 have weaker alignment than u32 and no invalid bit
    // patterns; the length is in bytes divided by the word's size.
    unsafe { core::slice::from_raw_parts(words.as_ptr().cast(), core::mem::size_of_val(words) / size_of::<W>()) }
}

fn bytemuck_mut<W: Word>(words: &mut [u32]) -> &mut [W] {
    // SAFETY: as `bytemuck`.
    unsafe { core::slice::from_raw_parts_mut(words.as_mut_ptr().cast(), core::mem::size_of_val(words) / size_of::<W>()) }
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32cm_sg00_curiosity_pro::init();
    let mut log = Log::init(p.SERCOM4, p.PD19, p.PD20);
    let mut led = Output::new(p.PA20, Level::High);
    let mut channels = Channels {
        DMA_CH0: p.DMA_CH0,
        DMA_CH1: p.DMA_CH1,
        DMA_CH2: p.DMA_CH2,
        DMA_CH3: p.DMA_CH3,
        DMA_CH4: p.DMA_CH4,
        DMA_CH5: p.DMA_CH5,
        DMA_CH6: p.DMA_CH6,
        DMA_CH7: p.DMA_CH7,
    };
    let _ = writeln!(log, "\npic32cm-sg00-curiosity-pro dma");

    let mut t = Tests { log: &mut log, failures: 0 };
    match select(tests(&mut channels, &mut t), ticker()).await {
        Either::First(()) | Either::Second(_) => {}
    }
    let failures = t.failures;
    let _ = if failures == 0 { writeln!(log, "dma: all passed") } else { writeln!(log, "dma: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
