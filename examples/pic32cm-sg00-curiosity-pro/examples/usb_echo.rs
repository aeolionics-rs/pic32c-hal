//! `pic32c-hal`'s `usb` with embassy-usb on the SG00: a CDC-ACM serial
//! port on the board's target USB connector (the Micro-AB, D+ PD03, D-
//! PD02) that echoes everything it receives. The 48 MHz USB clock is
//! generator 3, from the 12 MHz crystal through PLL0. Progress goes out over
//! the virtual COM port; `tools/host/cdc_echo_test.py` drives the echo.

#![no_std]
#![no_main]
// Embassy's main macro passes `_spawner` on to the task it generates, where
// an attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;

use embassy_executor::Spawner;
use embassy_usb::class::cdc_acm::device::{self as cdc_acm, CdcAcmClass, State};
use embassy_usb::driver::EndpointError;
use embassy_usb::{Builder, Config};
use panic_halt as _;
use pic32c_hal::{bind_interrupts, usb};
use pic32cm_sg00_curiosity_pro::{GEN_48, Log};

pic32cm_sg00_curiosity_pro::boot!();

bind_interrupts!(struct Irqs {
    USB_EORSMDNRSM => usb::InterruptHandler;
    USB_SOFHSOF => usb::InterruptHandler;
    USB_TRCPT00 => usb::InterruptHandler;
    USB_TRCPT10 => usb::InterruptHandler;
});

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let peripherals = pic32cm_sg00_curiosity_pro::init();
    let mut log = Log::init(peripherals.SERCOM4, peripherals.PD19, peripherals.PD20);
    let _ = writeln!(log, "\npic32cm-sg00-curiosity-pro usb_echo: CPU {} Hz", pic32c_hal::clocks::generator_hz(0).unwrap_or(0));
    let driver = usb::Driver::new(peripherals.USB, Irqs, peripherals.PD03, peripherals.PD02, GEN_48);
    // A test VID/PID (pid.codes' test range).
    let mut config = Config::new(0x1209, 0x000A);
    config.manufacturer = Some("Aeolionics");
    config.product = Some("PIC32CM SG00 USB echo");
    config.serial_number = Some("pic32cm-sg00-curiosity-pro");
    config.max_power = 100;
    config.max_packet_size_0 = 64;

    let mut config_descriptor = [0; 256];
    let mut bos_descriptor = [0; 256];
    let mut control_buf = [0; 64];
    let mut state = State::new();
    let mut builder = Builder::new(driver, config, &mut config_descriptor, &mut bos_descriptor, &mut [], &mut control_buf);
    let mut class = CdcAcmClass::new(&mut builder, &mut state, cdc_acm::Config::new());
    let mut usb = builder.build();
    let _ = writeln!(log, "USB device built; attaching");

    let echo = async {
        loop {
            class.wait_connection().await;
            let _ = writeln!(log, "connected");
            let mut echoed = 0usize;
            let mut buf = [0; 64];
            loop {
                match class.read_packet(&mut buf).await {
                    Ok(n) => {
                        if class.write_packet(&buf[..n]).await.is_err() {
                            break;
                        }
                        echoed += n;
                    }
                    Err(EndpointError::BufferOverflow) => {}
                    Err(_) => break,
                }
            }
            let _ = writeln!(log, "disconnected after echoing {echoed} bytes");
        }
    };
    embassy_futures::join::join(usb.run(), echo).await;
}
