//! `pic32c-hal`'s `spi` on the mikroBUS socket's pins (SERCOM2: SCK PC18,
//! MOSI PC19, MISO PC16), with nothing in the socket, so in loopback: the
//! receiver reads the MOSI pad, through the pin. Blocking, then by DMA:
//! rates from 1 to 24 MHz, the four modes and LSB first, transfers of
//! unequal lengths and in place, reads and writes alone, timed, with a
//! ticker task counting meanwhile; then a full-duplex SPI with MISO on PC16,
//! which reads whatever the empty socket gives. Over the virtual COM port;
//! LED0 blinks slowly when all passed, fast on a failure.

#![no_std]
#![no_main]
// Embassy's macros pass `_spawner` on to the task they generate, where an
// attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;
use core::sync::atomic::{AtomicU32, Ordering};

use embassy_executor::Spawner;
use embassy_futures::select::{Either, select};
use embassy_time::{Duration, Timer};
use embedded_hal::spi::{MODE_0, MODE_1, MODE_2, MODE_3};
use panic_halt as _;
use pic32c_hal::gpio::{Level, Output};
use pic32c_hal::spi::{BitOrder, Config, Spi};
use pic32c_hal::{Peri, peripherals};
use pic32cm_sg00_curiosity_pro::{Log, micros};

pic32cm_sg00_curiosity_pro::boot!();

/// 100 µs ticks taken by the ticker task.
static TICKS: AtomicU32 = AtomicU32::new(0);

async fn ticker() -> ! {
    loop {
        Timer::after(Duration::from_micros(100)).await;
        TICKS.fetch_add(1, Ordering::Relaxed);
    }
}

#[expect(non_snake_case, reason = "named as the peripherals")]
struct Parts {
    SERCOM2: Peri<'static, peripherals::SERCOM2>,
    PC19: Peri<'static, peripherals::PC19>,
    PC18: Peri<'static, peripherals::PC18>,
    PC16: Peri<'static, peripherals::PC16>,
    DMA_CH0: Peri<'static, peripherals::DMA_CH0>,
    DMA_CH1: Peri<'static, peripherals::DMA_CH1>,
}

struct Tests<'a> {
    log: &'a mut Log,
    failures: u32,
}

impl Tests<'_> {
    fn check(&mut self, name: &str, good: bool, detail: core::fmt::Arguments<'_>) {
        let _ = writeln!(self.log, "{name}: {} {detail}", if good { "ok" } else { "FAILED" });
        self.failures += u32::from(!good);
    }
}

fn pattern(buffer: &mut [u8], seed: u8) {
    for (i, b) in buffer.iter_mut().enumerate() {
        #[expect(clippy::cast_possible_truncation, reason = "a pattern")]
        let v = (i as u8).wrapping_mul(37).wrapping_add(seed);
        *b = v;
    }
}

fn config(frequency: u32) -> Config {
    let mut config = Config::default();
    config.frequency = frequency;
    config.loopback = true;
    config
}

async fn tests(p: &mut Parts, t: &mut Tests<'_>) {
    let mut out = [0u8; 4096];
    let mut back = [0u8; 4096];
    pattern(&mut out, 5);

    // Blocking, at several rates.
    for frequency in [1_000_000, 6_000_000, 12_000_000, 24_000_000] {
        let mut spi = Spi::new_blocking_txonly(p.SERCOM2.reborrow(), p.PC18.reborrow(), p.PC19.reborrow(), config(frequency)).unwrap();
        back.fill(0);
        let start = micros();
        let result = spi.blocking_transfer(&mut back[..256], &out[..256]);
        let us = micros() - start;
        t.check("blocking", result.is_ok() && back[..256] == out[..256], format_args!("256 bytes at {} Hz in {us} us ({result:?})", spi.frequency()));
    }

    // The four modes and LSB first: one bus, moved between them by
    // `set_config`.
    let mut spi = Spi::new_blocking_txonly(p.SERCOM2.reborrow(), p.PC18.reborrow(), p.PC19.reborrow(), config(1_000_000)).unwrap();
    for (name, mode) in [("mode 0", MODE_0), ("mode 1", MODE_1), ("mode 2", MODE_2), ("mode 3", MODE_3)] {
        for bit_order in [BitOrder::MsbFirst, BitOrder::LsbFirst] {
            let mut config = config(4_000_000);
            config.mode = mode;
            config.bit_order = bit_order;
            spi.set_config(&config).unwrap();
            back.fill(0);
            let result = spi.blocking_transfer(&mut back[..64], &out[..64]);
            t.check(name, result.is_ok() && back[..64] == out[..64], format_args!("{bit_order:?} at {} Hz ({result:?})", spi.frequency()));
        }
    }
    drop(spi);

    // Unequal lengths and in place, blocking.
    {
        let mut spi = Spi::new_blocking_txonly(p.SERCOM2.reborrow(), p.PC18.reborrow(), p.PC19.reborrow(), config(12_000_000)).unwrap();
        back.fill(0xEE);
        let result = spi.blocking_transfer(&mut back[..40], &out[..32]);
        t.check(
            "blocking, read longer",
            result.is_ok() && back[..32] == out[..32] && back[32..40].iter().all(|&b| b == 0) && back[40] == 0xEE,
            format_args!("({result:?})"),
        );
        let mut words = [0u8; 100];
        pattern(&mut words, 9);
        let sent = words;
        let result = spi.blocking_transfer_in_place(&mut words);
        t.check("blocking, in place", result.is_ok() && words == sent, format_args!("({result:?})"));
    }

    // By DMA.
    {
        let mut spi = Spi::new_txonly(p.SERCOM2.reborrow(), p.PC18.reborrow(), p.PC19.reborrow(), p.DMA_CH0.reborrow(), p.DMA_CH1.reborrow(), config(24_000_000)).unwrap();
        back.fill(0);
        let ticks = TICKS.load(Ordering::Relaxed);
        let start = micros();
        let result = spi.transfer(&mut back, &out).await;
        let us = micros() - start;
        let ticks = TICKS.load(Ordering::Relaxed) - ticks;
        t.check(
            "DMA transfer",
            result.is_ok() && back == out,
            format_args!("4 KiB at {} Hz in {us} us ({} kB/s), ticker ran {ticks} times ({result:?})", spi.frequency(), 4096 * 1000 / us.max(1)),
        );

        back.fill(0xEE);
        let result = spi.transfer(&mut back[..300], &out[..200]).await;
        t.check(
            "DMA, read longer",
            result.is_ok() && back[..200] == out[..200] && back[200..300].iter().all(|&b| b == 0) && back[300] == 0xEE,
            format_args!("({result:?})"),
        );
        back.fill(0xEE);
        let result = spi.transfer(&mut back[..100], &out[..300]).await;
        t.check("DMA, write longer", result.is_ok() && back[..100] == out[..100] && back[100] == 0xEE, format_args!("({result:?})"));

        back.fill(0xEE);
        let result = spi.read(&mut back[..64]).await;
        t.check("DMA read alone", result.is_ok() && back[..64].iter().all(|&b| b == 0), format_args!("zeros sent and read back ({result:?})"));
        let result = spi.write(&out[..1000]).await;
        t.check("DMA write alone", result.is_ok(), format_args!("({result:?})"));

        let mut words = [0u8; 200];
        pattern(&mut words, 77);
        let sent = words;
        let result = spi.transfer_in_place(&mut words).await;
        t.check("DMA in place", result.is_ok() && words == sent, format_args!("200 bytes ({result:?})"));

        // The blocking calls work on the DMA one too.
        back.fill(0);
        let result = spi.blocking_transfer(&mut back[..16], &out[..16]);
        t.check("blocking on the DMA SPI", result.is_ok() && back[..16] == out[..16], format_args!("({result:?})"));
    }

    // Full duplex with MISO on PC16, the empty socket's: it runs, whatever
    // it reads.
    {
        let mut config = Config::default();
        config.frequency = 12_000_000;
        let mut spi = Spi::new(p.SERCOM2.reborrow(), p.PC18.reborrow(), p.PC19.reborrow(), p.PC16.reborrow(), p.DMA_CH0.reborrow(), p.DMA_CH1.reborrow(), config).unwrap();
        let result = spi.transfer(&mut back[..512], &out[..512]).await;
        let ones = back[..512].iter().fold(0, |n, &b| n + usize::from(b == 0xFF));
        t.check("full duplex, MISO on PC16", result.is_ok(), format_args!("{ones} of 512 bytes read 0xFF ({result:?})"));
    }
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = pic32cm_sg00_curiosity_pro::init();
    let mut log = Log::init(p.SERCOM4, p.PD19, p.PD20);
    let mut led = Output::new(p.PA20, Level::High);
    let _ = writeln!(log, "\npic32cm-sg00-curiosity-pro spi");
    let mut parts = Parts {
        SERCOM2: p.SERCOM2,
        PC19: p.PC19,
        PC18: p.PC18,
        PC16: p.PC16,
        DMA_CH0: p.DMA_CH0,
        DMA_CH1: p.DMA_CH1,
    };

    let mut t = Tests { log: &mut log, failures: 0 };
    match select(tests(&mut parts, &mut t), ticker()).await {
        Either::First(()) | Either::Second(_) => {}
    }
    let failures = t.failures;
    let _ = if failures == 0 { writeln!(log, "spi: all passed") } else { writeln!(log, "spi: {failures} failures") };
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
