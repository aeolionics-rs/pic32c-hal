//! `pic32c-hal`'s `exti` under test on the SG00, with nothing wired:
//! - the pull while the EIC has the pin: the mikroBUS AN pin (PA07,
//!   EXTINT7) floats with the socket empty, so PORT reads it high with the
//!   pull-up and low with the pull-down if the pull holds (the EIC's
//!   PINSTATE is printed too);
//! - if it does, flipping the pull's direction (PORT's OUT, written here
//!   behind the driver's back) makes real edges on PA07: each wait (rising,
//!   falling, any edge, high, low) must end soon after the flip that meets
//!   it, and not before; the latency from the flip to the wake is printed;
//! - SW0 (PB07, EXTINT8, the pull-up on), released: `wait_for_high` ends at
//!   once, `wait_for_low` not within 200 ms;
//! - then SW0 pressed within 10 s, if anyone's there (not a failure).
//!
//! Results go out over the virtual COM port; LED0 blinks slowly when all
//! passed, fast on a failure.

#![no_std]
#![no_main]
// Embassy's main macro passes `_spawner` on to the task it generates, where
// an attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::fmt::Write;
use core::future::Future;

use embassy_executor::Spawner;
use embassy_futures::select::{Either, select};
use embassy_time::{Duration, Timer, with_timeout};
use panic_halt as _;
use pic32c_hal::exti::ExtiInput;
use pic32c_hal::gpio::{Level, Output, Pull};
use pic32c_hal::pac;
use pic32cm_sg00_curiosity_pro::{Log, micros};

pic32cm_sg00_curiosity_pro::boot!();

/// PA07: port group A, bit 7.
const PA07: u32 = 1 << 7;
/// Long enough for a pull to move the floating pin.
const SETTLE: Duration = Duration::from_micros(200);

/// PORT's group A (its one view on the SG00), to flip PA07's pull
/// direction.
fn port_a() -> &'static pac::port::Group {
    // SAFETY: PORT's register block; only PA07's OUT bit is written here.
    unsafe { (*pac::Port::ptr()).group(0) }
}

fn pull_up() {
    // SAFETY: PA07's OUT bit, which picks its pull's direction.
    port_a().outset().write(|w| unsafe { w.bits(PA07) });
}

fn pull_down() {
    // SAFETY: as for `pull_up`.
    port_a().outclr().write(|w| unsafe { w.bits(PA07) });
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let mut p = pic32cm_sg00_curiosity_pro::init();
    let mut log = Log::init(p.SERCOM4, p.PD19, p.PD20);
    let led0 = Output::new(p.PA20, Level::High);
    let _ = writeln!(log, "\npic32cm-sg00-curiosity-pro exti");
    let mut failures = 0;

    // The pull, with the EIC holding the pin.
    let mut held = true;
    for pull in [Pull::Up, Pull::Down] {
        let pin = ExtiInput::new(p.PA07.reborrow(), p.EXTINT7.reborrow(), pull);
        Timer::after(SETTLE).await;
        let (port, eic) = (pin.get_level(), pin.eic_level());
        let expected = if pull == Pull::Up { Level::High } else { Level::Low };
        let good = port == expected;
        held &= good;
        let _ = writeln!(log, "PA07 under the EIC, pull {pull:?}: PORT {port:?} (EIC PINSTATE {eic:?}){}", if good { "" } else { " (the pull doesn't hold)" });
    }

    if held {
        let mut pin = ExtiInput::new(p.PA07.reborrow(), p.EXTINT7.reborrow(), Pull::Down);
        Timer::after(SETTLE).await;
        failures += edge(&mut log, "rising edge", pin.wait_for_rising_edge(), pull_up).await;
        failures += edge(&mut log, "falling edge", pin.wait_for_falling_edge(), pull_down).await;
        failures += edge(&mut log, "any edge (rising)", pin.wait_for_any_edge(), pull_up).await;
        failures += edge(&mut log, "any edge (falling)", pin.wait_for_any_edge(), pull_down).await;
        failures += edge(&mut log, "high", pin.wait_for_high(), pull_up).await;
        failures += edge(&mut log, "low", pin.wait_for_low(), pull_down).await;
        // Already there: a level wait ends at once.
        let immediate = with_timeout(Duration::from_millis(10), pin.wait_for_low()).await.is_ok();
        let _ = writeln!(log, "low while low: {}", if immediate { "at once" } else { "NOT at once" });
        failures += u32::from(!immediate);
        // A hundred edges back to back, each awaited.
        let mut missed = 0;
        for n in 0..100 {
            let caught = if n % 2 == 0 {
                caught(pin.wait_for_rising_edge(), pull_up).await
            } else {
                caught(pin.wait_for_falling_edge(), pull_down).await
            };
            missed += u32::from(!caught);
        }
        let _ = writeln!(log, "100 alternate edges: {missed} missed");
        failures += u32::from(missed != 0);
    } else {
        let _ = writeln!(log, "the pull doesn't hold while the EIC has a pin: no edges to make without wiring");
        failures += 1;
    }

    // SW0, released.
    let mut sw0 = ExtiInput::new(p.PB07, p.EXTINT8, Pull::Up);
    let high = with_timeout(Duration::from_millis(10), sw0.wait_for_high()).await.is_ok();
    let low = with_timeout(Duration::from_millis(200), sw0.wait_for_low()).await.is_ok();
    let _ = writeln!(
        log,
        "SW0 released: wait_for_high {}, wait_for_low {}",
        if high { "at once" } else { "NOT at once" },
        if low { "ENDED (pressed?)" } else { "still waiting after 200 ms" }
    );
    failures += u32::from(!high || low);

    let _ = writeln!(log, "press SW0 within 10 s");
    match with_timeout(Duration::from_secs(10), sw0.wait_for_falling_edge()).await {
        Ok(()) => {
            let pressed = micros();
            let released = with_timeout(Duration::from_secs(10), sw0.wait_for_rising_edge()).await.is_ok();
            let _ = writeln!(log, "SW0 pressed, {}", if released { "released after" } else { "not released within 10 s of" });
            let _ = writeln!(log, "  {} ms", (micros() - pressed) / 1000);
        }
        Err(_) => {
            let _ = writeln!(log, "SW0 not pressed (not a failure)");
        }
    }

    if failures == 0 {
        let _ = writeln!(log, "exti: all passed");
    } else {
        let _ = writeln!(log, "exti: {failures} failures");
    }
    halt(&mut log, failures, led0).await;
}

/// `wait` mustn't end before `flip`, and must end within 10 ms after.
async fn edge(log: &mut Log, name: &str, wait: impl Future<Output = ()>, flip: fn()) -> u32 {
    let mut flipped_at = 0;
    let flipper = async {
        Timer::after(Duration::from_millis(5)).await;
        flipped_at = micros();
        flip();
        Timer::after(Duration::from_millis(10)).await;
    };
    match select(wait, flipper).await {
        Either::First(()) if flipped_at != 0 => {
            let latency = micros() - flipped_at;
            let _ = writeln!(log, "{name}: woke {latency} µs after the flip");
            0
        }
        Either::First(()) => {
            let _ = writeln!(log, "{name}: woke BEFORE the flip");
            1
        }
        Either::Second(()) => {
            let _ = writeln!(log, "{name}: NOT woken within 10 ms of the flip");
            1
        }
    }
}

/// Whether `wait` ends within 20 ms of `flip`, 100 µs in.
async fn caught(wait: impl Future<Output = ()>, flip: fn()) -> bool {
    let flipped = async {
        Timer::after(Duration::from_micros(100)).await;
        flip();
        Timer::after(Duration::from_millis(20)).await;
    };
    matches!(select(wait, flipped).await, Either::First(()))
}

async fn halt(log: &mut Log, failures: u32, mut led: Output<'static>) -> ! {
    log.flush();
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after(Duration::from_millis(period)).await;
    }
}
